function StateDot = AircraftDynamics6DOF(State, Controls, Environment, Aircraft)
% AIRCRAFTDYNAMICS6DOF
% Top-level rigid-body 6-DOF aircraft dynamics model.
%
% Computes the complete aircraft state derivative by coordinating all
% translational, rotational and kinematic models.
%
% Project
%   Adaptive Flight State Reconstruction and Trajectory Estimation
%
% MATLAB Version
%   R2024b
%
% INPUTS
%   State
%       Aircraft state structure
%
%   Controls
%       Aircraft control structure
%
%   Environment
%       Environment structure
%
%   Aircraft
%       config.AircraftConfig object or compatible structure
%
% OUTPUT
%   StateDot
%       Complete aircraft state derivative structure.
%

    narginchk(4,4);

    StateDot = runAircraftDynamics6DOF( ...
        State,...
        Controls,...
        Environment,...
        Aircraft);

end

% =========================================================================
%% CORE EXECUTION PIPELINE
% =========================================================================

function StateDot = runAircraftDynamics6DOF( ...
    State,...
    Controls,...
    Environment,...
    Aircraft)

    %% Validate Inputs

    validateAircraftDynamicsInputs( ...
        State,...
        Controls,...
        Environment,...
        Aircraft);

    %% Initialize Output

    StateDot = initializeAircraftDynamicsOutput();

    %% Compute Complete State Derivatives

    Derivatives = dynamics.StateDerivatives( ...
        State,...
        Controls,...
        Environment,...
        Aircraft);

    %% Populate Outputs

    StateDot = Derivatives;

    %% Validate Outputs

    validateAircraftDynamicsOutput(StateDot);

end

% =========================================================================
%% INITIALIZATION
% =========================================================================

function StateDot = initializeAircraftDynamicsOutput()

    StateDot = struct();

    StateDot.VelocityBody = zeros(3,1);

    StateDot.AngularRatesBody = zeros(3,1);

    StateDot.PositionNED = zeros(3,1);

    StateDot.Quaternion = zeros(4,1);

    StateDot.Translation = struct();

    StateDot.Rotation = struct();

end
% =========================================================================
%% INPUT VALIDATION
% =========================================================================

function validateAircraftDynamicsInputs( ...
    State,...
    Controls,...
    Environment,...
    Aircraft)

    %% State

    if ~isstruct(State)

        error( ...
            'AircraftDynamics6DOF:InvalidState', ...
            'State must be a structure.');

    end

    requiredState = { ...
        'VelocityBody',...
        'AngularRatesBody',...
        'EulerAngles'};

    for k = 1:numel(requiredState)

        if ~isfield(State,requiredState{k})

            error( ...
                'AircraftDynamics6DOF:MissingStateField', ...
                'Missing State.%s.', ...
                requiredState{k});

        end

    end

    %% Controls

    if ~isstruct(Controls)

        error( ...
            'AircraftDynamics6DOF:InvalidControls', ...
            'Controls must be a structure.');

    end

    %% Environment

    if ~isstruct(Environment)

        error( ...
            'AircraftDynamics6DOF:InvalidEnvironment', ...
            'Environment must be a structure.');

    end

    %% Aircraft

    if ~(isa(Aircraft,'config.AircraftConfig') || isstruct(Aircraft))

        error( ...
            'AircraftDynamics6DOF:InvalidAircraft', ...
            'Aircraft must be config.AircraftConfig or a compatible structure.');

    end

    %% Numerical Validation

    validateattributes( ...
        State.VelocityBody,...
        {'numeric'},...
        {'real','finite','size',[3 1]},...
        mfilename,...
        'VelocityBody');

    validateattributes( ...
        State.AngularRatesBody,...
        {'numeric'},...
        {'real','finite','size',[3 1]},...
        mfilename,...
        'AngularRatesBody');

    validateattributes( ...
        State.EulerAngles,...
        {'numeric'},...
        {'real','finite','size',[3 1]},...
        mfilename,...
        'EulerAngles');

end

% =========================================================================
%% OUTPUT VALIDATION
% =========================================================================

function validateAircraftDynamicsOutput(StateDot)

    requiredFields = { ...
        'VelocityBody',...
        'AngularRatesBody',...
        'PositionNED',...
        'Quaternion',...
        'Translation',...
        'Rotation'};

    for k = 1:numel(requiredFields)

        if ~isfield(StateDot,requiredFields{k})

            error( ...
                'AircraftDynamics6DOF:MissingOutputField', ...
                'Missing StateDot.%s.', ...
                requiredFields{k});

        end

    end

    validateattributes( ...
        StateDot.VelocityBody,...
        {'numeric'},...
        {'real','finite','size',[3 1]},...
        mfilename,...
        'VelocityBody');

    validateattributes( ...
        StateDot.AngularRatesBody,...
        {'numeric'},...
        {'real','finite','size',[3 1]},...
        mfilename,...
        'AngularRatesBody');

    validateattributes( ...
        StateDot.PositionNED,...
        {'numeric'},...
        {'real','finite','size',[3 1]},...
        mfilename,...
        'PositionNED');

    validateattributes( ...
        StateDot.Quaternion,...
        {'numeric'},...
        {'real','finite','numel',4},...
        mfilename,...
        'Quaternion');

    if ~isstruct(StateDot.Translation)

        error( ...
            'AircraftDynamics6DOF:InvalidTranslation', ...
            'StateDot.Translation must be a structure.');

    end

    if ~isstruct(StateDot.Rotation)

        error( ...
            'AircraftDynamics6DOF:InvalidRotation', ...
            'StateDot.Rotation must be a structure.');

    end

end
