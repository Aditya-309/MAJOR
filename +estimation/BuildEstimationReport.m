function Report = BuildEstimationReport(RunID, PreprocessID, EstimationID, Config, InputInfo, InitInfo, Timeline, NoiseModels, ForwardEKF, ForwardUKF, SmoothingEKF, SmoothingUKF, Diagnostics, Evaluation, Comparison, ProcessingInfo)
%BUILDESTIMATIONREPORT Assemble the EstimationReport structure.
%
%   Report = BUILDESTIMATIONREPORT(...) builds the JSON-publishable
%   estimation report: identity, exact input contract, model assumptions,
%   initialization and noise provenance, filter and smoothing details,
%   diagnostic summaries, evaluation summaries, processing information
%   and the acceptance-gate evidence fields. Numerical detail lives in
%   EstimationResults.mat and the Review CSVs; this report is the
%   human-readable, machine-checkable summary.
%
%   INTERNAL function. Not part of the public Block 10 API.
%
%   See also: ExportEstimationResults, GetEstimationReport.

    Report = struct();
    Report.SchemaVersion = '1.0';

    Report.RunInfo = struct( ...
        'RunID', RunID, ...
        'PreprocessID', PreprocessID, ...
        'EstimationID', EstimationID, ...
        'RunDirectory', InputInfo.ReportRunInfo.RunDirectory, ...
        'PreprocessedDirectory', InputInfo.PreprocessedDirectory, ...
        'Status', 'SUCCESS');

    Report.Environment = ProcessingInfo.Environment;

    Report.InputContract = struct( ...
        'MatFile', InputInfo.MatFile, ...
        'MatVariable', InputInfo.MatVariable, ...
        'ReportFile', InputInfo.ReportFile, ...
        'Streams', fieldnames(Timeline.Streams), ...
        'TimelineEventCount', Timeline.TotalEvents, ...
        'TimelineStreams', Timeline.Streams, ...
        'PreInitializationEvents', InitInfo.PreInitializationEventCount, ...
        'ProvenanceNote', [ ...
            'Every update and diagnostic event carries its Block 9 ', ...
            'SourceRowIdx and SourceTime_s; see ', ...
            'EstimationResults.SourceProvenance.']);

    Report.StateModel = struct( ...
        'Model', Config.State.Model, ...
        'Definition', '15-state ZYX Euler [pN pE pD vN vE vD roll pitch yaw bax bay baz bgx bgy bgz]', ...
        'Units', {'m, m, m, m/s, m/s, m/s, rad, rad, rad, m/s^2, m/s^2, m/s^2, rad/s, rad/s, rad/s'}, ...
        'AttitudeConventions', [ ...
            'ZYX (yaw-pitch-roll), body-to-NED DCM, quaternion ', ...
            'export scalar-first [w x y z], SI units (frozen Block 2 ', ...
            'conventions). Roll/yaw continuous-unwrapped internally; ', ...
            'angular residuals wrapped.'], ...
        'PitchSingularityPolicy', struct( ...
            'Warning_deg', Config.State.PitchWarning_deg, ...
            'HardStop_deg', Config.State.PitchHardStop_deg, ...
            'Note', [ ...
                'Euler representation is not valid at |pitch| = 90 deg; ', ...
                'unrestricted aerobatic or near-vertical capability is ', ...
                'NOT claimed.']));

    Report.ProcessModel = struct( ...
        'Equations', { { ...
            'p_dot = v', ...
            'v_dot = Cbn(eta)*(f_m - b_a) + g_n', ...
            'eta_dot = T(eta)*(omega_m - b_g)', ...
            'b_a_dot = w_ba (random walk)', ...
            'b_g_dot = w_bg (random walk)'} }, ...
        'SpecificForceConvention', 'f = a - g (frozen Block 4 generator convention)', ...
        'RotationDirection', 'Cbn body-to-NED, ZYX', ...
        'Gravity', 'g_n = [0;0;+9.80665] m/s^2 (frozen +dynamics/GravityModel)', ...
        'EarthModel', [ ...
            'Local NED frame at the run navigation origin; flat-Earth. ', ...
            'Earth rotation and transport-rate terms neglected; ', ...
            'justified for <= 300 s, < 10 m/s flights (below configured ', ...
            'sensor noise); not valid for long-duration or ', ...
            'high-latitude navigation.'], ...
        'Integration', [ ...
            'First-order Euler with piecewise-constant (ZOH) IMU input ', ...
            'over each actual event interval dt; dt always measured, ', ...
            'never a fixed step. Discretization error characterized in ', ...
            'the numerical test suite.']);

    Report.MeasurementModels = struct( ...
        'GNSSPosition', 'z = [pN;pE;pD] (local NED about the anchor, WGS-84 via frozen Block 2 LLA2ECEF/ECEF2NED)', ...
        'GNSSVelocity', 'z = [vN;vE;vD] (NED, from Block 9 canonical channels)', ...
        'MagneticField', [ ...
            'z = Cbn(eta)'' * B_NED(p) in T; B_NED from the WMM ', ...
            '(wrldmagm, model epoch 2024) at the estimated position - ', ...
            'the same model and call convention as the frozen ', ...
            'simulator. Enabled as attitude update (calibration: the ', ...
            'simulated magnetometer has Gaussian noise only; units T; ', ...
            'reference model validated; Jacobian verified numerically; ', ...
            'residuals validated in tests). Configurable to ', ...
            'diagnostic-only.'], ...
        'AirData', [ ...
            'Diagnostic-only consistency record (true airspeed and ', ...
            'dynamic pressure). True airspeed is never fused as ground ', ...
            'velocity; no wind estimation is performed or claimed.']);

    Report.Initialization = InitInfo;

    Report.NoiseModels = NoiseModels.Provenance;

    Report.Filters = struct( ...
        'Implementation', 'MATLAB R2024b Sensor Fusion and Tracking Toolbox trackingEKF / trackingUKF', ...
        'SharedAssumptions', [ ...
            'Same state, process model, measurement models, inputs, ', ...
            'timestamps, initial state/covariance, noise assumptions, ', ...
            'sensor availability and gating/validity policies; ', ...
            'independent state and covariance per filter.'], ...
        'EKF', 'Analytical process and measurement Jacobians (finite-difference verified).', ...
        'UKF', struct('Alpha', 1e-3, 'Beta', 2, 'Kappa', 0, ...
            'Note', 'Scaled unscented transform parameters, configured explicitly.'), ...
        'Gating', Config.MeasurementPolicy.Gate);

    Report.Forward = struct( ...
        'EKF', struct( ...
            'Steps', numel(ForwardEKF.Time_s), ...
            'Predicts', ForwardEKF.PredictCount, ...
            'TimeRange_s', [ForwardEKF.Time_s(1), ForwardEKF.Time_s(end)], ...
            'FinalSigmaPosition_m', sqrt(ForwardEKF.CovDiag(end, 1:3))), ...
        'UKF', struct( ...
            'Steps', numel(ForwardUKF.Time_s), ...
            'Predicts', ForwardUKF.PredictCount, ...
            'TimeRange_s', [ForwardUKF.Time_s(1), ForwardUKF.Time_s(end)], ...
            'FinalSigmaPosition_m', sqrt(ForwardUKF.CovDiag(end, 1:3))));

    Report.Smoothing = struct( ...
        'EKF', SmoothingSummary(SmoothingEKF), ...
        'UKF', SmoothingSummary(SmoothingUKF), ...
        'Policy', [ ...
            'MATLAB backward smoothing recursion (trackingEKF/', ...
            'trackingUKF smooth); full-flight history configured via ', ...
            'EnableSmoothing and MaxNumSmoothingSteps; no shorter ', ...
            'window is ever reported as full-flight.']);

    Report.Diagnostics = struct( ...
        'IntegrityDisclaimer', Diagnostics.Integrity.EKF.Disclaimer, ...
        'IntegrityWeights', Diagnostics.Integrity.EKF.Weights, ...
        'IntegrityWeightRationale', Diagnostics.Integrity.EKF.WeightRationale, ...
        'SensorContributionNote', Diagnostics.SensorContribution.EKF.Notes, ...
        'ModelMismatchNote', Diagnostics.ModelMismatch.Notes, ...
        'InvestigationEventCount', Diagnostics.Investigation.EventCount, ...
        'ConfidenceSummaryEKF', Diagnostics.Confidence.EKF.Summary, ...
        'ConfidenceSummaryUKF', Diagnostics.Confidence.UKF.Summary);

    Report.Evaluation = EvaluationSummary(Evaluation);
    Report.Comparison = Comparison;

    Report.ProcessingInfo = ProcessingInfo;

end

function Summary = SmoothingSummary(Smoothing)
    Summary = struct( ...
        'Status', Smoothing.Status, ...
        'HistorySteps', Smoothing.HistorySteps, ...
        'AlignmentVerified', Smoothing.AlignmentVerified, ...
        'Limitation', Smoothing.Limitation);

    if strcmp(Smoothing.Status, 'Smoothed')

        % Reviewer finding F6: revision statistics exclude the initial
        % boundary row (its revision is zero by construction and is not a
        % smoothing result).
        Summary.InitialBoundaryRow = 1;
        Summary.BoundaryPolicy = Smoothing.BoundaryPolicy;

        if isfield(Smoothing, 'InitialBoundaryRow') && ...
                Smoothing.InitialBoundaryRow == 1 && ...
                numel(Smoothing.RevisionNorm) > 1
            RevisionRows = Smoothing.RevisionNorm(2:end);
        else
            RevisionRows = Smoothing.RevisionNorm;
        end

        Summary.MaxRevisionNorm = max(RevisionRows);
        Summary.MeanRevisionNorm = mean(RevisionRows);

    end

end

function Summary = EvaluationSummary(Evaluation)
    Summary = struct();
    Summary.Stage = Evaluation.Stage;
    Summary.SeparationNote = Evaluation.SeparationNote;
    Summary.GroundTruthFile = Evaluation.GroundTruthFile;
    Summary.OutageErrorBehaviour = Evaluation.OutageErrorBehaviour;

    Names = {'ForwardEKF', 'SmoothedEKF', 'ForwardUKF', 'SmoothedUKF'};

    for Index = 1:numel(Names)

        Name = Names{Index};

        if isfield(Evaluation, Name) && ...
                isfield(Evaluation.(Name), 'Status') && ...
                strcmp(Evaluation.(Name).Status, 'Evaluated')

            M = Evaluation.(Name);
            Summary.(Name) = struct( ...
                'Position3DRMSE_m', M.Position3DRMSE_m, ...
                'PositionRMSE_m', M.PositionRMSE_m, ...
                'VelocityRMSE_mps', M.VelocityRMSE_mps, ...
                'AttitudeAngularRMSE_rad', M.AttitudeAngularRMSE_rad, ...
                'NEESMean', M.NEESMean, ...
                'NEESMethod', M.NEESMethod, ...
                'NEESDiagMean', M.NEESDiagMean, ...
                'NEESPsdRejectedRows', M.NEESPsdRejectedRows, ...
                'EvaluatedRows', M.EvaluatedRows, ...
                'ExcludedRows', M.ExcludedRows, ...
                'InvalidEstimateRows', M.InvalidEstimateRows, ...
                'Coverage', M.Coverage);

        else

            Summary.(Name) = struct('Status', 'NotEvaluated');

        end

    end

end
