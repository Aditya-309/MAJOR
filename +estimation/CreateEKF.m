function Filter = CreateEKF(x0, P0, Config, NoiseModels, MaxSmoothingSteps)
%CREATEEKF Create the toolbox EKF with the approved Block 10 models.
%
%   Filter = CREATEEKF(x0, P0, Config, NoiseModels, MagParams,
%   MaxSmoothingSteps) creates a Sensor Fusion and Tracking Toolbox
%   trackingEKF (R2024b) configured with:
%       - the approved 15-state definition (same as the UKF),
%       - StateTransitionModel / StateTransitionJacobian (analytical),
%       - state-only measurement models (measurement functions are bound
%         per measurement type; RunFilter swaps MeasurementFcn and
%         MeasurementJacobianFcn before each update),
%       - additive process and measurement noise,
%       - smoothing history sized for the requested horizon.
%
%   The initial state and covariance are set from x0 and P0 (built by
%   InitializeState; identical for both filters). ProcessNoise is set to
%   a numeric placeholder and replaced by the per-step discrete Q(x, dt)
%   from NoiseModels before every predict.
%
%   INTERNAL function. Not part of the public Block 10 API.
%
%   See also: CreateUKF, RunFilter, BuildNoiseModels.

    Definition = estimation.StateDefinition();

    if ~(isnumeric(x0) && isequal(size(x0), [Definition.Count, 1]))

        error( ...
            'Estimation:CreateEKF:InvalidState', ...
            'x0 must be a 15x1 state vector.');

    end

    if ~(isnumeric(P0) && isequal(size(P0), ...
            [Definition.Count, Definition.Count]))

        error( ...
            'Estimation:CreateEKF:InvalidCovariance', ...
            'P0 must be a 15x15 covariance matrix.');

    end

    if ~(isnumeric(MaxSmoothingSteps) && isscalar(MaxSmoothingSteps) && ...
            MaxSmoothingSteps >= 1 && ...
            MaxSmoothingSteps == floor(MaxSmoothingSteps))

        error( ...
            'Estimation:CreateEKF:InvalidSmoothingSteps', ...
            'MaxSmoothingSteps must be a positive integer scalar.');

    end

    % Default binding: GNSS position (RunFilter swaps per update type).
    Filter = trackingEKF( ...
        'StateTransitionFcn', ...
            @(x, dt, accel, gyro) estimation.StateTransitionModel( ...
                x, dt, accel, gyro), ...
        'StateTransitionJacobianFcn', ...
            @(x, dt, accel, gyro) estimation.StateTransitionJacobian( ...
                x, dt, accel, gyro), ...
        'MeasurementFcn', ...
            @(x) estimation.MeasurementModel(x, 'GNSSPosition', []), ...
        'MeasurementJacobianFcn', ...
            @(x) estimation.MeasurementJacobian(x, 'GNSSPosition', []), ...
        'State', x0, ...
        'StateCovariance', P0, ...
        'ProcessNoise', eye(Definition.Count), ...
        'MeasurementNoise', NoiseModels.R.GNSSPosition, ...
        'HasAdditiveProcessNoise', true, ...
        'HasAdditiveMeasurementNoise', true, ...
        'EnableSmoothing', Config.Smoothing.FullFlight, ...
        'MaxNumSmoothingSteps', MaxSmoothingSteps);

end
