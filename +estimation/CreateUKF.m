function Filter = CreateUKF(x0, P0, Config, NoiseModels, MaxSmoothingSteps)
%CREATEUKF Create the toolbox UKF with the approved Block 10 models.
%
%   Filter = CREATEUKF(x0, P0, Config, NoiseModels, MagParams,
%   MaxSmoothingSteps) creates a Sensor Fusion and Tracking Toolbox
%   trackingUKF (R2024b) with the SAME state definition, process model,
%   measurement models, initial state, initial covariance, noise
%   assumptions, sensor availability and gating/validity policies as
%   CreateEKF. Only the filtering algorithm differs.
%
%   Sigma-point parameters (configured explicitly and documented):
%       Alpha = 1e-3, Beta = 2, Kappa = 0
%   (standard scaled unscented-transform parameters; spread alpha*sqrt(n
%   + kappa) = 1e-3*sqrt(15)). They are recorded in the estimation
%   report. The UKF is not assumed to outperform the EKF; any comparison
%   is made from experimental results only.
%
%   INTERNAL function. Not part of the public Block 10 API.
%
%   See also: CreateEKF, RunFilter, BuildNoiseModels.

    Definition = estimation.StateDefinition();

    if ~(isnumeric(x0) && isequal(size(x0), [Definition.Count, 1]))

        error( ...
            'Estimation:CreateUKF:InvalidState', ...
            'x0 must be a 15x1 state vector.');

    end

    if ~(isnumeric(P0) && isequal(size(P0), ...
            [Definition.Count, Definition.Count]))

        error( ...
            'Estimation:CreateUKF:InvalidCovariance', ...
            'P0 must be a 15x15 covariance matrix.');

    end

    if ~(isnumeric(MaxSmoothingSteps) && isscalar(MaxSmoothingSteps) && ...
            MaxSmoothingSteps >= 1 && ...
            MaxSmoothingSteps == floor(MaxSmoothingSteps))

        error( ...
            'Estimation:CreateUKF:InvalidSmoothingSteps', ...
            'MaxSmoothingSteps must be a positive integer scalar.');

    end

    % The UKF has no Jacobian properties (sigma points replace them);
    % the shared analytical Jacobians are used by the EKF and by the
    % numerical verification only.
    Filter = trackingUKF( ...
        'StateTransitionFcn', ...
            @(x, dt, accel, gyro) estimation.StateTransitionModel( ...
                x, dt, accel, gyro), ...
        'MeasurementFcn', ...
            @(x) estimation.MeasurementModel(x, 'GNSSPosition', []), ...
        'State', x0, ...
        'StateCovariance', P0, ...
        'ProcessNoise', eye(Definition.Count), ...
        'MeasurementNoise', NoiseModels.R.GNSSPosition, ...
        'HasAdditiveProcessNoise', true, ...
        'HasAdditiveMeasurementNoise', true, ...
        'Alpha', 1e-3, ...
        'Beta', 2, ...
        'Kappa', 0, ...
        'EnableSmoothing', Config.Smoothing.FullFlight, ...
        'MaxNumSmoothingSteps', MaxSmoothingSteps);

end
