function Config = ValidateEstimationConfig(Config)
%VALIDATEESTIMATIONCONFIG Validate a Block 10 estimation configuration.
%
%   Config = VALIDATEESTIMATIONCONFIG(Config) validates the configuration
%   structure produced by EstimationConfig and returns it unchanged on
%   success. Every failure raises a typed error
%   Estimation:ValidateEstimationConfig:<Reason>.
%
%   Validation covers structure shape, value ranges, internal
%   consistency (warning threshold below hard-stop threshold, weights sum
%   to one, probabilities in range) and the attitude-source policy
%   requirements (a Prior attitude must carry finite values and a
%   provenance text).
%
%   INTERNAL function. Not part of the public Block 10 API.
%
%   See also: EstimationConfig, RunStateReconstruction.

    if ~(isstruct(Config) && isscalar(Config))

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidConfig', ...
            'Config must be a scalar structure.');

    end

    RequiredTop = { ...
        'Name', 'Version', 'ImplementationVersion', 'State', 'Noise', ...
        'NoiseProvenance', 'Magnetometer', 'MeasurementPolicy', ...
        'Initialization', 'Smoothing', 'Integrity', 'Diagnostics', ...
        'Evaluation', 'Output'};

    for Index = 1:numel(RequiredTop)

        if ~isfield(Config, RequiredTop{Index})

            error( ...
                'Estimation:ValidateEstimationConfig:MissingField', ...
                'Config is missing required field "%s".', ...
                RequiredTop{Index});

        end

    end

    %% State thresholds

    checkFiniteScalar(Config.State.PitchWarning_deg, ...
        'State.PitchWarning_deg');
    checkFiniteScalar(Config.State.PitchHardStop_deg, ...
        'State.PitchHardStop_deg');

    if Config.State.PitchWarning_deg <= 0 || ...
            Config.State.PitchHardStop_deg >= 90

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidPitchThresholds', ...
            ['Pitch thresholds must satisfy 0 < warning < hard stop ', ...
             '< 90 degrees.']);

    end

    if Config.State.PitchWarning_deg >= Config.State.PitchHardStop_deg

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidPitchThresholds', ...
            'Pitch warning threshold must be below the hard-stop threshold.');

    end

    if ~strcmp(Config.State.Model, 'ZYX15')

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidStateModel', ...
            'State.Model must be ''ZYX15''.');

    end

    %% Noise parameters (all strictly positive finite scalars)

    PositiveNoise = { ...
        'Noise.GNSS.HorizontalSigma_m', ...
        'Noise.GNSS.VerticalSigma_m', ...
        'Noise.GNSS.VelocitySigma_mps', ...
        'Noise.GNSS.BiasSigmaHorizontal_m', ...
        'Noise.GNSS.BiasSigmaVertical_m', ...
        'Noise.GNSS.BiasCorrelationTime_s', ...
        'Noise.IMU.AccelVRW_mps2SqrtHz', ...
        'Noise.IMU.GyroARW_radpsSqrtHz', ...
        'Noise.IMU.AccelInRunBiasSigma_mps2', ...
        'Noise.IMU.GyroInRunBiasSigma_radps', ...
        'Noise.IMU.InRunBiasCorrelationTime_s', ...
        'Noise.IMU.AccelTurnOnBiasSigma_mps2', ...
        'Noise.IMU.GyroTurnOnBiasSigma_radps', ...
        'Noise.Magnetometer.Sigma_T'};

    for Index = 1:numel(PositiveNoise)

        Value = getNestedField(Config, PositiveNoise{Index});

        if ~(isnumeric(Value) && isreal(Value) && isscalar(Value) && ...
                isfinite(Value) && Value > 0)

            error( ...
                'Estimation:ValidateEstimationConfig:InvalidNoiseValue', ...
                '%s must be a positive finite real scalar.', ...
                PositiveNoise{Index});

        end

    end

    if ~(islogical(Config.Noise.GNSS.IncludeBiasInR) && ...
            isscalar(Config.Noise.GNSS.IncludeBiasInR))

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidNoiseValue', ...
            'Noise.GNSS.IncludeBiasInR must be a logical scalar.');

    end

    %% Magnetometer section

    if ~(islogical(Config.Magnetometer.EnableUpdates) && ...
            isscalar(Config.Magnetometer.EnableUpdates))

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidMagnetometer', ...
            'Magnetometer.EnableUpdates must be a logical scalar.');

    end

    if ~strcmp(Config.Magnetometer.ReferenceModel, 'WMM')

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidMagnetometer', ...
            'Magnetometer.ReferenceModel must be ''WMM''.');

    end

    if ~(isnumeric(Config.Magnetometer.ModelYear) && ...
            isscalar(Config.Magnetometer.ModelYear) && ...
            isfinite(Config.Magnetometer.ModelYear) && ...
            Config.Magnetometer.ModelYear == floor(Config.Magnetometer.ModelYear))

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidMagnetometer', ...
            'Magnetometer.ModelYear must be an integer scalar.');

    end

    %% Measurement policy

    if ~iscellstr(Config.MeasurementPolicy.RequiredFlagsTrue)

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidPolicy', ...
            'MeasurementPolicy.RequiredFlagsTrue must be a cell array of character vectors.');

    end

    ValidRequired = {'Available', 'RowValid', 'MeasurementValid'};

    if ~all(ismember(Config.MeasurementPolicy.RequiredFlagsTrue, ValidRequired))

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidPolicy', ...
            ['MeasurementPolicy.RequiredFlagsTrue may only name ', ...
             'Available, RowValid and MeasurementValid.']);

    end

    if ~iscellstr(Config.MeasurementPolicy.ExcludeFlagNames)

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidPolicy', ...
            'MeasurementPolicy.ExcludeFlagNames must be a cell array of character vectors.');

    end

    ValidExclude = [ValidRequired, { ...
        'NonFiniteTimestamp', 'DuplicateTimestampLater', ...
        'BackwardTimestamp', 'UnexpectedGap', 'Unavailable', ...
        'NonFiniteMeasurement', 'PhysicalOutlier', ...
        'StatisticalOutlier', 'SuddenChange', 'StartupTransient'}];

    if ~all(ismember(Config.MeasurementPolicy.ExcludeFlagNames, ValidExclude))

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidPolicy', ...
            ['MeasurementPolicy.ExcludeFlagNames contains an unknown ', ...
             'flag name.']);

    end

    if ~(islogical(Config.MeasurementPolicy.Gate.Enabled) && ...
            isscalar(Config.MeasurementPolicy.Gate.Enabled))

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidPolicy', ...
            'MeasurementPolicy.Gate.Enabled must be a logical scalar.');

    end

    Prob = Config.MeasurementPolicy.Gate.Probability;

    if ~(isnumeric(Prob) && isreal(Prob) && isscalar(Prob) && ...
            isfinite(Prob) && Prob > 0 && Prob < 1)

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidPolicy', ...
            'MeasurementPolicy.Gate.Probability must be in (0, 1).');

    end

    %% Initialization

    if ~strcmp(Config.Initialization.OriginPolicy, 'FirstEligibleGNSSFix')

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidInit', ...
            'Initialization.OriginPolicy must be ''FirstEligibleGNSSFix''.');

    end

    AttitudeSource = Config.Initialization.AttitudeSource;

    if ~(strcmp(AttitudeSource, 'AccelerometerMagnetometer') || ...
            strcmp(AttitudeSource, 'Prior'))

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidInit', ...
            ['Initialization.AttitudeSource must be ', ...
             '''AccelerometerMagnetometer'' or ''Prior''.']);

    end

    if ~(strcmp(Config.Initialization.AlignmentWindow, 'Forward') || ...
            strcmp(Config.Initialization.AlignmentWindow, 'Trailing'))

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidInit', ...
            ['Initialization.AlignmentWindow must be ''Forward'' or ', ...
             '''Trailing''.']);

    end

    checkFiniteScalar(Config.Initialization.Window_s, ...
        'Initialization.Window_s');

    if Config.Initialization.Window_s <= 0

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidInit', ...
            'Initialization.Window_s must be positive.');

    end

    if strcmp(AttitudeSource, 'Prior')

        Prior = Config.Initialization.PriorAttitude;

        PriorValues = [Prior.roll_rad, Prior.pitch_rad, Prior.yaw_rad, ...
            Prior.sigma_rad];

        if any(~isfinite(PriorValues)) || any(PriorValues(4:6) <= 0)

            error( ...
                'Estimation:ValidateEstimationConfig:InvalidPriorAttitude', ...
                ['Prior attitude requires finite angles and positive ', ...
                 'finite standard deviations.']);

        end

        if ~(ischar(Prior.Provenance) || isstring(Prior.Provenance)) || ...
                strlength(string(Prior.Provenance)) == 0

            error( ...
                'Estimation:ValidateEstimationConfig:InvalidPriorAttitude', ...
                'Prior attitude requires a nonempty Provenance text.');

        end

    end

    %% Smoothing, integrity, diagnostics, evaluation, output

    if ~(islogical(Config.Smoothing.FullFlight) && ...
            isscalar(Config.Smoothing.FullFlight))

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidSmoothing', ...
            'Smoothing.FullFlight must be a logical scalar.');

    end

    checkFiniteScalar(Config.Smoothing.MemoryLimit_MB, ...
        'Smoothing.MemoryLimit_MB');

    WeightNames = fieldnames(Config.Integrity.Weights);

    if ~all(ismember(WeightNames, { ...
            'Consistency', 'CovarianceValidity', 'SensorSupport', ...
            'InnovationHealth'})) || numel(WeightNames) ~= 4

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidIntegrityWeights', ...
            ['Integrity.Weights must define exactly Consistency, ', ...
             'CovarianceValidity, SensorSupport and InnovationHealth.']);

    end

    WeightSum = 0;

    for Index = 1:numel(WeightNames)

        Weight = Config.Integrity.Weights.(WeightNames{Index});
        checkFiniteScalar(Weight, ['Integrity.Weights.' WeightNames{Index}]);

        if Weight < 0

            error( ...
                'Estimation:ValidateEstimationConfig:InvalidIntegrityWeights', ...
                'Integrity weights must be nonnegative.');

        end

        WeightSum = WeightSum + Weight;

    end

    if abs(WeightSum - 1) > 1e-9

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidIntegrityWeights', ...
            'Integrity weights must sum to 1.');

    end

    checkFiniteScalar(Config.Diagnostics.MismatchWindow_s, ...
        'Diagnostics.MismatchWindow_s');
    checkFiniteScalar(Config.Diagnostics.DisagreementSigmaGate, ...
        'Diagnostics.DisagreementSigmaGate');
    checkFiniteScalar(Config.Diagnostics.SmoothingRevisionSigma, ...
        'Diagnostics.SmoothingRevisionSigma');

    if Config.Diagnostics.MismatchWindow_s <= 0 || ...
            Config.Diagnostics.DisagreementSigmaGate <= 0 || ...
            Config.Diagnostics.SmoothingRevisionSigma <= 0

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidDiagnostics', ...
            'Diagnostics window and gate values must be positive.');

    end

    if ~(islogical(Config.Evaluation.EnableGroundTruthEvaluation) && ...
            isscalar(Config.Evaluation.EnableGroundTruthEvaluation))

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidEvaluation', ...
            'Evaluation.EnableGroundTruthEvaluation must be a logical scalar.');

    end

    if ~(isnumeric(Config.Evaluation.CoverageSigmas) && ...
            isvector(Config.Evaluation.CoverageSigmas) && ...
            all(isfinite(Config.Evaluation.CoverageSigmas)) && ...
            all(Config.Evaluation.CoverageSigmas > 0))

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidEvaluation', ...
            'Evaluation.CoverageSigmas must be a positive finite vector.');

    end

    LogicalOutputs = {'WriteMat', 'WriteReportJson', 'WriteReviewCsv'};

    for Index = 1:numel(LogicalOutputs)

        Value = Config.Output.(LogicalOutputs{Index});

        if ~(islogical(Value) && isscalar(Value))

            error( ...
                'Estimation:ValidateEstimationConfig:InvalidOutput', ...
                'Output.%s must be a logical scalar.', ...
                LogicalOutputs{Index});

        end

    end

    if ~(ischar(Config.Output.EstimationRoot) || ...
            (isstring(Config.Output.EstimationRoot) && ...
            isscalar(Config.Output.EstimationRoot)))

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidOutput', ...
            'Output.EstimationRoot must be a character vector or scalar string.');

    end

end

%% Local helpers

function Value = getNestedField(Config, Path)
    Parts = strsplit(Path, '.');
    Value = Config;

    for Index = 1:numel(Parts)
        Value = Value.(Parts{Index});
    end
end

function checkFiniteScalar(Value, Label)
    if ~(isnumeric(Value) && isreal(Value) && isscalar(Value) && ...
            isfinite(Value))

        error( ...
            'Estimation:ValidateEstimationConfig:InvalidValue', ...
            '%s must be a finite real scalar.', ...
            Label);

    end
end
