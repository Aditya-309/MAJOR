function Control = SmoothControlProfile( ...
    Time_s, ...
    InitialValue, ...
    TargetValue, ...
    RampStartTime_s, ...
    HoldStartTime_s, ...
    ReturnStartTime_s, ...
    FinalTime_s, ...
    FinalValue)
%SMOOTHCONTROLPROFILE Generate a deterministic smooth control profile.
%
%   Control = flightscenario.SmoothControlProfile( ...
%       Time_s, ...
%       InitialValue, ...
%       TargetValue, ...
%       RampStartTime_s, ...
%       HoldStartTime_s, ...
%       ReturnStartTime_s, ...
%       FinalTime_s, ...
%       FinalValue)
%
%   Generates a smooth control profile with the sequence:
%
%       InitialValue
%           |
%           | Smooth ramp
%           v
%       TargetValue
%           |
%           | Hold
%           v
%       TargetValue
%           |
%           | Smooth return
%           v
%       FinalValue
%
%   The ramp transitions use a quintic smoothstep trajectory:
%
%       s(x) = 6x^5 - 15x^4 + 10x^3
%
%   This provides zero first and second derivatives at both transition
%   boundaries, avoiding discontinuities in the generated control profile.
%
%   INPUTS
%
%       Time_s
%           Real finite scalar or vector containing evaluation times in
%           seconds. The input shape is preserved in the output.
%
%       InitialValue
%           Scalar control value before RampStartTime_s.
%
%       TargetValue
%           Scalar control value reached at HoldStartTime_s.
%
%       RampStartTime_s
%           Start time of the smooth transition from InitialValue to
%           TargetValue.
%
%       HoldStartTime_s
%           End time of the ramp and beginning of the hold interval.
%
%       ReturnStartTime_s
%           Start time of the smooth transition from TargetValue to
%           FinalValue.
%
%       FinalTime_s
%           End time of the return transition.
%
%       FinalValue
%           Scalar control value after FinalTime_s.
%
%   OUTPUT
%
%       Control
%           Smooth deterministic control profile with the same dimensions
%           as Time_s.
%
%   REQUIREMENTS
%
%       RampStartTime_s < HoldStartTime_s <= ReturnStartTime_s < FinalTime_s
%
%   NOTES
%
%       - No scenario-specific logic is contained in this function.
%       - No aircraft parameters are required.
%       - The function is deterministic.
%       - No overshoot is introduced.
%       - Scalar and vector time inputs are supported.
%       - This function does not impose actuator limits. Normalized or
%         physical control limits are the responsibility of the caller.
%
%   MATLAB Version
%       MATLAB R2024b compatible.

    %% Input Validation

    validateattributes( ...
        Time_s, ...
        {'numeric'}, ...
        {'real', 'finite'}, ...
        mfilename, ...
        'Time_s', ...
        1);

    validateattributes( ...
        InitialValue, ...
        {'numeric'}, ...
        {'real', 'finite', 'scalar'}, ...
        mfilename, ...
        'InitialValue', ...
        2);

    validateattributes( ...
        TargetValue, ...
        {'numeric'}, ...
        {'real', 'finite', 'scalar'}, ...
        mfilename, ...
        'TargetValue', ...
        3);

    validateattributes( ...
        RampStartTime_s, ...
        {'numeric'}, ...
        {'real', 'finite', 'scalar'}, ...
        mfilename, ...
        'RampStartTime_s', ...
        4);

    validateattributes( ...
        HoldStartTime_s, ...
        {'numeric'}, ...
        {'real', 'finite', 'scalar'}, ...
        mfilename, ...
        'HoldStartTime_s', ...
        5);

    validateattributes( ...
        ReturnStartTime_s, ...
        {'numeric'}, ...
        {'real', 'finite', 'scalar'}, ...
        mfilename, ...
        'ReturnStartTime_s', ...
        6);

    validateattributes( ...
        FinalTime_s, ...
        {'numeric'}, ...
        {'real', 'finite', 'scalar'}, ...
        mfilename, ...
        'FinalTime_s', ...
        7);

    validateattributes( ...
        FinalValue, ...
        {'numeric'}, ...
        {'real', 'finite', 'scalar'}, ...
        mfilename, ...
        'FinalValue', ...
        8);

    if ~(RampStartTime_s < HoldStartTime_s)

        error( ...
            'SmoothControlProfile:InvalidRampInterval', ...
            ['RampStartTime_s must be strictly less than ' ...
             'HoldStartTime_s.']);

    end

    if ReturnStartTime_s < HoldStartTime_s

        error( ...
            'SmoothControlProfile:InvalidHoldInterval', ...
            ['ReturnStartTime_s must be greater than or equal to ' ...
             'HoldStartTime_s.']);

    end

    if ~(ReturnStartTime_s < FinalTime_s)

        error( ...
            'SmoothControlProfile:InvalidReturnInterval', ...
            ['ReturnStartTime_s must be strictly less than ' ...
             'FinalTime_s.']);

    end

    %% Initialize Output

    Control = InitialValue .* ones(size(Time_s));

    %% Smooth Ramp: InitialValue -> TargetValue

    RampMask = ...
        Time_s >= RampStartTime_s & ...
        Time_s < HoldStartTime_s;

    if any(RampMask, 'all')

        NormalizedTime = ...
            (Time_s(RampMask) - RampStartTime_s) ./ ...
            (HoldStartTime_s - RampStartTime_s);

        SmoothFraction = localQuinticSmoothStep(NormalizedTime);

        Control(RampMask) = ...
            InitialValue + ...
            (TargetValue - InitialValue) .* ...
            SmoothFraction;

    end

    %% Hold Target Value

    HoldMask = ...
        Time_s >= HoldStartTime_s & ...
        Time_s < ReturnStartTime_s;

    if any(HoldMask, 'all')

        Control(HoldMask) = TargetValue;

    end

    %% Smooth Return: TargetValue -> FinalValue

    ReturnMask = ...
        Time_s >= ReturnStartTime_s & ...
        Time_s < FinalTime_s;

    if any(ReturnMask, 'all')

        NormalizedTime = ...
            (Time_s(ReturnMask) - ReturnStartTime_s) ./ ...
            (FinalTime_s - ReturnStartTime_s);

        SmoothFraction = localQuinticSmoothStep(NormalizedTime);

        Control(ReturnMask) = ...
            TargetValue + ...
            (FinalValue - TargetValue) .* ...
            SmoothFraction;

    end

    %% Final Value

    FinalMask = Time_s >= FinalTime_s;

    if any(FinalMask, 'all')

        Control(FinalMask) = FinalValue;

    end

end


function SmoothFraction = localQuinticSmoothStep(NormalizedTime)
%LOCALQUINTICSMOOTHSTEP Quintic zero-slope transition function.

    NormalizedTime = min(max(NormalizedTime, 0), 1);

    SmoothFraction = ...
        6 .* NormalizedTime.^5 - ...
        15 .* NormalizedTime.^4 + ...
        10 .* NormalizedTime.^3;

end