function Validation = ValidateScenario(Scenario)
%VALIDATESCENARIO Validate a flight scenario configuration.
%
%   Validation = flightscenario.ValidateScenario(Scenario)
%
%   Validates the scenario structure produced by
%   flightscenario.ScenarioConfig. The function verifies core scenario
%   metadata, timing, initial conditions, wind configuration, event
%   definitions, and control phase definitions.
%
%   The function throws an error immediately when an invalid scenario is
%   detected. On success, it returns a validation summary structure.

    %% Validate Input

    if ~isstruct(Scenario) || ~isscalar(Scenario)

        error( ...
            'ValidateScenario:InvalidScenario', ...
            'Scenario must be a scalar structure.');

    end

    %% Required Top-Level Fields

    RequiredFields = {
        'Metadata'
        'Name'
        'ID'
        'Time'
        'SampleRate_Hz'
        'SampleTime_s'
        'Duration_s'
        'InitialCondition'
        'Controls'
        'Wind'
        'Events'
    };

    localRequireFields( ...
        Scenario, ...
        RequiredFields, ...
        'Scenario');

    %% Scenario Identity

    validateattributes( ...
        Scenario.ID, ...
        {'numeric'}, ...
        {'real', 'finite', 'scalar', 'integer', 'positive'}, ...
        mfilename, ...
        'Scenario.ID');

    if ~ischar(Scenario.Name) && ...
            ~(isstring(Scenario.Name) && isscalar(Scenario.Name))

        error( ...
            'ValidateScenario:InvalidName', ...
            'Scenario.Name must be a character vector or string scalar.');

    end

    if strlength(string(Scenario.Name)) == 0

        error( ...
            'ValidateScenario:InvalidName', ...
            'Scenario.Name cannot be empty.');

    end

    %% Time Configuration

    validateattributes( ...
        Scenario.SampleRate_Hz, ...
        {'numeric'}, ...
        {'real', 'finite', 'scalar', 'positive'}, ...
        mfilename, ...
        'Scenario.SampleRate_Hz');

    validateattributes( ...
        Scenario.SampleTime_s, ...
        {'numeric'}, ...
        {'real', 'finite', 'scalar', 'positive'}, ...
        mfilename, ...
        'Scenario.SampleTime_s');

    validateattributes( ...
        Scenario.Duration_s, ...
        {'numeric'}, ...
        {'real', 'finite', 'scalar', 'positive'}, ...
        mfilename, ...
        'Scenario.Duration_s');

    ExpectedSampleTime_s = ...
        1 / Scenario.SampleRate_Hz;

    if abs( ...
            Scenario.SampleTime_s - ...
            ExpectedSampleTime_s) > ...
            1e-12

        error( ...
            'ValidateScenario:InconsistentSampleTime', ...
            ['Scenario.SampleTime_s must equal the inverse of ' ...
             'Scenario.SampleRate_Hz.']);

    end

    DurationSamples = ...
        Scenario.Duration_s / ...
        Scenario.SampleTime_s;

    if abs( ...
            DurationSamples - ...
            round(DurationSamples)) > ...
            1e-9

        error( ...
            'ValidateScenario:DurationNotSampleAligned', ...
            ['Scenario.Duration_s must contain an integer number ' ...
             'of sample intervals.']);

    end

    %% Initial Conditions

    if ~isstruct(Scenario.InitialCondition) || ...
            ~isscalar(Scenario.InitialCondition)

        error( ...
            'ValidateScenario:InvalidInitialCondition', ...
            'Scenario.InitialCondition must be a scalar structure.');

    end

    InitialCondition = ...
        Scenario.InitialCondition;

    localValidateFiniteNumericFields( ...
        InitialCondition, ...
        'Scenario.InitialCondition');

    if isfield(InitialCondition, 'Speed_mps')

        validateattributes( ...
            InitialCondition.Speed_mps, ...
            {'numeric'}, ...
            {'real', 'finite', 'scalar', 'positive'}, ...
            mfilename, ...
            'Scenario.InitialCondition.Speed_mps');

    end

    if isfield(InitialCondition, 'Altitude_m')

        validateattributes( ...
            InitialCondition.Altitude_m, ...
            {'numeric'}, ...
            {'real', 'finite', 'scalar', 'nonnegative'}, ...
            mfilename, ...
            'Scenario.InitialCondition.Altitude_m');

    end

    %% Wind Configuration

    if ~isstruct(Scenario.Wind) || ...
            ~isscalar(Scenario.Wind)

        error( ...
            'ValidateScenario:InvalidWind', ...
            'Scenario.Wind must be a scalar structure.');

    end

    localRequireFields( ...
        Scenario.Wind, ...
        {
            'Mode'
            'Frame'
            'Units'
            'ConstantNED_mps'
            'Gust'
        }, ...
        'Scenario.Wind');

    ConstantWindNED_mps = ...
        Scenario.Wind.ConstantNED_mps;

    validateattributes( ...
        ConstantWindNED_mps, ...
        {'numeric'}, ...
        {'real', 'finite', 'vector', 'numel', 3}, ...
        mfilename, ...
        'Scenario.Wind.ConstantNED_mps');

    if ~strcmp( ...
            char(Scenario.Wind.Frame), ...
            'NED')

        error( ...
            'ValidateScenario:InvalidWindFrame', ...
            'Scenario.Wind.Frame must be ''NED''.');

    end

    if ~strcmp( ...
            char(Scenario.Wind.Units), ...
            'm/s')

        error( ...
            'ValidateScenario:InvalidWindUnits', ...
            'Scenario.Wind.Units must be ''m/s''.');

    end

    if ~isstruct(Scenario.Wind.Gust) || ...
            ~isscalar(Scenario.Wind.Gust)

        error( ...
            'ValidateScenario:InvalidGust', ...
            'Scenario.Wind.Gust must be a scalar structure.');

    end

    localValidateGust(Scenario.Wind.Gust);

    %% Event Configuration

    if ~isstruct(Scenario.Events) || ...
            ~isscalar(Scenario.Events)

        error( ...
            'ValidateScenario:InvalidEvents', ...
            'Scenario.Events must be a scalar structure.');

    end

    EventNames = ...
        fieldnames(Scenario.Events);

    for k = 1:numel(EventNames)

        EventName = ...
            EventNames{k};

        Event = ...
            Scenario.Events.(EventName);

        localValidateEvent( ...
            Event, ...
            EventName, ...
            Scenario.Duration_s);

    end

    %% Control Configuration

    if ~isstruct(Scenario.Controls) || ...
            ~isscalar(Scenario.Controls)

        error( ...
            'ValidateScenario:InvalidControls', ...
            'Scenario.Controls must be a scalar structure.');

    end

    ControlNames = ...
        fieldnames(Scenario.Controls);

    for k = 1:numel(ControlNames)

        ControlName = ...
            ControlNames{k};

        ControlDefinition = ...
            Scenario.Controls.(ControlName);

        if isstruct(ControlDefinition) && ...
                isscalar(ControlDefinition) && ...
                isfield(ControlDefinition, 'StartTime_s') && ...
                isfield(ControlDefinition, 'EndTime_s')

            localValidatePhase( ...
                ControlDefinition, ...
                ControlName, ...
                Scenario.Duration_s);

        elseif isnumeric(ControlDefinition) && ...
                isscalar(ControlDefinition)

            if ~isfinite(ControlDefinition) && ...
                    ~isnan(ControlDefinition)

                error( ...
                    'ValidateScenario:InvalidControlValue', ...
                    ['Control definition "' ControlName ...
                     '" must be finite or NaN.']);

            end

        elseif isstruct(ControlDefinition)

            % Non-timing control metadata such as Turn.
            localValidateFiniteNumericFields( ...
                ControlDefinition, ...
                ['Scenario.Controls.' ControlName]);

        else

            error( ...
                'ValidateScenario:InvalidControlDefinition', ...
                ['Control definition "' ControlName ...
                 '" has an unsupported type.']);

        end

    end

    %% Validate Enabled Wind Event Consistency

    if isfield( ...
            Scenario.Events, ...
            'WindDisturbance')

        WindEvent = ...
            Scenario.Events.WindDisturbance;

        if WindEvent.Enabled

            if ~isfield(Scenario.Wind, 'Gust') || ...
                    isempty(fieldnames(Scenario.Wind.Gust))

                error( ...
                    'ValidateScenario:MissingWindGust', ...
                    ['An enabled WindDisturbance requires a valid ' ...
                     'Scenario.Wind.Gust definition.']);

            end

        end

    end

    %% Validation Result

    Validation = struct();

    Validation.IsValid = true;

    Validation.ScenarioID = ...
        Scenario.ID;

    Validation.ScenarioName = ...
        char(string(Scenario.Name));

    Validation.SampleRate_Hz = ...
        Scenario.SampleRate_Hz;

    Validation.SampleTime_s = ...
        Scenario.SampleTime_s;

    Validation.Duration_s = ...
        Scenario.Duration_s;

    Validation.NumberOfSampleIntervals = ...
        round(DurationSamples);

    Validation.NumberOfSamples = ...
        round(DurationSamples) + 1;

    Validation.ValidatedEvents = ...
        EventNames;

    Validation.ValidatedControls = ...
        ControlNames;

end


%% ========================================================================
%  Local Functions
%  ========================================================================

function localRequireFields(Structure, RequiredFields, StructureName)

    for k = 1:numel(RequiredFields)

        FieldName = ...
            RequiredFields{k};

        if ~isfield(Structure, FieldName)

            error( ...
                'ValidateScenario:MissingField', ...
                '%s is missing required field "%s".', ...
                StructureName, ...
                FieldName);

        end

    end

end


function localValidateFiniteNumericFields(Structure, StructureName)

    FieldNames = ...
        fieldnames(Structure);

    for k = 1:numel(FieldNames)

        FieldName = ...
            FieldNames{k};

        Value = ...
            Structure.(FieldName);

        if isnumeric(Value)

            if ~isreal(Value) || ...
                    any(isinf(Value), 'all')

                error( ...
                    'ValidateScenario:InvalidNumericValue', ...
                    ['%s.%s contains an invalid numeric value.'], ...
                    StructureName, ...
                    FieldName);

            end

        end

    end

end


function localValidateGust(Gust)

    GustFields = ...
        fieldnames(Gust);

    FoundVector = false;

    for k = 1:numel(GustFields)

        Value = ...
            Gust.(GustFields{k});

        if isnumeric(Value) && ...
                isreal(Value) && ...
                isvector(Value) && ...
                numel(Value) == 3 && ...
                all(isfinite(Value))

            FoundVector = true;

            break

        end

    end

    if ~FoundVector

        error( ...
            'ValidateScenario:InvalidGustVector', ...
            ['Scenario.Wind.Gust must contain at least one finite ' ...
             '3-element numeric vector.']);

    end

end


function localValidateEvent(Event, EventName, Duration_s)

    if ~isstruct(Event) || ...
            ~isscalar(Event)

        error( ...
            'ValidateScenario:InvalidEvent', ...
            'Event "%s" must be a scalar structure.', ...
            EventName);

    end

    localRequireFields( ...
        Event, ...
        {
            'Enabled'
            'StartTime_s'
            'EndTime_s'
        }, ...
        ['Scenario.Events.' EventName]);

    if ~(islogical(Event.Enabled) && ...
            isscalar(Event.Enabled))

        error( ...
            'ValidateScenario:InvalidEventEnabled', ...
            'Event "%s".Enabled must be a logical scalar.', ...
            EventName);

    end

    if Event.Enabled

        validateattributes( ...
            Event.StartTime_s, ...
            {'numeric'}, ...
            {'real', 'finite', 'scalar', 'nonnegative'}, ...
            mfilename, ...
            [EventName '.StartTime_s']);

        validateattributes( ...
            Event.EndTime_s, ...
            {'numeric'}, ...
            {'real', 'finite', 'scalar', 'positive'}, ...
            mfilename, ...
            [EventName '.EndTime_s']);

        if Event.EndTime_s <= ...
                Event.StartTime_s

            error( ...
                'ValidateScenario:InvalidEventInterval', ...
                'Event "%s" must have EndTime_s > StartTime_s.', ...
                EventName);

        end

        if Event.EndTime_s > Duration_s

            error( ...
                'ValidateScenario:EventExceedsDuration', ...
                'Event "%s" exceeds scenario duration.', ...
                EventName);

        end

    else

        if ~( ...
                (isnumeric(Event.StartTime_s) && ...
                 isscalar(Event.StartTime_s)) && ...
                (isnumeric(Event.EndTime_s) && ...
                 isscalar(Event.EndTime_s)))

            error( ...
                'ValidateScenario:InvalidDisabledEventTiming', ...
                ['Disabled event "%s" must contain scalar numeric ' ...
                 'timing values or NaN placeholders.'], ...
                EventName);

        end

    end

end


function localValidatePhase(Phase, PhaseName, Duration_s)

    StartTime_s = ...
        Phase.StartTime_s;

    EndTime_s = ...
        Phase.EndTime_s;

    if isnan(StartTime_s) && ...
            isnan(EndTime_s)

        return

    end

    validateattributes( ...
        StartTime_s, ...
        {'numeric'}, ...
        {'real', 'finite', 'scalar', 'nonnegative'}, ...
        mfilename, ...
        [PhaseName '.StartTime_s']);

    validateattributes( ...
        EndTime_s, ...
        {'numeric'}, ...
        {'real', 'finite', 'scalar', 'positive'}, ...
        mfilename, ...
        [PhaseName '.EndTime_s']);

    if EndTime_s <= StartTime_s

        error( ...
            'ValidateScenario:InvalidPhaseInterval', ...
            ['Phase "' PhaseName ...
             '" must have EndTime_s > StartTime_s.']);

    end

    if EndTime_s > Duration_s

        error( ...
            'ValidateScenario:PhaseExceedsDuration', ...
            ['Phase "' PhaseName ...
             '" exceeds scenario duration.']);

    end

end