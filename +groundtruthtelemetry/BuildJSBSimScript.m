function ScriptFile = BuildJSBSimScript( ...
    RunConfig, ...
    Scenario, ...
    Timeline)
%BUILDJSBSIMSCRIPT Build the JSBSim execution script for Block 7.

    %% Input Validation

    if nargin ~= 3
        error( ...
            'Block7:BuildJSBSimScript:InvalidInputCount', ...
            ['BuildJSBSimScript requires exactly three inputs: ' ...
             'RunConfig, Scenario, and Timeline.']);
    end

    if ~isstruct(RunConfig) || ~isscalar(RunConfig)
        error( ...
            'Block7:BuildJSBSimScript:InvalidRunConfig', ...
            'RunConfig must be a scalar structure.');
    end

    if ~isstruct(Scenario) || ~isscalar(Scenario)
        error( ...
            'Block7:BuildJSBSimScript:InvalidScenario', ...
            'Scenario must be a scalar structure.');
    end

    if ~isstruct(Timeline) || ~isscalar(Timeline)
        error( ...
            'Block7:BuildJSBSimScript:InvalidTimeline', ...
            'Timeline must be a scalar structure.');
    end

    if ~isfield(RunConfig, 'ScriptFile') || ...
            isempty(RunConfig.ScriptFile)

        error( ...
            'Block7:BuildJSBSimScript:MissingScriptFile', ...
            'RunConfig.ScriptFile is required.');
    end

    if ~isfield(RunConfig, 'InitFile') || ...
            isempty(RunConfig.InitFile)

        error( ...
            'Block7:BuildJSBSimScript:MissingInitFile', ...
            'RunConfig.InitFile is required.');
    end

    if ~isfield(RunConfig, 'Duration_s') || ...
            ~isscalar(RunConfig.Duration_s) || ...
            ~isnumeric(RunConfig.Duration_s) || ...
            ~isfinite(RunConfig.Duration_s) || ...
            RunConfig.Duration_s < 0

        error( ...
            'Block7:BuildJSBSimScript:InvalidDuration', ...
            'RunConfig.Duration_s must be a finite non-negative scalar.');
    end

    if ~isfield(RunConfig, 'Aircraft') || ...
            isempty(RunConfig.Aircraft)

        error( ...
            'Block7:BuildJSBSimScript:MissingAircraft', ...
            'RunConfig.Aircraft is required.');
    end

    if ~isfield(Timeline, 'Time_s') || ...
            isempty(Timeline.Time_s)

        error( ...
            'Block7:BuildJSBSimScript:MissingTimelineTime', ...
            'Timeline.Time_s is required.');
    end

    if ~isfield(Timeline, 'SampleTime_s') || ...
            isempty(Timeline.SampleTime_s)

        error( ...
            'Block7:BuildJSBSimScript:MissingSampleTime', ...
            'Timeline.SampleTime_s is required.');
    end

    Time_s = Timeline.Time_s(:);

    if ~isnumeric(Time_s) || ...
            any(~isfinite(Time_s)) || ...
            any(diff(Time_s) <= 0)

        error( ...
            'Block7:BuildJSBSimScript:InvalidTimelineTime', ...
            'Timeline.Time_s must be finite and strictly increasing.');
    end

    SampleTime_s = Timeline.SampleTime_s;

    if ~isscalar(SampleTime_s) || ...
            ~isnumeric(SampleTime_s) || ...
            ~isfinite(SampleTime_s) || ...
            SampleTime_s <= 0

        error( ...
            'Block7:BuildJSBSimScript:InvalidSampleTime', ...
            'Timeline.SampleTime_s must be a positive finite scalar.');
    end

    %% Resolve Paths

    ScriptFile = char(RunConfig.ScriptFile);

    [ScriptDirectory, ~, ~] = fileparts(ScriptFile);

    if isempty(ScriptDirectory)
        error( ...
            'Block7:BuildJSBSimScript:InvalidScriptPath', ...
            'RunConfig.ScriptFile must include a directory path.');
    end

    if ~isfolder(ScriptDirectory)
        mkdir(ScriptDirectory);
    end

    InitFile = char(RunConfig.InitFile);

InitReference = strrep( ...
    InitFile, ...
    '\', ...
    '/');

    %% Build Script XML

    AircraftName = char(string(RunConfig.Aircraft));

    EndTime_s = RunConfig.Duration_s;

    XMLLines = {
        '<?xml version="1.0" encoding="UTF-8"?>'
        '<runscript name="Block7GroundTruthRun">'
        '  <description>'
        '    Block 7 generated JSBSim ground-truth execution script.'
        '  </description>'
        ''
        sprintf('  <use aircraft="%s" initialize="%s">', ...
            AircraftName, ...
            InitReference)
        '  </use>'
        ''
        sprintf( ...
            '  <run start="0.0" end="%.15g" dt="%.15g">', ...
            EndTime_s, ...
            SampleTime_s)
        '  </run>'
        ''
        '</runscript>'
        };

    %% Write Script

    FileID = fopen( ...
        ScriptFile, ...
        'w');

    if FileID == -1
        error( ...
            'Block7:BuildJSBSimScript:FileOpenFailed', ...
            'Unable to open script file for writing: %s', ...
            ScriptFile);
    end

    CleanupObject = onCleanup(@() fclose(FileID));

    for LineIndex = 1:numel(XMLLines)

        fprintf( ...
            FileID, ...
            '%s\n', ...
            XMLLines{LineIndex});

    end

    clear CleanupObject;

    %% Final Verification

    if ~isfile(ScriptFile)
        error( ...
            'Block7:BuildJSBSimScript:FileCreationFailed', ...
            'JSBSim script file was not created successfully.');
    end

end