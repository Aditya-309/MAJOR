function TelemetryFile = RunJSBSim( ...
    RunConfig, ...
    ScriptFile)
%RUNJSBSIM Execute JSBSim and generate Block 7 ground-truth telemetry.
%
%   TelemetryFile = RunJSBSim(RunConfig, ScriptFile)
%
%   Executes JSBSim using the generated run script and output directive.
%   The generated telemetry is collected from the JSBSim installation
%   output location and placed in RunConfig.TelemetryFile.

    %% Input Validation

    if nargin ~= 2
        error( ...
            'Block7:RunJSBSim:InvalidInputCount', ...
            'RunJSBSim requires exactly two inputs: RunConfig and ScriptFile.');
    end

    if ~isstruct(RunConfig) || ~isscalar(RunConfig)
        error( ...
            'Block7:RunJSBSim:InvalidRunConfig', ...
            'RunConfig must be a scalar structure.');
    end

    if ~(ischar(ScriptFile) || ...
            (isstring(ScriptFile) && isscalar(ScriptFile)))

        error( ...
            'Block7:RunJSBSim:InvalidScriptFile', ...
            'ScriptFile must be a character vector or scalar string.');
    end

    ScriptFile = char(ScriptFile);

    if ~isfile(ScriptFile)
        error( ...
            'Block7:RunJSBSim:ScriptFileNotFound', ...
            'JSBSim script file does not exist: %s', ...
            ScriptFile);
    end

    RequiredFields = { ...
        'ProjectRoot', ...
        'TelemetryFile', ...
        'OutputFile'};

    for FieldIndex = 1:numel(RequiredFields)

        FieldName = RequiredFields{FieldIndex};

        if ~isfield(RunConfig, FieldName) || ...
                isempty(RunConfig.(FieldName))

            error( ...
                'Block7:RunJSBSim:MissingRunConfigField', ...
                'RunConfig.%s is required.', ...
                FieldName);
        end

    end

    ProjectRoot = char(RunConfig.ProjectRoot);
    TelemetryFile = char(RunConfig.TelemetryFile);
    OutputFile = char(RunConfig.OutputFile);

    if ~isfolder(ProjectRoot)
        error( ...
            'Block7:RunJSBSim:InvalidProjectRoot', ...
            'ProjectRoot does not exist: %s', ...
            ProjectRoot);
    end

    if ~isfile(OutputFile)
        error( ...
            'Block7:RunJSBSim:OutputFileNotFound', ...
            'JSBSim output definition does not exist: %s', ...
            OutputFile);
    end

    [TelemetryDirectory, ...
     TelemetryName, ...
     TelemetryExtension] = ...
        fileparts(TelemetryFile);

    if isempty(TelemetryDirectory)
        error( ...
            'Block7:RunJSBSim:InvalidTelemetryPath', ...
            'TelemetryFile must include a directory path.');
    end

    if ~strcmpi(TelemetryExtension, '.csv')
        error( ...
            'Block7:RunJSBSim:InvalidTelemetryExtension', ...
            'TelemetryFile must use the .csv extension.');
    end

    if ~isfolder(TelemetryDirectory)
        mkdir(TelemetryDirectory);
    end

    %% Resolve JSBSim Installation

    JSBSimExecutable = ...
        'C:\Users\lalit\AppData\Local\JSBSim\JSBSim.exe';

    if ~isfile(JSBSimExecutable)
        error( ...
            'Block7:RunJSBSim:ExecutableNotFound', ...
            'JSBSim executable was not found: %s', ...
            JSBSimExecutable);
    end

    JSBSimRoot = ...
        fileparts(JSBSimExecutable);

    %% Resolve JSBSim Output Location

    OutputName = ...
        [TelemetryName TelemetryExtension];

    JSBSimTelemetryFile = ...
        fullfile( ...
            JSBSimRoot, ...
            OutputName);

    %% Remove Previous Files

    if isfile(TelemetryFile)
        delete(TelemetryFile);
    end

    if isfile(JSBSimTelemetryFile)
        delete(JSBSimTelemetryFile);
    end

    %% Build JSBSim Command

    ScriptReference = ...
        strrep(ScriptFile, '\', '/');

    OutputReference = ...
        strrep(OutputFile, '\', '/');

    JSBSimRootReference = ...
        strrep(JSBSimRoot, '\', '/');

    Command = sprintf( ...
        ['"%s" ' ...
         '--root="%s" ' ...
         '--script="%s" ' ...
         '--logdirectivefile="%s" ' ...
         '--outputlogfile="%s"'], ...
        JSBSimExecutable, ...
        JSBSimRootReference, ...
        ScriptReference, ...
        OutputReference, ...
        OutputName);

    %% Execute JSBSim

    [Status, CommandOutput] = ...
        system(Command);

    if Status ~= 0
        error( ...
            'Block7:RunJSBSim:ExecutionFailed', ...
            ['JSBSim execution failed.\n\n' ...
             'Command:\n%s\n\n' ...
             'Output:\n%s'], ...
            Command, ...
            CommandOutput);
    end

    %% Validate JSBSim Output

    if ~isfile(JSBSimTelemetryFile)
        error( ...
            'Block7:RunJSBSim:TelemetryNotGenerated', ...
            ['JSBSim completed successfully, but no telemetry ' ...
             'file was generated at:\n%s\n\n' ...
             'JSBSim output:\n%s'], ...
            JSBSimTelemetryFile, ...
            CommandOutput);
    end

    FileInfo = dir(JSBSimTelemetryFile);

    if FileInfo.bytes <= 0
        error( ...
            'Block7:RunJSBSim:EmptyTelemetryFile', ...
            'JSBSim generated an empty telemetry file: %s', ...
            JSBSimTelemetryFile);
    end

    %% Move Telemetry Into Block 7 Run Directory

    [MoveStatus, MoveMessage] = ...
        movefile( ...
            JSBSimTelemetryFile, ...
            TelemetryFile, ...
            'f');

    if ~MoveStatus
        error( ...
            'Block7:RunJSBSim:TelemetryMoveFailed', ...
            ['JSBSim generated telemetry successfully, but it ' ...
             'could not be moved to the Block 7 run directory.\n\n' ...
             'Source: %s\n' ...
             'Destination: %s\n\n' ...
             'Reason: %s'], ...
            JSBSimTelemetryFile, ...
            TelemetryFile, ...
            MoveMessage);
    end

    %% Final Verification

    if ~isfile(TelemetryFile)
        error( ...
            'Block7:RunJSBSim:TelemetryNotAvailable', ...
            'Telemetry file is missing after collection: %s', ...
            TelemetryFile);
    end

    FileInfo = dir(TelemetryFile);

    if FileInfo.bytes <= 0
        error( ...
            'Block7:RunJSBSim:EmptyCollectedTelemetry', ...
            'Collected telemetry file is empty: %s', ...
            TelemetryFile);
    end

end