function ValidateSensorNoiseConfig(Config)
% noisemodels.ValidateSensorNoiseConfig
%
% Validate the frozen Block 5 sensor-noise configuration.
%
% This function performs validation only. It does not:
%   - modify Config
%   - generate random numbers
%   - generate sensor noise
%   - apply sensor corruption
%   - implement outages or faults
%   - implement estimator/trust logic
%
% Usage:
%   noisemodels.ValidateSensorNoiseConfig(Config)
%
% Successful validation returns silently.

    %% Input validation

    if nargin ~= 1
        error('noisemodels:ValidateSensorNoiseConfig:InvalidInputCount', ...
            'Exactly one input, Config, is required.');
    end

    if ~isstruct(Config) || ~isscalar(Config)
        error('noisemodels:ValidateSensorNoiseConfig:InvalidConfig', ...
            'Config must be a scalar structure.');
    end

    %% Required top-level fields

    ValidateRequiredFields(Config, { ...
        'RandomSeed', ...
        'Corruption', ...
        'GNSS', ...
        'IMU', ...
        'Airspeed', ...
        'Magnetometer'}, ...
        'Config');

    %% Random seed

    ValidateFiniteScalar( ...
        Config.RandomSeed, ...
        'Config.RandomSeed');

    if Config.RandomSeed < 0 || ...
            Config.RandomSeed ~= floor(Config.RandomSeed)

        error('noisemodels:ValidateSensorNoiseConfig:InvalidRandomSeed', ...
            'Config.RandomSeed must be a nonnegative integer.');
    end

    %% Corruption configuration

    ValidateScalarStruct( ...
        Config.Corruption, ...
        'Config.Corruption');

    ValidateRequiredFields(Config.Corruption, { ...
        'GNSS', ...
        'IMU', ...
        'Airspeed', ...
        'Magnetometer'}, ...
        'Config.Corruption');

    CorruptionNames = { ...
        'GNSS', ...
        'IMU', ...
        'Airspeed', ...
        'Magnetometer'};

    for k = 1:numel(CorruptionNames)

        Name = CorruptionNames{k};
        Value = Config.Corruption.(Name);

        ValidateFiniteScalar( ...
            Value, ...
            sprintf('Config.Corruption.%s', Name));

        if Value < 0 || Value > 100

            error( ...
                'noisemodels:ValidateSensorNoiseConfig:InvalidCorruption', ...
                'Config.Corruption.%s must be between 0 and 100 percent.', ...
                Name);
        end
    end

    %% GNSS configuration

    ValidateScalarStruct(Config.GNSS, 'Config.GNSS');

    ValidateRequiredFields(Config.GNSS, { ...
        'HorizontalNoiseSigma_m', ...
        'VerticalNoiseSigma_m', ...
        'VelocityNoiseSigma_mps', ...
        'BiasSigmaHorizontal_m', ...
        'BiasSigmaVertical_m', ...
        'BiasCorrelationTime_s'}, ...
        'Config.GNSS');

    ValidateNonnegativeScalar( ...
        Config.GNSS.HorizontalNoiseSigma_m, ...
        'Config.GNSS.HorizontalNoiseSigma_m');

    ValidateNonnegativeScalar( ...
        Config.GNSS.VerticalNoiseSigma_m, ...
        'Config.GNSS.VerticalNoiseSigma_m');

    ValidateNonnegativeScalar( ...
        Config.GNSS.VelocityNoiseSigma_mps, ...
        'Config.GNSS.VelocityNoiseSigma_mps');

    ValidateNonnegativeScalar( ...
        Config.GNSS.BiasSigmaHorizontal_m, ...
        'Config.GNSS.BiasSigmaHorizontal_m');

    ValidateNonnegativeScalar( ...
        Config.GNSS.BiasSigmaVertical_m, ...
        'Config.GNSS.BiasSigmaVertical_m');

    ValidatePositiveScalar( ...
        Config.GNSS.BiasCorrelationTime_s, ...
        'Config.GNSS.BiasCorrelationTime_s');

    %% IMU configuration

    ValidateScalarStruct(Config.IMU, 'Config.IMU');

    ValidateRequiredFields(Config.IMU, { ...
        'GyroTurnOnBiasSigma_radps', ...
        'GyroInRunBiasSigma_radps', ...
        'GyroInRunBiasCorrelationTime_s', ...
        'GyroARW_radpsSqrtHz', ...
        'GyroScaleFactorSigma', ...
        'AccelTurnOnBiasSigma_mps2', ...
        'AccelInRunBiasSigma_mps2', ...
        'AccelInRunBiasCorrelationTime_s', ...
        'AccelVRW_mps2SqrtHz', ...
        'AccelScaleFactorSigma'}, ...
        'Config.IMU');

    ValidateNonnegativeScalar( ...
        Config.IMU.GyroTurnOnBiasSigma_radps, ...
        'Config.IMU.GyroTurnOnBiasSigma_radps');

    ValidateNonnegativeScalar( ...
        Config.IMU.GyroInRunBiasSigma_radps, ...
        'Config.IMU.GyroInRunBiasSigma_radps');

    ValidatePositiveScalar( ...
        Config.IMU.GyroInRunBiasCorrelationTime_s, ...
        'Config.IMU.GyroInRunBiasCorrelationTime_s');

    ValidateNonnegativeScalar( ...
        Config.IMU.GyroARW_radpsSqrtHz, ...
        'Config.IMU.GyroARW_radpsSqrtHz');

    ValidateNonnegativeScalar( ...
        Config.IMU.GyroScaleFactorSigma, ...
        'Config.IMU.GyroScaleFactorSigma');

    ValidateNonnegativeScalar( ...
        Config.IMU.AccelTurnOnBiasSigma_mps2, ...
        'Config.IMU.AccelTurnOnBiasSigma_mps2');

    ValidateNonnegativeScalar( ...
        Config.IMU.AccelInRunBiasSigma_mps2, ...
        'Config.IMU.AccelInRunBiasSigma_mps2');

    ValidatePositiveScalar( ...
        Config.IMU.AccelInRunBiasCorrelationTime_s, ...
        'Config.IMU.AccelInRunBiasCorrelationTime_s');

    ValidateNonnegativeScalar( ...
        Config.IMU.AccelVRW_mps2SqrtHz, ...
        'Config.IMU.AccelVRW_mps2SqrtHz');

    ValidateNonnegativeScalar( ...
        Config.IMU.AccelScaleFactorSigma, ...
        'Config.IMU.AccelScaleFactorSigma');

    %% Airspeed configuration

    ValidateScalarStruct( ...
        Config.Airspeed, ...
        'Config.Airspeed');

    ValidateRequiredFields(Config.Airspeed, { ...
        'NoiseSigma_mps'}, ...
        'Config.Airspeed');

    ValidateNonnegativeScalar( ...
        Config.Airspeed.NoiseSigma_mps, ...
        'Config.Airspeed.NoiseSigma_mps');

    %% Magnetometer configuration

    ValidateScalarStruct( ...
        Config.Magnetometer, ...
        'Config.Magnetometer');

    ValidateRequiredFields(Config.Magnetometer, { ...
        'NoiseSigma_uT'}, ...
        'Config.Magnetometer');

    ValidateNonnegativeScalar( ...
        Config.Magnetometer.NoiseSigma_uT, ...
        'Config.Magnetometer.NoiseSigma_uT');

end


%% Local validation helpers

function ValidateRequiredFields(S, RequiredFields, SectionName)

    for k = 1:numel(RequiredFields)

        Name = RequiredFields{k};

        if ~isfield(S, Name)

            error( ...
                'noisemodels:ValidateSensorNoiseConfig:MissingField', ...
                '%s is missing required field "%s".', ...
                SectionName, Name);

        end
    end
end


function ValidateScalarStruct(Value, Name)

    if ~isstruct(Value) || ~isscalar(Value)

        error( ...
            'noisemodels:ValidateSensorNoiseConfig:InvalidSection', ...
            '%s must be a scalar structure.', Name);

    end
end


function ValidateFiniteScalar(Value, Name)

    if ~(isnumeric(Value) && ...
            isreal(Value) && ...
            isscalar(Value) && ...
            isfinite(Value))

        error( ...
            'noisemodels:ValidateSensorNoiseConfig:InvalidValue', ...
            '%s must be a finite real numeric scalar.', Name);

    end
end


function ValidateNonnegativeScalar(Value, Name)

    ValidateFiniteScalar(Value, Name);

    if Value < 0

        error( ...
            'noisemodels:ValidateSensorNoiseConfig:NegativeValue', ...
            '%s must be nonnegative.', Name);

    end
end


function ValidatePositiveScalar(Value, Name)

    ValidateFiniteScalar(Value, Name);

    if Value <= 0

        error( ...
            'noisemodels:ValidateSensorNoiseConfig:NonpositiveValue', ...
            '%s must be greater than zero.', Name);

    end
end

