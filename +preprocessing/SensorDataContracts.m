function Contracts = SensorDataContracts()
%SENSORDATACONTRACTS Canonical Block 9 sensor data contracts.
%
%   Contracts = SENSORDATACONTRACTS() returns the canonical data contracts
%   used by the Block 9 preprocessing pipeline.
%
%   Fields:
%       Contracts.Version       - contract version
%       Contracts.Streams       - canonical stream names (cell array)
%       Contracts.AuditFields   - per-row audit columns preserved by Block 9
%       Contracts.<StreamName>  - per-stream contract:
%           .Files              - source folder and file names
%           .Channels           - canonical channel definitions
%           .RateFallback_Hz    - code-default reference sample rate
%           .RateFallbackSource - provenance text for the fallback rate
%
%   Each channel definition contains:
%       CanonicalField    - canonical field name used in Block 9 outputs
%       Unit              - canonical SI unit of the canonical field
%       SourceUnit        - unit of the source values
%       ScaleToCanonical  - factor applied to source values
%       IdealCsvField     - field name in ideal sensor CSV files
%                         ('' = not present in ideal CSV files)
%       RealisticCsvField - field name in realistic sensor CSV files
%       MatField          - field name in the sensor MAT structures
%       MatColumn         - column index for Nx3 MAT fields (0 = scalar)
%
%   Naming dialects follow the frozen Block 4 and Block 8 artifacts. The
%   magnetic field source values are in microtesla and are scaled to tesla
%   (canonical unit T).
%
%   RateFallback_Hz values mirror +sensormodels/SensorConfig.m. They are a
%   documented code-default reference only and are never treated as proof
%   of historical run sample rates (see
%   PreprocessingConfig.Timestamps.NominalRateSource for the provenance
%   chain: recorded per-run configuration, then measured timestamps, then
%   this code default).
%
%   INTERNAL function. Not part of the public Block 9 API. The public API
%   is DiscoverRuns, InspectRun, PreprocessRun and GetPreprocessingReport.
%
%   See also: NormalizeSensorSchema, NormalizeSensorUnits, QualityFlags.

    %% Top-Level Contracts

    Contracts = struct();
    Contracts.Version = '1.0';
    Contracts.Streams = {'IMU', 'GNSS', 'AirData', 'Magnetometer'};
    Contracts.AuditFields = {'SourceRowIdx', 'SourceTime_s'};

    StreamFiles = struct( ...
        'IdealCsvFolder', 'IdealSensorTelemetry', ...
        'RealisticCsvFolder', 'RealisticSensorTelemetry', ...
        'IdealMatFile', 'IdealSensorTelemetry.mat', ...
        'RealisticMatFile', 'RealisticSensorTelemetry.mat', ...
        'IdealMatVariable', 'IdealSensorTelemetryToSave', ...
        'RealisticMatVariable', 'RealisticSensorTelemetry');

    RateFallbackSource = [ ...
        'CodeDefault reference mirroring +sensormodels/SensorConfig.m; ', ...
        'not evidence of historical run sample rates'];

    %% IMU Contract

    IMU = struct();
    IMU.Files = withCsvFile(StreamFiles, 'IMU.csv');
    IMU.Channels = [ ...
        channelEntry('Time_s', 's', 1, 's', ...
            'Time_s', 'Time_s', 'Time_s', 0); ...
        channelEntry('Accelerometer_X_mps2', 'm/s^2', 1, 'm/s^2', ...
            'Accelerometer_X_mps2', 'AccelerometerX_mps2', ...
            'Accelerometer_mps2', 1); ...
        channelEntry('Accelerometer_Y_mps2', 'm/s^2', 1, 'm/s^2', ...
            'Accelerometer_Y_mps2', 'AccelerometerY_mps2', ...
            'Accelerometer_mps2', 2); ...
        channelEntry('Accelerometer_Z_mps2', 'm/s^2', 1, 'm/s^2', ...
            'Accelerometer_Z_mps2', 'AccelerometerZ_mps2', ...
            'Accelerometer_mps2', 3); ...
        channelEntry('Gyroscope_X_radps', 'rad/s', 1, 'rad/s', ...
            'Gyroscope_X_radps', 'GyroscopeX_radps', ...
            'Gyroscope_radps', 1); ...
        channelEntry('Gyroscope_Y_radps', 'rad/s', 1, 'rad/s', ...
            'Gyroscope_Y_radps', 'GyroscopeY_radps', ...
            'Gyroscope_radps', 2); ...
        channelEntry('Gyroscope_Z_radps', 'rad/s', 1, 'rad/s', ...
            'Gyroscope_Z_radps', 'GyroscopeZ_radps', ...
            'Gyroscope_radps', 3); ...
        channelEntry('Available', '1', 1, '1', ...
            '', 'Available', 'Available', 0)];
    IMU.RateFallback_Hz = 100.0;
    IMU.RateFallbackSource = RateFallbackSource;

    %% GNSS Contract

    GNSS = struct();
    GNSS.Files = withCsvFile(StreamFiles, 'GNSS.csv');
    GNSS.Channels = [ ...
        channelEntry('Time_s', 's', 1, 's', ...
            'Time_s', 'Time_s', 'Time_s', 0); ...
        channelEntry('Latitude_rad', 'rad', 1, 'rad', ...
            'Latitude_rad', 'Latitude_rad', 'Latitude_rad', 0); ...
        channelEntry('Longitude_rad', 'rad', 1, 'rad', ...
            'Longitude_rad', 'Longitude_rad', 'Longitude_rad', 0); ...
        channelEntry('Altitude_m', 'm', 1, 'm', ...
            'Altitude_m', 'Altitude_m', 'Altitude_m', 0); ...
        channelEntry('Velocity_North_mps', 'm/s', 1, 'm/s', ...
            'Velocity_North_mps', 'VelocityNorth_mps', ...
            'Velocity_NED_mps', 1); ...
        channelEntry('Velocity_East_mps', 'm/s', 1, 'm/s', ...
            'Velocity_East_mps', 'VelocityEast_mps', ...
            'Velocity_NED_mps', 2); ...
        channelEntry('Velocity_Down_mps', 'm/s', 1, 'm/s', ...
            'Velocity_Down_mps', 'VelocityDown_mps', ...
            'Velocity_NED_mps', 3); ...
        channelEntry('Available', '1', 1, '1', ...
            '', 'Available', 'Available', 0)];
    GNSS.RateFallback_Hz = 10.0;
    GNSS.RateFallbackSource = RateFallbackSource;

    %% AirData Contract

    AirData = struct();
    AirData.Files = withCsvFile(StreamFiles, 'AirData.csv');
    AirData.Channels = [ ...
        channelEntry('Time_s', 's', 1, 's', ...
            'Time_s', 'Time_s', 'Time_s', 0); ...
        channelEntry('TrueAirspeed_mps', 'm/s', 1, 'm/s', ...
            'TrueAirspeed_mps', 'TrueAirspeed_mps', ...
            'TrueAirspeed_mps', 0); ...
        channelEntry('DynamicPressure_Pa', 'Pa', 1, 'Pa', ...
            'DynamicPressure_Pa', 'DynamicPressure_Pa', ...
            'DynamicPressure_Pa', 0); ...
        channelEntry('Available', '1', 1, '1', ...
            '', 'Available', 'Available', 0)];
    AirData.RateFallback_Hz = 50.0;
    AirData.RateFallbackSource = RateFallbackSource;

    %% Magnetometer Contract

    Magnetometer = struct();
    Magnetometer.Files = withCsvFile(StreamFiles, 'Magnetometer.csv');
    Magnetometer.Channels = [ ...
        channelEntry('Time_s', 's', 1, 's', ...
            'Time_s', 'Time_s', 'Time_s', 0); ...
        channelEntry('MagneticFieldBody_X_T', 'T', 1.0e-6, 'uT', ...
            'MagneticFieldBody_X_uT', 'MagneticFieldX_uT', ...
            'MagneticFieldBody_uT', 1); ...
        channelEntry('MagneticFieldBody_Y_T', 'T', 1.0e-6, 'uT', ...
            'MagneticFieldBody_Y_uT', 'MagneticFieldY_uT', ...
            'MagneticFieldBody_uT', 2); ...
        channelEntry('MagneticFieldBody_Z_T', 'T', 1.0e-6, 'uT', ...
            'MagneticFieldBody_Z_uT', 'MagneticFieldZ_uT', ...
            'MagneticFieldBody_uT', 3); ...
        channelEntry('Available', '1', 1, '1', ...
            '', 'Available', 'Available', 0)];
    Magnetometer.RateFallback_Hz = 50.0;
    Magnetometer.RateFallbackSource = RateFallbackSource;

    Contracts.IMU = IMU;
    Contracts.GNSS = GNSS;
    Contracts.AirData = AirData;
    Contracts.Magnetometer = Magnetometer;

    %% Self-Check

    for Index = 1:numel(Contracts.Streams)

        StreamName = Contracts.Streams{Index};
        Stream = Contracts.(StreamName);
        ChannelNames = {Stream.Channels.CanonicalField};

        if numel(unique(ChannelNames)) ~= numel(ChannelNames)

            error( ...
                'Preprocessing:SensorDataContracts:DuplicateCanonicalField', ...
                'Stream "%s" defines duplicate canonical fields.', ...
                StreamName);

        end

        if ~all(ismember({'Time_s', 'Available'}, ChannelNames))

            error( ...
                'Preprocessing:SensorDataContracts:MissingAuditChannel', ...
                ['Stream "%s" must define the Time_s and Available ', ...
                 'channels.'], ...
                StreamName);

        end

    end

end

% =========================================================================
%% LOCAL HELPERS
% =========================================================================

function Channel = channelEntry( ...
    CanonicalField, ...
    Unit, ...
    ScaleToCanonical, ...
    SourceUnit, ...
    IdealCsvField, ...
    RealisticCsvField, ...
    MatField, ...
    MatColumn)
%CHANNELENTRY Build one canonical channel definition.

    Channel = struct( ...
        'CanonicalField', CanonicalField, ...
        'Unit', Unit, ...
        'ScaleToCanonical', ScaleToCanonical, ...
        'SourceUnit', SourceUnit, ...
        'IdealCsvField', IdealCsvField, ...
        'RealisticCsvField', RealisticCsvField, ...
        'MatField', MatField, ...
        'MatColumn', MatColumn);

end

function Files = withCsvFile(StreamFiles, CsvFileName)
%WITHCSVFILE Attach the per-stream CSV file name to the shared file map.

    Files = StreamFiles;
    Files.IdealCsvFile = CsvFileName;
    Files.RealisticCsvFile = CsvFileName;

end
