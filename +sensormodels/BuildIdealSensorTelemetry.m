function SensorTelemetry = BuildIdealSensorTelemetry( ...
    GroundTruth, ...
    SensorConfig, ...
    Scenario)
%BUILDIDEALSENSORTELEMETRY Build complete deterministic ideal sensor data.
%
%   SensorTelemetry = BUILDIDEALSENSORTELEMETRY( ...
%       GroundTruth, SensorConfig, Scenario)
%
%   builds complete deterministic multi-rate ideal sensor telemetry from
%   frozen GroundTruth data, validated sensor configuration, and the
%   validated Block 6 flight scenario.
%
%   Block 4 generates ideal deterministic measurements only.
%   No noise, bias, random walk, scale factor, misalignment, quantization,
%   saturation, latency, dropout, outage, or fault behavior is introduced.

    %% Validate Inputs

    sensormodels.ValidateSensorConfig(SensorConfig);

    if ~isstruct(GroundTruth) || ~isscalar(GroundTruth)

        error( ...
            'ASRTE:IdealSensorTelemetry:InvalidGroundTruthStructure', ...
            'GroundTruth must be a scalar structure.');

    end

    if ~isstruct(Scenario) || ~isscalar(Scenario)

        error( ...
            'ASRTE:IdealSensorTelemetry:InvalidScenarioStructure', ...
            'Scenario must be a scalar structure.');

    end

    RequiredGroundTruthFields = ...
        {'Time_s', 'SampleCount'};

    MissingFields = ...
        RequiredGroundTruthFields( ...
            ~isfield(GroundTruth, RequiredGroundTruthFields));

    if ~isempty(MissingFields)

        error( ...
            'ASRTE:IdealSensorTelemetry:MissingGroundTruthField', ...
            'GroundTruth is missing required field(s): %s.', ...
            strjoin(MissingFields, ', '));

    end

    GroundTruthTime_s = GroundTruth.Time_s;

    if ~isnumeric(GroundTruthTime_s) || ...
            ~isreal(GroundTruthTime_s) || ...
            ~isvector(GroundTruthTime_s) || ...
            numel(GroundTruthTime_s) < 2 || ...
            any(~isfinite(GroundTruthTime_s))

        error( ...
            'ASRTE:IdealSensorTelemetry:InvalidGroundTruthTime', ...
            ['GroundTruth.Time_s must be a finite real vector ', ...
             'containing at least two samples.']);

    end

    GroundTruthTime_s = GroundTruthTime_s(:);

    if any(diff(GroundTruthTime_s) <= 0)

        error( ...
            'ASRTE:IdealSensorTelemetry:NonIncreasingGroundTruthTime', ...
            'GroundTruth.Time_s must be strictly increasing.');

    end

    if ~isnumeric(GroundTruth.SampleCount) || ...
            ~isreal(GroundTruth.SampleCount) || ...
            ~isscalar(GroundTruth.SampleCount) || ...
            ~isfinite(GroundTruth.SampleCount) || ...
            GroundTruth.SampleCount ~= numel(GroundTruthTime_s)

        error( ...
            'ASRTE:IdealSensorTelemetry:InvalidGroundTruthSampleCount', ...
            ['GroundTruth.SampleCount must equal the number of ', ...
             'GroundTruth.Time_s samples.']);

    end

    %% Build GNSS

    GNSSTimeline = ...
        sensormodels.BuildSensorTimeline( ...
            GroundTruth, ...
            SensorConfig.GNSS.SampleRate_Hz);

    GNSS = ...
        sensormodels.GenerateIdealGNSS( ...
            GroundTruth, ...
            GNSSTimeline);

    %% Build IMU

    IMUTimeline = ...
        sensormodels.BuildSensorTimeline( ...
            GroundTruth, ...
            SensorConfig.IMU.SampleRate_Hz);

    IMU = ...
        sensormodels.GenerateIdealIMU( ...
            GroundTruth, ...
            IMUTimeline);

    %% Build Air Data

    AirDataTimeline = ...
        sensormodels.BuildSensorTimeline( ...
            GroundTruth, ...
            SensorConfig.AirData.SampleRate_Hz);

    AirData = ...
        sensormodels.GenerateIdealAirData( ...
            GroundTruth, ...
            AirDataTimeline, ...
            Scenario);

    %% Build Magnetometer

    MagnetometerTimeline = ...
        sensormodels.BuildSensorTimeline( ...
            GroundTruth, ...
            SensorConfig.Magnetometer.SampleRate_Hz);

    Magnetometer = ...
        sensormodels.GenerateIdealMagnetometer( ...
            GroundTruth, ...
            MagnetometerTimeline);

    %% Build Output

    SensorTelemetry = struct();

    SensorTelemetry.GNSS = GNSS;
    SensorTelemetry.IMU = IMU;
    SensorTelemetry.AirData = AirData;
    SensorTelemetry.Magnetometer = Magnetometer;

end