function AirData = GenerateIdealAirData(GroundTruth, Timeline, Scenario)
%GENERATEIDEALAIRDATA Generate ideal air-data measurements.
%
%   AirData = sensormodels.GenerateIdealAirData( ...
%       GroundTruth, Timeline, Scenario)
%
%   Generates ideal true airspeed and dynamic pressure from:
%       - Block 7 body velocity and air density
%       - Block 2 attitude transformations
%       - Block 6 authoritative wind profile
%
%   No random noise, bias, corruption, outage, or fault generation is
%   performed in this function.

    %% Input validation

    RequiredGroundTruthFields = { ...
        'Time_s', ...
        'VelocityBody_mps', ...
        'Euler_rad', ...
        'AirDensity_kgpm3'};

    for FieldIndex = 1:numel(RequiredGroundTruthFields)

        FieldName = RequiredGroundTruthFields{FieldIndex};

        if ~isfield(GroundTruth, FieldName)
            error( ...
                'sensormodels:GenerateIdealAirData:MissingGroundTruthField', ...
                'GroundTruth.%s is required.', ...
                FieldName);
        end
    end

    RequiredTimelineFields = { ...
        'Time_s', ...
        'SampleRate_Hz', ...
        'SampleCount'};

    for FieldIndex = 1:numel(RequiredTimelineFields)

        FieldName = RequiredTimelineFields{FieldIndex};

        if ~isfield(Timeline, FieldName)
            error( ...
                'sensormodels:GenerateIdealAirData:MissingTimelineField', ...
                'Timeline.%s is required.', ...
                FieldName);
        end
    end

    RequiredScenarioFields = { ...
        'Wind', ...
        'Events'};

    for FieldIndex = 1:numel(RequiredScenarioFields)

        FieldName = RequiredScenarioFields{FieldIndex};

        if ~isfield(Scenario, FieldName)
            error( ...
                'sensormodels:GenerateIdealAirData:MissingScenarioField', ...
                'Scenario.%s is required.', ...
                FieldName);
        end
    end

    if ~isfield(Scenario.Wind, 'ConstantNED_mps')
        error( ...
            'sensormodels:GenerateIdealAirData:MissingWindField', ...
            'Scenario.Wind.ConstantNED_mps is required.');
    end

    if ~isfield(Scenario.Wind, 'Gust') || ...
            ~isfield(Scenario.Wind.Gust, 'Enabled') || ...
            ~isfield(Scenario.Wind.Gust, 'PeakNED_mps')

        error( ...
            'sensormodels:GenerateIdealAirData:MissingGustField', ...
            ['Scenario.Wind.Gust.Enabled and ' ...
             'Scenario.Wind.Gust.PeakNED_mps are required.']);
    end

    if ~isfield(Scenario.Events, 'WindDisturbance') || ...
            ~isfield(Scenario.Events.WindDisturbance, 'Enabled') || ...
            ~isfield(Scenario.Events.WindDisturbance, 'StartTime_s') || ...
            ~isfield(Scenario.Events.WindDisturbance, 'EndTime_s')

        error( ...
            'sensormodels:GenerateIdealAirData:MissingWindDisturbanceField', ...
            ['Scenario.Events.WindDisturbance.Enabled, StartTime_s, ' ...
             'and EndTime_s are required.']);
    end

    %% Extract source data

    GroundTruthTime_s = GroundTruth.Time_s(:);
    GroundTruthVelocityBody_mps = GroundTruth.VelocityBody_mps;
    GroundTruthEuler_rad = GroundTruth.Euler_rad;
    GroundTruthAirDensity_kgpm3 = GroundTruth.AirDensity_kgpm3(:);

    SensorTime_s = Timeline.Time_s(:);

    GroundTruthSampleCount = numel(GroundTruthTime_s);
    SensorSampleCount = Timeline.SampleCount;

    if size(GroundTruthVelocityBody_mps, 1) ~= ...
            GroundTruthSampleCount

        error( ...
            'sensormodels:GenerateIdealAirData:VelocitySizeMismatch', ...
            ['GroundTruth.VelocityBody_mps must have one row per ' ...
             'GroundTruth.Time_s sample.']);
    end

    if size(GroundTruthVelocityBody_mps, 2) ~= 3

        error( ...
            'sensormodels:GenerateIdealAirData:InvalidVelocitySize', ...
            'GroundTruth.VelocityBody_mps must be N-by-3.');
    end

    if size(GroundTruthEuler_rad, 1) ~= GroundTruthSampleCount || ...
            size(GroundTruthEuler_rad, 2) ~= 3

        error( ...
            'sensormodels:GenerateIdealAirData:InvalidEulerSize', ...
            'GroundTruth.Euler_rad must be N-by-3.');
    end

    if numel(GroundTruthAirDensity_kgpm3) ~= ...
            GroundTruthSampleCount

        error( ...
            'sensormodels:GenerateIdealAirData:DensitySizeMismatch', ...
            ['GroundTruth.AirDensity_kgpm3 must have one value per ' ...
             'GroundTruth.Time_s sample.']);
    end

    if numel(SensorTime_s) ~= SensorSampleCount

        error( ...
            'sensormodels:GenerateIdealAirData:TimelineSizeMismatch', ...
            'Timeline.SampleCount must match Timeline.Time_s.');
    end

    %% Generate authoritative Block 6 wind

    WindDisturbanceEnabled = ...
        Scenario.Events.WindDisturbance.Enabled;

    WindDisturbanceStartTime_s = ...
        Scenario.Events.WindDisturbance.StartTime_s;

    WindDisturbanceEndTime_s = ...
        Scenario.Events.WindDisturbance.EndTime_s;

    % Block 6 permits disabled events whose timing fields are not
    % meaningful. WindProfile requires finite timing arguments even when
    % the disturbance is disabled. Therefore provide a finite inert
    % interval when the event is disabled.
    if ~WindDisturbanceEnabled

    % WindProfile validates the interval even when the disturbance
    % is disabled. Use a finite, valid inert interval.
    WindDisturbanceStartTime_s = 0.0;
    WindDisturbanceEndTime_s = 1.0;

    else

        validateattributes( ...
            WindDisturbanceStartTime_s, ...
            {'double'}, ...
            {'real','finite','scalar'}, ...
            mfilename, ...
            'WindDisturbance.StartTime_s');

        validateattributes( ...
            WindDisturbanceEndTime_s, ...
            {'double'}, ...
            {'real','finite','scalar'}, ...
            mfilename, ...
            'WindDisturbance.EndTime_s');

        if WindDisturbanceEndTime_s <= ...
                WindDisturbanceStartTime_s

            error( ...
                'sensormodels:GenerateIdealAirData:InvalidWindDisturbanceInterval', ...
                'Wind disturbance EndTime_s must exceed StartTime_s.');
        end
    end

    WindNED_mps = flightscenario.WindProfile( ...
        SensorTime_s, ...
        Scenario.Wind.ConstantNED_mps, ...
        WindDisturbanceEnabled, ...
        Scenario.Wind.Gust.PeakNED_mps, ...
        WindDisturbanceStartTime_s, ...
        WindDisturbanceEndTime_s);

    if size(WindNED_mps, 1) ~= SensorSampleCount || ...
            size(WindNED_mps, 2) ~= 3

        error( ...
            'sensormodels:GenerateIdealAirData:InvalidWindOutput', ...
            'Block 6 WindProfile returned an invalid wind array size.');
    end

    %% Interpolate aircraft velocity, attitude, and density

    VelocityBodySensor_mps = interp1( ...
        GroundTruthTime_s, ...
        GroundTruthVelocityBody_mps, ...
        SensorTime_s, ...
        'linear');

    EulerSensor_rad = interp1( ...
        GroundTruthTime_s, ...
        GroundTruthEuler_rad, ...
        SensorTime_s, ...
        'linear');

    AirDensitySensor_kgpm3 = interp1( ...
        GroundTruthTime_s, ...
        GroundTruthAirDensity_kgpm3, ...
        SensorTime_s, ...
        'linear');

    %% Calculate air-relative velocity

    AirVelocityBody_mps = zeros(SensorSampleCount, 3);

    for SampleIndex = 1:SensorSampleCount

        Roll_rad = EulerSensor_rad(SampleIndex, 1);
        Pitch_rad = EulerSensor_rad(SampleIndex, 2);
        Yaw_rad = EulerSensor_rad(SampleIndex, 3);

        Quaternion = coordinates.Euler2Quaternion( ...
            Roll_rad, ...
            Pitch_rad, ...
            Yaw_rad);

        Cbn = coordinates.Quaternion2DCM(Quaternion);

        WindBody_mps = ...
            Cbn.' * WindNED_mps(SampleIndex, :).';

        AirVelocityBody_mps(SampleIndex, :) = ...
            VelocityBodySensor_mps(SampleIndex, :) - ...
            WindBody_mps.';
    end

    %% True airspeed

    TrueAirspeed_mps = sqrt( ...
        sum(AirVelocityBody_mps.^2, 2));

    %% Dynamic pressure

    DynamicPressure_Pa = ...
        0.5 .* AirDensitySensor_kgpm3 .* ...
        TrueAirspeed_mps.^2;

    %% Build output

    AirData = struct();

    AirData.Time_s = SensorTime_s;
    AirData.SampleRate_Hz = Timeline.SampleRate_Hz;
    AirData.SampleCount = SensorSampleCount;

    AirData.TrueAirspeed_mps = TrueAirspeed_mps;
    AirData.DynamicPressure_Pa = DynamicPressure_Pa;

    AirData.Available = true(SensorSampleCount, 1);

end