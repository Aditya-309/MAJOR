
function IMU = GenerateIdealIMU( ...
    GroundTruth, ...
    Timeline)
%GENERATEIDEALIMU Generate deterministic ideal IMU measurements.
%
%   IMU = GENERATEIDEALIMU(GroundTruth, Timeline) generates ideal
%   accelerometer specific force and gyroscope angular-rate measurements
%   on the supplied deterministic IMU timeline.
%
%   GroundTruth is consumed without modification.
%
%   The accelerometer specific force is derived from the actual frozen
%   Block 7 GroundTruth interface:
%
%       f_b = dv_b/dt + omega_b x v_b - g_b
%
%   where:
%       v_b     = GroundTruth.VelocityBody_mps
%       omega_b = GroundTruth.AngularRateBody_radps
%       g_b     = gravity expressed in Body coordinates
%
%   Gravity is obtained from the existing Block 3 GravityModel using the
%   existing Block 2 quaternion convention.
%
%   The ideal gyroscope measurement is the body angular-rate vector
%   interpolated onto the native IMU timeline.
%
%   No noise, bias, random walk, scale factor, misalignment, saturation,
%   quantization, latency, dropout, outage, or fault behavior is applied.
%
%   Output:
%
%       IMU.Time_s
%       IMU.SampleRate_Hz
%       IMU.SampleCount
%       IMU.Accelerometer_mps2
%       IMU.Gyroscope_radps
%       IMU.Available

    %% Validate GroundTruth Structure

    if ~isstruct(GroundTruth) || ~isscalar(GroundTruth)

        error( ...
            'ASRTE:IdealIMU:InvalidGroundTruthStructure', ...
            'GroundTruth must be a scalar structure.');

    end

    RequiredGroundTruthFields = ...
        {'SampleCount', ...
         'SampleTime_s', ...
         'Time_s', ...
         'VelocityBody_mps', ...
         'AngularRateBody_radps', ...
         'Euler_rad'};

    MissingFields = ...
        RequiredGroundTruthFields( ...
            ~isfield(GroundTruth, RequiredGroundTruthFields));

    if ~isempty(MissingFields)

        error( ...
            'ASRTE:IdealIMU:MissingGroundTruthField', ...
            'GroundTruth is missing required field(s): %s.', ...
            strjoin(MissingFields, ', '));

    end

    %% Validate GroundTruth Time

    GroundTruthTime_s = ...
        GroundTruth.Time_s;

    if ~isnumeric(GroundTruthTime_s) || ...
            ~isreal(GroundTruthTime_s) || ...
            ~isvector(GroundTruthTime_s) || ...
            isempty(GroundTruthTime_s) || ...
            any(~isfinite(GroundTruthTime_s))

        error( ...
            'ASRTE:IdealIMU:InvalidGroundTruthTime', ...
            ['GroundTruth.Time_s must be a nonempty finite ', ...
             'real numeric vector.']);

    end

    GroundTruthTime_s = GroundTruthTime_s(:);

    GroundTruthSampleCount = ...
        numel(GroundTruthTime_s);

    if GroundTruthSampleCount < 2 || ...
            any(diff(GroundTruthTime_s) <= 0)

        error( ...
            'ASRTE:IdealIMU:InvalidGroundTruthTimeline', ...
            ['GroundTruth.Time_s must contain at least two ', ...
             'strictly increasing samples.']);

    end

    %% Validate GroundTruth Sample Count

    if ~isnumeric(GroundTruth.SampleCount) || ...
            ~isreal(GroundTruth.SampleCount) || ...
            ~isscalar(GroundTruth.SampleCount) || ...
            ~isfinite(GroundTruth.SampleCount) || ...
            GroundTruth.SampleCount ~= GroundTruthSampleCount

        error( ...
            'ASRTE:IdealIMU:InvalidSampleCount', ...
            ['GroundTruth.SampleCount must equal the number of ', ...
             'GroundTruth.Time_s samples.']);

    end

    %% Validate GroundTruth Sample Time

    if ~isnumeric(GroundTruth.SampleTime_s) || ...
            ~isreal(GroundTruth.SampleTime_s) || ...
            ~isscalar(GroundTruth.SampleTime_s) || ...
            ~isfinite(GroundTruth.SampleTime_s) || ...
            GroundTruth.SampleTime_s <= 0

        error( ...
            'ASRTE:IdealIMU:InvalidSampleTime', ...
            'GroundTruth.SampleTime_s must be a positive finite scalar.');

    end

    %% Validate Body Velocity

    VelocityBody_mps = ...
        GroundTruth.VelocityBody_mps;

    if ~isnumeric(VelocityBody_mps) || ...
            ~isreal(VelocityBody_mps) || ...
            ~isequal( ...
                size(VelocityBody_mps), ...
                [GroundTruthSampleCount, 3]) || ...
            any(~isfinite(VelocityBody_mps(:)))

        error( ...
            'ASRTE:IdealIMU:InvalidVelocityBody', ...
            ['GroundTruth.VelocityBody_mps must be a finite ', ...
             'SampleCount-by-3 real numeric array.']);

    end

    %% Validate Body Angular Rate

    AngularRateBody_radps = ...
        GroundTruth.AngularRateBody_radps;

    if ~isnumeric(AngularRateBody_radps) || ...
            ~isreal(AngularRateBody_radps) || ...
            ~isequal( ...
                size(AngularRateBody_radps), ...
                [GroundTruthSampleCount, 3]) || ...
            any(~isfinite(AngularRateBody_radps(:)))

        error( ...
            'ASRTE:IdealIMU:InvalidAngularRate', ...
            ['GroundTruth.AngularRateBody_radps must be a finite ', ...
             'SampleCount-by-3 real numeric array.']);

    end

    %% Validate Euler Attitude

    Euler_rad = ...
        GroundTruth.Euler_rad;

    if ~isnumeric(Euler_rad) || ...
            ~isreal(Euler_rad) || ...
            ~isequal( ...
                size(Euler_rad), ...
                [GroundTruthSampleCount, 3]) || ...
            any(~isfinite(Euler_rad(:)))

        error( ...
            'ASRTE:IdealIMU:InvalidEulerAngles', ...
            ['GroundTruth.Euler_rad must be a finite ', ...
             'SampleCount-by-3 real numeric array.']);

    end

    %% Validate Timeline Structure

    if ~isstruct(Timeline) || ~isscalar(Timeline)

        error( ...
            'ASRTE:IdealIMU:InvalidTimelineStructure', ...
            'Timeline must be a scalar structure.');

    end

    RequiredTimelineFields = ...
        {'Time_s', ...
         'SampleRate_Hz', ...
         'SampleCount'};

    MissingTimelineFields = ...
        RequiredTimelineFields( ...
            ~isfield(Timeline, RequiredTimelineFields));

    if ~isempty(MissingTimelineFields)

        error( ...
            'ASRTE:IdealIMU:MissingTimelineField', ...
            'Timeline is missing required field(s): %s.', ...
            strjoin(MissingTimelineFields, ', '));

    end

    %% Validate Timeline Time

    SensorTime_s = ...
        Timeline.Time_s;

    if ~isnumeric(SensorTime_s) || ...
            ~isreal(SensorTime_s) || ...
            ~isvector(SensorTime_s) || ...
            isempty(SensorTime_s) || ...
            any(~isfinite(SensorTime_s))

        error( ...
            'ASRTE:IdealIMU:InvalidSensorTimeline', ...
            ['Timeline.Time_s must be a nonempty finite ', ...
             'real numeric vector.']);

    end

    SensorTime_s = SensorTime_s(:);

    if any(diff(SensorTime_s) <= 0)

        error( ...
            'ASRTE:IdealIMU:NonIncreasingSensorTimeline', ...
            'Timeline.Time_s must be strictly increasing.');

    end

    %% Validate Sample Rate

    if ~isnumeric(Timeline.SampleRate_Hz) || ...
            ~isreal(Timeline.SampleRate_Hz) || ...
            ~isscalar(Timeline.SampleRate_Hz) || ...
            ~isfinite(Timeline.SampleRate_Hz) || ...
            Timeline.SampleRate_Hz <= 0

        error( ...
            'ASRTE:IdealIMU:InvalidSampleRate', ...
            'Timeline.SampleRate_Hz must be a positive finite scalar.');

    end

    %% Validate Timeline Sample Count

    if ~isnumeric(Timeline.SampleCount) || ...
            ~isreal(Timeline.SampleCount) || ...
            ~isscalar(Timeline.SampleCount) || ...
            ~isfinite(Timeline.SampleCount) || ...
            Timeline.SampleCount ~= numel(SensorTime_s)

        error( ...
            'ASRTE:IdealIMU:InvalidTimelineSampleCount', ...
            ['Timeline.SampleCount must equal the number of ', ...
             'Timeline.Time_s samples.']);

    end

    %% Validate Timeline Bounds

    TimeTolerance_s = ...
        16 * eps(max( ...
            1, ...
            max(abs([GroundTruthTime_s(1), ...
                     GroundTruthTime_s(end)]))));

    if SensorTime_s(1) < ...
            GroundTruthTime_s(1) - TimeTolerance_s || ...
            SensorTime_s(end) > ...
            GroundTruthTime_s(end) + TimeTolerance_s

        error( ...
            'ASRTE:IdealIMU:TimelineOutsideGroundTruth', ...
            ['Timeline.Time_s must remain within the GroundTruth ', ...
             'time bounds.']);

    end

    %% Derive Body Velocity Derivative

    %
    % The derivative is calculated on the native GroundTruth timeline.
    % MATLAB gradient with the explicit time vector correctly handles the
    % actual GroundTruth sampling interval.
    %

    VelocityDerivativeBody_mps2 = zeros( ...
    GroundTruthSampleCount, 3);

for Axis = 1:3

    VelocityDerivativeBody_mps2(:,Axis) = ...
        gradient( ...
            VelocityBody_mps(:,Axis), ...
            GroundTruthTime_s);

end


    if ~isequal( ...
            size(VelocityDerivativeBody_mps2), ...
            [GroundTruthSampleCount, 3]) || ...
            any(~isfinite(VelocityDerivativeBody_mps2(:)))

        error( ...
            'ASRTE:IdealIMU:InvalidVelocityDerivative', ...
            'Derived body-velocity derivative is invalid.');

    end

    %% Calculate Gravity in Body Coordinates

    GravityBody_mps2 = ...
        zeros(GroundTruthSampleCount, 3);

    for k = 1:GroundTruthSampleCount

        Roll_rad = Euler_rad(k,1);
        Pitch_rad = Euler_rad(k,2);
        Yaw_rad = Euler_rad(k,3);

        Quaternion = ...
            coordinates.Euler2Quaternion( ...
                Roll_rad, ...
                Pitch_rad, ...
                Yaw_rad);

        GravityVectorBody_mps2 = ...
            dynamics.GravityModel( ...
                "BODY", ...
                Quaternion);

        GravityBody_mps2(k,:) = ...
            GravityVectorBody_mps2(:).';

    end

    %% Derive Ideal Specific Force

    RotationalVelocityTerm_mps2 = ...
        cross( ...
            AngularRateBody_radps, ...
            VelocityBody_mps, ...
            2);

    SpecificForceBody_mps2 = ...
        VelocityDerivativeBody_mps2 + ...
        RotationalVelocityTerm_mps2 - ...
        GravityBody_mps2;

    if any(~isfinite(SpecificForceBody_mps2(:)))

        error( ...
            'ASRTE:IdealIMU:InvalidSpecificForce', ...
            'Derived ideal specific force contains NaN or Inf values.');

    end

    %% Interpolate Specific Force to IMU Timeline

    IMUAccelerometer_mps2 = ...
        interp1( ...
            GroundTruthTime_s, ...
            SpecificForceBody_mps2, ...
            SensorTime_s, ...
            'linear');

    %% Interpolate Angular Rate to IMU Timeline

    IMUGyroscope_radps = ...
        interp1( ...
            GroundTruthTime_s, ...
            AngularRateBody_radps, ...
            SensorTime_s, ...
            'linear');

    %% Validate Generated Measurements

    if any(~isfinite(IMUAccelerometer_mps2(:))) || ...
            any(~isfinite(IMUGyroscope_radps(:)))

        error( ...
            'ASRTE:IdealIMU:InvalidGeneratedMeasurement', ...
            'Generated ideal IMU measurements must be finite.');

    end

    %% Build Output

    IMU = struct();

    IMU.Time_s = ...
        SensorTime_s;

    IMU.SampleRate_Hz = ...
        Timeline.SampleRate_Hz;

    IMU.SampleCount = ...
        numel(SensorTime_s);

    IMU.Accelerometer_mps2 = ...
        IMUAccelerometer_mps2;

    IMU.Gyroscope_radps = ...
        IMUGyroscope_radps;

    IMU.Available = ...
        true(numel(SensorTime_s), 1);

end

