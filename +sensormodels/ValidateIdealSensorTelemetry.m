%% ============================================================
% Air Data
% ============================================================

function ValidateAirData(AirData)

    SensorName = 'AirData';

    RequiredFields = { ...
        'Time_s', ...
        'SampleRate_Hz', ...
        'SampleCount', ...
        'TrueAirspeed_mps', ...
        'DynamicPressure_Pa', ...
        'Available'};

    ValidateSensorStructure( ...
        AirData, RequiredFields, SensorName);

    SampleCount = ...
        ValidateSensorMetadata(AirData, SensorName);

    TrueAirspeed_mps = ...
        ValidateSignalVector( ...
            AirData.TrueAirspeed_mps, ...
            SampleCount, ...
            SensorName, ...
            'TrueAirspeed_mps');

    if any(TrueAirspeed_mps < 0)

        error( ...
            'ASRTE:IdealSensorTelemetry:NegativeTrueAirspeed', ...
            'AirData.TrueAirspeed_mps must be nonnegative.');

    end

    DynamicPressure_Pa = ...
        ValidateSignalVector( ...
            AirData.DynamicPressure_Pa, ...
            SampleCount, ...
            SensorName, ...
            'DynamicPressure_Pa');

    if any(DynamicPressure_Pa < 0)

        error( ...
            'ASRTE:IdealSensorTelemetry:NegativeDynamicPressure', ...
            'AirData.DynamicPressure_Pa must be nonnegative.');

    end

    ValidateAvailability( ...
        AirData.Available, ...
        SampleCount, ...
        SensorName);

end


