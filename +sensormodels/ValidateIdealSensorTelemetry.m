function ValidateIdealSensorTelemetry(SensorTelemetry)
%VALIDATEIDEALSENSORTTELEMETRY Validate complete ideal sensor telemetry.
%
%   Validates the frozen Block 4 ideal sensor telemetry interface.
%
%   Required branches:
%       GNSS
%       IMU
%       AirData
%       Magnetometer
%
%   Validation is read-only and does not modify the input.

    %% Top-level structure

    if ~isstruct(SensorTelemetry) || ...
            ~isscalar(SensorTelemetry)

        error( ...
            'ASRTE:IdealSensorTelemetry:InvalidStructure', ...
            'SensorTelemetry must be a scalar structure.');

    end

    RequiredSensorFields = { ...
        'GNSS', ...
        'IMU', ...
        'AirData', ...
        'Magnetometer'};

    MissingSensorFields = ...
        RequiredSensorFields( ...
            ~isfield(SensorTelemetry, RequiredSensorFields));

    if ~isempty(MissingSensorFields)

        error( ...
            'ASRTE:IdealSensorTelemetry:MissingSensorField', ...
            'SensorTelemetry is missing required field(s): %s.', ...
            strjoin(MissingSensorFields, ', '));

    end

    %% Sensor branches

    ValidateGNSS(SensorTelemetry.GNSS);
    ValidateIMU(SensorTelemetry.IMU);
    ValidateAirData(SensorTelemetry.AirData);
    ValidateMagnetometer(SensorTelemetry.Magnetometer);

end


%% ============================================================
% GNSS
% ============================================================

function ValidateGNSS(GNSS)

    SensorName = 'GNSS';

    RequiredFields = { ...
        'Time_s', ...
        'SampleRate_Hz', ...
        'SampleCount', ...
        'Latitude_rad', ...
        'Longitude_rad', ...
        'Altitude_m', ...
        'Velocity_NED_mps', ...
        'Available'};

    ValidateSensorStructure( ...
        GNSS, RequiredFields, SensorName);

    SampleCount = ...
        ValidateSensorMetadata(GNSS, SensorName);

    ValidateSignalVector( ...
        GNSS.Latitude_rad, ...
        SampleCount, ...
        SensorName, ...
        'Latitude_rad');

    ValidateSignalVector( ...
        GNSS.Longitude_rad, ...
        SampleCount, ...
        SensorName, ...
        'Longitude_rad');

    ValidateSignalVector( ...
        GNSS.Altitude_m, ...
        SampleCount, ...
        SensorName, ...
        'Altitude_m');

    ValidateSignalMatrix( ...
        GNSS.Velocity_NED_mps, ...
        SampleCount, ...
        3, ...
        SensorName, ...
        'Velocity_NED_mps');

    ValidateAvailability( ...
        GNSS.Available, ...
        SampleCount, ...
        SensorName);

end


