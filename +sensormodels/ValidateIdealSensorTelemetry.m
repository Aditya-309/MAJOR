%% ============================================================
% Generic structure validation
% ============================================================

function ValidateSensorStructure( ...
    Sensor, ...
    RequiredFields, ...
    SensorName)

    if ~isstruct(Sensor) || ...
            ~isscalar(Sensor)

        error( ...
            'ASRTE:IdealSensorTelemetry:InvalidSensorStructure', ...
            '%s must be a scalar structure.', ...
            SensorName);

    end

    MissingFields = ...
        RequiredFields( ...
            ~isfield(Sensor, RequiredFields));

    if ~isempty(MissingFields)

        error( ...
            'ASRTE:IdealSensorTelemetry:MissingMeasurementField', ...
            '%s is missing required field(s): %s.', ...
            SensorName, ...
            strjoin(MissingFields, ', '));

    end

end


%% ============================================================
% Metadata validation
% ============================================================

function SampleCount = ValidateSensorMetadata( ...
    Sensor, ...
    SensorName)

    Time_s = Sensor.Time_s;

    if ~isnumeric(Time_s) || ...
            ~isreal(Time_s) || ...
            ~isvector(Time_s) || ...
            isempty(Time_s) || ...
            any(~isfinite(Time_s))

        error( ...
            'ASRTE:IdealSensorTelemetry:InvalidTimeline', ...
            '%s.Time_s must be a finite real numeric vector.', ...
            SensorName);

    end

    Time_s = Time_s(:);

    SampleCount = numel(Time_s);

    if SampleCount < 2 || ...
            any(diff(Time_s) <= 0)

        error( ...
            'ASRTE:IdealSensorTelemetry:InvalidTimelineOrdering', ...
            '%s.Time_s must be strictly increasing.', ...
            SensorName);

    end

    SampleRate_Hz = Sensor.SampleRate_Hz;

    if ~isnumeric(SampleRate_Hz) || ...
            ~isreal(SampleRate_Hz) || ...
            ~isscalar(SampleRate_Hz) || ...
            ~isfinite(SampleRate_Hz) || ...
            SampleRate_Hz <= 0

        error( ...
            'ASRTE:IdealSensorTelemetry:InvalidSampleRate', ...
            '%s.SampleRate_Hz must be positive and finite.', ...
            SensorName);

    end

    DeclaredSampleCount = Sensor.SampleCount;

    if ~isnumeric(DeclaredSampleCount) || ...
            ~isreal(DeclaredSampleCount) || ...
            ~isscalar(DeclaredSampleCount) || ...
            ~isfinite(DeclaredSampleCount) || ...
            DeclaredSampleCount ~= floor(DeclaredSampleCount) || ...
            DeclaredSampleCount ~= SampleCount

        error( ...
            'ASRTE:IdealSensorTelemetry:InvalidSampleCount', ...
            '%s.SampleCount must equal numel(%s.Time_s).', ...
            SensorName, SensorName);

    end

end


%% ============================================================
% Vector validation
% ============================================================

function Signal = ValidateSignalVector( ...
    Signal, ...
    SampleCount, ...
    SensorName, ...
    SignalName)

    if ~isnumeric(Signal) || ...
            ~isreal(Signal) || ...
            ~isvector(Signal) || ...
            numel(Signal) ~= SampleCount || ...
            any(~isfinite(Signal(:)))

        error( ...
            'ASRTE:IdealSensorTelemetry:InvalidMeasurementVector', ...
            '%s.%s must contain %d finite real samples.', ...
            SensorName, SignalName, SampleCount);

    end

    Signal = Signal(:);

end


%% ============================================================
% Matrix validation
% ============================================================

function Signal = ValidateSignalMatrix( ...
    Signal, ...
    SampleCount, ...
    ColumnCount, ...
    SensorName, ...
    SignalName)

    if ~isnumeric(Signal) || ...
            ~isreal(Signal) || ...
            ~isequal(size(Signal), ...
                [SampleCount, ColumnCount]) || ...
            any(~isfinite(Signal(:)))

        error( ...
            'ASRTE:IdealSensorTelemetry:InvalidMeasurementMatrix', ...
            '%s.%s must be a finite real %d-by-%d matrix.', ...
            SensorName, ...
            SignalName, ...
            SampleCount, ...
            ColumnCount);

    end

end


%% ============================================================
% Availability validation
% ============================================================

function ValidateAvailability( ...
    Available, ...
    SampleCount, ...
    SensorName)

    if ~islogical(Available) || ...
            ~isequal(size(Available), [SampleCount, 1])

        error( ...
            'ASRTE:IdealSensorTelemetry:InvalidAvailability', ...
            '%s.Available must be a SampleCount-by-1 logical vector.', ...
            SensorName);

    end

end