function ValidateSensorConfig(Config)
%VALIDATESENSORCONFIG Validate the frozen Block 4 sensor configuration.
%
%   VALIDATESENSORCONFIG(CONFIG) verifies the structure, required fields,
%   numerical validity, physical ranges, and internal consistency of the
%   frozen Block 4 sensor configuration.
%
%   This function validates configuration only. It does not modify CONFIG
%   and does not generate noise, bias, random walk, outage, dropout, fault,
%   or any other sensor corruption.

    %% Top-Level Validation

    if ~isstruct(Config) || ~isscalar(Config)
        error( ...
            'ASRTE:SensorConfig:InvalidStructure', ...
            'Sensor configuration must be a scalar structure.');
    end

    RequiredTopLevelFields = ...
        {'Name', ...
         'Version', ...
         'GNSS', ...
         'IMU', ...
         'AirData', ...
         'Magnetometer', ...
         'Availability'};

    ValidateRequiredFields( ...
        Config, ...
        RequiredTopLevelFields, ...
        'Sensor configuration');

    %% Metadata Validation

    ValidateTextScalar( ...
        Config.Name, ...
        'ASRTE:SensorConfig:InvalidName', ...
        'Config.Name must be a nonempty text scalar.');

    ValidateTextScalar( ...
        Config.Version, ...
        'ASRTE:SensorConfig:InvalidVersion', ...
        'Config.Version must be a nonempty text scalar.');

    %% GNSS Validation

    if ~isstruct(Config.GNSS) || ~isscalar(Config.GNSS)
        error( ...
            'ASRTE:SensorConfig:InvalidGNSSStructure', ...
            'Config.GNSS must be a scalar structure.');
    end

    RequiredGNSSFields = ...
        {'SampleRate_Hz', ...
         'PositionAccuracyHorizontal_m', ...
         'PositionAccuracyVertical_m', ...
         'VelocityAccuracy_mps'};

    ValidateRequiredFields( ...
        Config.GNSS, ...
        RequiredGNSSFields, ...
        'Config.GNSS');

    ValidatePositiveFiniteScalar( ...
        Config.GNSS.SampleRate_Hz, ...
        'ASRTE:SensorConfig:InvalidGNSSSampleRate', ...
        'Config.GNSS.SampleRate_Hz must be a positive finite scalar.');

    ValidateNonnegativeFiniteScalar( ...
        Config.GNSS.PositionAccuracyHorizontal_m, ...
        'ASRTE:SensorConfig:InvalidGNSSHorizontalAccuracy', ...
        ['Config.GNSS.PositionAccuracyHorizontal_m must be a ', ...
         'nonnegative finite scalar.']);

    ValidateNonnegativeFiniteScalar( ...
        Config.GNSS.PositionAccuracyVertical_m, ...
        'ASRTE:SensorConfig:InvalidGNSSVerticalAccuracy', ...
        ['Config.GNSS.PositionAccuracyVertical_m must be a ', ...
         'nonnegative finite scalar.']);

    ValidateNonnegativeFiniteScalar( ...
        Config.GNSS.VelocityAccuracy_mps, ...
        'ASRTE:SensorConfig:InvalidGNSSVelocityAccuracy', ...
        ['Config.GNSS.VelocityAccuracy_mps must be a ', ...
         'nonnegative finite scalar.']);

    %% IMU Validation

    if ~isstruct(Config.IMU) || ~isscalar(Config.IMU)
        error( ...
            'ASRTE:SensorConfig:InvalidIMUStructure', ...
            'Config.IMU must be a scalar structure.');
    end

    RequiredIMUFields = ...
        {'SampleRate_Hz', ...
         'Accelerometer', ...
         'Gyroscope'};

    ValidateRequiredFields( ...
        Config.IMU, ...
        RequiredIMUFields, ...
        'Config.IMU');

    ValidatePositiveFiniteScalar( ...
        Config.IMU.SampleRate_Hz, ...
        'ASRTE:SensorConfig:InvalidIMUSampleRate', ...
        'Config.IMU.SampleRate_Hz must be a positive finite scalar.');

    %% Accelerometer Validation

    if ~isstruct(Config.IMU.Accelerometer) || ...
            ~isscalar(Config.IMU.Accelerometer)

        error( ...
            'ASRTE:SensorConfig:InvalidAccelerometerStructure', ...
            'Config.IMU.Accelerometer must be a scalar structure.');
    end

    RequiredAccelerometerFields = ...
        {'FullScale_mps2', ...
         'NoiseDensity_mps2_per_sqrtHz', ...
         'BiasInstability_mps2'};

    ValidateRequiredFields( ...
        Config.IMU.Accelerometer, ...
        RequiredAccelerometerFields, ...
        'Config.IMU.Accelerometer');

    ValidatePositiveFiniteScalar( ...
        Config.IMU.Accelerometer.FullScale_mps2, ...
        'ASRTE:SensorConfig:InvalidAccelerometerFullScale', ...
        ['Config.IMU.Accelerometer.FullScale_mps2 must be a ', ...
         'positive finite scalar.']);

    ValidateNonnegativeFiniteScalar( ...
        Config.IMU.Accelerometer.NoiseDensity_mps2_per_sqrtHz, ...
        'ASRTE:SensorConfig:InvalidAccelerometerNoiseDensity', ...
        ['Config.IMU.Accelerometer.NoiseDensity_mps2_per_sqrtHz ', ...
         'must be a nonnegative finite scalar.']);

    ValidateNonnegativeFiniteScalar( ...
        Config.IMU.Accelerometer.BiasInstability_mps2, ...
        'ASRTE:SensorConfig:InvalidAccelerometerBiasInstability', ...
        ['Config.IMU.Accelerometer.BiasInstability_mps2 must be ', ...
         'a nonnegative finite scalar.']);

    %% Gyroscope Validation

    if ~isstruct(Config.IMU.Gyroscope) || ...
            ~isscalar(Config.IMU.Gyroscope)

        error( ...
            'ASRTE:SensorConfig:InvalidGyroscopeStructure', ...
            'Config.IMU.Gyroscope must be a scalar structure.');
    end

    RequiredGyroscopeFields = ...
        {'FullScale_radps', ...
         'NoiseDensity_radps_per_sqrtHz', ...
         'BiasInstability_radps'};

    ValidateRequiredFields( ...
        Config.IMU.Gyroscope, ...
        RequiredGyroscopeFields, ...
        'Config.IMU.Gyroscope');

    ValidatePositiveFiniteScalar( ...
        Config.IMU.Gyroscope.FullScale_radps, ...
        'ASRTE:SensorConfig:InvalidGyroscopeFullScale', ...
        ['Config.IMU.Gyroscope.FullScale_radps must be a ', ...
         'positive finite scalar.']);

    ValidateNonnegativeFiniteScalar( ...
        Config.IMU.Gyroscope.NoiseDensity_radps_per_sqrtHz, ...
        'ASRTE:SensorConfig:InvalidGyroscopeNoiseDensity', ...
        ['Config.IMU.Gyroscope.NoiseDensity_radps_per_sqrtHz ', ...
         'must be a nonnegative finite scalar.']);

    ValidateNonnegativeFiniteScalar( ...
        Config.IMU.Gyroscope.BiasInstability_radps, ...
        'ASRTE:SensorConfig:InvalidGyroscopeBiasInstability', ...
        ['Config.IMU.Gyroscope.BiasInstability_radps must be ', ...
         'a nonnegative finite scalar.']);

    %% Air Data Validation

    if ~isstruct(Config.AirData) || ~isscalar(Config.AirData)
        error( ...
            'ASRTE:SensorConfig:InvalidAirDataStructure', ...
            'Config.AirData must be a scalar structure.');
    end

    RequiredAirDataFields = ...
        {'SampleRate_Hz', ...
         'DynamicPressureRange_Pa'};

    ValidateRequiredFields( ...
        Config.AirData, ...
        RequiredAirDataFields, ...
        'Config.AirData');

    ValidatePositiveFiniteScalar( ...
        Config.AirData.SampleRate_Hz, ...
        'ASRTE:SensorConfig:InvalidAirDataSampleRate', ...
        'Config.AirData.SampleRate_Hz must be a positive finite scalar.');

    DynamicPressureRange_Pa = ...
        Config.AirData.DynamicPressureRange_Pa;

    if ~isnumeric(DynamicPressureRange_Pa) || ...
            ~isreal(DynamicPressureRange_Pa) || ...
            numel(DynamicPressureRange_Pa) ~= 2 || ...
            any(~isfinite(DynamicPressureRange_Pa))

        error( ...
            'ASRTE:SensorConfig:InvalidDynamicPressureRange', ...
            ['Config.AirData.DynamicPressureRange_Pa must contain ', ...
             'exactly two finite real numeric values.']);
    end

    DynamicPressureRange_Pa = ...
        reshape(DynamicPressureRange_Pa, 1, []);

    if DynamicPressureRange_Pa(1) < 0 || ...
            DynamicPressureRange_Pa(2) <= DynamicPressureRange_Pa(1)

        error( ...
            'ASRTE:SensorConfig:InvalidDynamicPressureRangeOrder', ...
            ['Config.AirData.DynamicPressureRange_Pa must define a ', ...
             'nonnegative lower bound and a strictly greater upper bound.']);
    end

    %% Magnetometer Validation

    if ~isstruct(Config.Magnetometer) || ...
            ~isscalar(Config.Magnetometer)

        error( ...
            'ASRTE:SensorConfig:InvalidMagnetometerStructure', ...
            'Config.Magnetometer must be a scalar structure.');
    end

    RequiredMagnetometerFields = ...
        {'SampleRate_Hz', ...
         'FullScale_uT'};

    ValidateRequiredFields( ...
        Config.Magnetometer, ...
        RequiredMagnetometerFields, ...
        'Config.Magnetometer');

    ValidatePositiveFiniteScalar( ...
        Config.Magnetometer.SampleRate_Hz, ...
        'ASRTE:SensorConfig:InvalidMagnetometerSampleRate', ...
        ['Config.Magnetometer.SampleRate_Hz must be a ', ...
         'positive finite scalar.']);

    ValidatePositiveFiniteScalar( ...
        Config.Magnetometer.FullScale_uT, ...
        'ASRTE:SensorConfig:InvalidMagnetometerFullScale', ...
        ['Config.Magnetometer.FullScale_uT must be a ', ...
         'positive finite scalar.']);

    %% Availability Validation

    if ~isstruct(Config.Availability) || ...
            ~isscalar(Config.Availability)

        error( ...
            'ASRTE:SensorConfig:InvalidAvailabilityStructure', ...
            'Config.Availability must be a scalar structure.');
    end

    RequiredAvailabilityFields = ...
        {'GNSS', ...
         'IMU', ...
         'AirData', ...
         'Magnetometer'};

    ValidateRequiredFields( ...
        Config.Availability, ...
        RequiredAvailabilityFields, ...
        'Config.Availability');

    AvailabilityFields = ...
        RequiredAvailabilityFields;

    for k = 1:numel(AvailabilityFields)

        FieldName = AvailabilityFields{k};

        if ~islogical(Config.Availability.(FieldName)) || ...
                ~isscalar(Config.Availability.(FieldName))

            error( ...
                'ASRTE:SensorConfig:InvalidAvailabilityFlag', ...
                ['Config.Availability.', FieldName, ...
                 ' must be a logical scalar.']);
        end

        if ~Config.Availability.(FieldName)

            error( ...
                'ASRTE:SensorConfig:UnavailableIdealSensor', ...
                ['Block 4 ideal sensor availability must be true for ', ...
                 FieldName, '.']);
        end

    end

end


function ValidateRequiredFields( ...
    Structure, ...
    RequiredFields, ...
    StructureName)

    MissingFields = ...
        RequiredFields( ...
            ~isfield(Structure, RequiredFields));

    if ~isempty(MissingFields)

        error( ...
            'ASRTE:SensorConfig:MissingRequiredField', ...
            '%s is missing required field(s): %s.', ...
            StructureName, ...
            strjoin(MissingFields, ', '));
    end

end


function ValidateTextScalar( ...
    Value, ...
    ErrorIdentifier, ...
    ErrorMessage)

    IsValid = ...
        (ischar(Value) && isrow(Value) && ~isempty(Value)) || ...
        (isstring(Value) && isscalar(Value) && strlength(Value) > 0);

    if ~IsValid

        error( ...
            ErrorIdentifier, ...
            '%s', ...
            ErrorMessage);
    end

end


function ValidatePositiveFiniteScalar( ...
    Value, ...
    ErrorIdentifier, ...
    ErrorMessage)

    IsValid = ...
        isnumeric(Value) && ...
        isreal(Value) && ...
        isscalar(Value) && ...
        isfinite(Value) && ...
        Value > 0;

    if ~IsValid

        error( ...
            ErrorIdentifier, ...
            '%s', ...
            ErrorMessage);
    end

end


function ValidateNonnegativeFiniteScalar( ...
    Value, ...
    ErrorIdentifier, ...
    ErrorMessage)

    IsValid = ...
        isnumeric(Value) && ...
        isreal(Value) && ...
        isscalar(Value) && ...
        isfinite(Value) && ...
        Value >= 0;

    if ~IsValid

        error( ...
            ErrorIdentifier, ...
            '%s', ...
            ErrorMessage);
    end

end