function ValidateSensorSimulationInput( ...
    NoisySensorTelemetry, Config)
%VALIDATESENSORSIMULATIONINPUT Validate Block 8 simulation inputs.
%
%   sensorsimulation.ValidateSensorSimulationInput( ...
%       NoisySensorTelemetry, Config)
%
%   Validates the complete input boundary for Block 8 sensor simulation.
%
%   No data is modified, generated, or simulated by this function.
%
%   Required telemetry branches:
%       GNSS
%       IMU
%       AirData
%       Magnetometer
%
%   Required configuration:
%       Config.Corruption.GNSS
%       Config.Corruption.IMU
%       Config.Corruption.Airspeed
%       Config.Corruption.Magnetometer
%
%   Corruption severity:
%       finite real scalar in [0,100].
%
%   Notes:
%       - Validation is independent of sensor corruption.
%       - Availability is validated as a logical vector.
%       - Sensor timelines must be finite and strictly increasing.
%       - Sensor sample counts, rates, and measurement dimensions are
%         validated against the frozen Block 5 interfaces.
%       - This function does not perform cross-rate resampling.

arguments
    NoisySensorTelemetry (1,1) struct
    Config (1,1) struct
end

%% ============================================================
%  Validate top-level telemetry branches
%  ============================================================

RequiredBranches = { ...
    'GNSS', ...
    'IMU', ...
    'AirData', ...
    'Magnetometer'};

for k = 1:numel(RequiredBranches)

    BranchName = RequiredBranches{k};

    if ~isfield(NoisySensorTelemetry,BranchName)

        error( ...
            "sensorsimulation:MissingTelemetryBranch", ...
            "NoisySensorTelemetry is missing required branch '%s'.", ...
            BranchName);
    end

    if ~isstruct(NoisySensorTelemetry.(BranchName)) || ...
            ~isscalar(NoisySensorTelemetry.(BranchName))

        error( ...
            "sensorsimulation:InvalidTelemetryBranch", ...
            "Telemetry branch '%s' must be a scalar structure.", ...
            BranchName);
    end
end

%% ============================================================
%  Validate corruption configuration
%  ============================================================

if ~isfield(Config,'Corruption')

    error( ...
        "sensorsimulation:MissingCorruptionConfig", ...
        "Config is missing the required 'Corruption' field.");
end

if ~isstruct(Config.Corruption) || ...
        ~isscalar(Config.Corruption)

    error( ...
        "sensorsimulation:InvalidCorruptionConfig", ...
        "Config.Corruption must be a scalar structure.");
end

RequiredCorruptionFields = { ...
    'GNSS', ...
    'IMU', ...
    'Airspeed', ...
    'Magnetometer'};

for k = 1:numel(RequiredCorruptionFields)

    SensorName = RequiredCorruptionFields{k};

    if ~isfield(Config.Corruption,SensorName)

        error( ...
            "sensorsimulation:MissingCorruptionSeverity", ...
            "Config.Corruption is missing '%s'.", ...
            SensorName);
    end

    Severity = Config.Corruption.(SensorName);

    if ~isnumeric(Severity) || ...
            ~isscalar(Severity) || ...
            ~isreal(Severity) || ...
            ~isfinite(Severity) || ...
            Severity < 0 || ...
            Severity > 100

        error( ...
            "sensorsimulation:InvalidCorruptionSeverity", ...
            "Config.Corruption.%s must be a finite real scalar in [0,100].", ...
            SensorName);
    end
end

%% ============================================================
%  Validate GNSS branch
%  ============================================================

GNSS = NoisySensorTelemetry.GNSS;

RequiredGNSSFields = { ...
    'Time_s', ...
    'SampleRate_Hz', ...
    'SampleCount', ...
    'Latitude_rad', ...
    'Longitude_rad', ...
    'Altitude_m', ...
    'Velocity_NED_mps', ...
    'Available'};

ValidateRequiredFields(GNSS,RequiredGNSSFields,'GNSS');

ValidateTimeAndMetadata( ...
    GNSS.Time_s, ...
    GNSS.SampleRate_Hz, ...
    GNSS.SampleCount, ...
    'GNSS');

N = GNSS.SampleCount;

ValidateVector(GNSS.Latitude_rad,N,'GNSS Latitude_rad');
ValidateVector(GNSS.Longitude_rad,N,'GNSS Longitude_rad');
ValidateVector(GNSS.Altitude_m,N,'GNSS Altitude_m');

ValidateMatrix3( ...
    GNSS.Velocity_NED_mps,N,'GNSS Velocity_NED_mps');

ValidateAvailability( ...
    GNSS.Available,N,'GNSS');

%% ============================================================
%  Validate IMU branch
%  ============================================================

IMU = NoisySensorTelemetry.IMU;

RequiredIMUFields = { ...
    'Time_s', ...
    'SampleRate_Hz', ...
    'SampleCount', ...
    'Accelerometer_mps2', ...
    'Gyroscope_radps', ...
    'Available'};

ValidateRequiredFields(IMU,RequiredIMUFields,'IMU');

ValidateTimeAndMetadata( ...
    IMU.Time_s, ...
    IMU.SampleRate_Hz, ...
    IMU.SampleCount, ...
    'IMU');

N = IMU.SampleCount;

ValidateMatrix3( ...
    IMU.Accelerometer_mps2,N,'IMU Accelerometer_mps2');

ValidateMatrix3( ...
    IMU.Gyroscope_radps,N,'IMU Gyroscope_radps');

ValidateAvailability( ...
    IMU.Available,N,'IMU');

%% ============================================================
%  Validate AirData branch
%  ============================================================

AirData = NoisySensorTelemetry.AirData;

RequiredAirDataFields = { ...
    'Time_s', ...
    'SampleRate_Hz', ...
    'SampleCount', ...
    'TrueAirspeed_mps', ...
    'DynamicPressure_Pa', ...
    'Available'};

ValidateRequiredFields( ...
    AirData,RequiredAirDataFields,'AirData');

ValidateTimeAndMetadata( ...
    AirData.Time_s, ...
    AirData.SampleRate_Hz, ...
    AirData.SampleCount, ...
    'AirData');

N = AirData.SampleCount;

ValidateVector( ...
    AirData.TrueAirspeed_mps,N,'AirData TrueAirspeed_mps');

ValidateVector( ...
    AirData.DynamicPressure_Pa,N,'AirData DynamicPressure_Pa');

ValidateAvailability( ...
    AirData.Available,N,'AirData');

%% ============================================================
%  Validate Magnetometer branch
%  ============================================================

Magnetometer = NoisySensorTelemetry.Magnetometer;

RequiredMagnetometerFields = { ...
    'Time_s', ...
    'SampleRate_Hz', ...
    'SampleCount', ...
    'MagneticFieldBody_uT', ...
    'Available'};

ValidateRequiredFields( ...
    Magnetometer,RequiredMagnetometerFields,'Magnetometer');

ValidateTimeAndMetadata( ...
    Magnetometer.Time_s, ...
    Magnetometer.SampleRate_Hz, ...
    Magnetometer.SampleCount, ...
    'Magnetometer');

N = Magnetometer.SampleCount;

ValidateMatrix3( ...
    Magnetometer.MagneticFieldBody_uT, ...
    N, ...
    'Magnetometer MagneticFieldBody_uT');

ValidateAvailability( ...
    Magnetometer.Available,N,'Magnetometer');

end


%% ========================================================================
%  Local validation helpers
%  ========================================================================

function ValidateRequiredFields(Data,RequiredFields,BranchName)

for i = 1:numel(RequiredFields)

    FieldName = RequiredFields{i};

    if ~isfield(Data,FieldName)

        error( ...
            "sensorsimulation:MissingSensorField", ...
            "%s is missing required field '%s'.", ...
            BranchName,FieldName);
    end
end

end


function ValidateTimeAndMetadata( ...
    Time_s,SampleRate_Hz,SampleCount,BranchName)

if ~isnumeric(SampleRate_Hz) || ...
        ~isscalar(SampleRate_Hz) || ...
        ~isreal(SampleRate_Hz) || ...
        ~isfinite(SampleRate_Hz) || ...
        SampleRate_Hz <= 0

    error( ...
        "sensorsimulation:InvalidSampleRate", ...
        "%s SampleRate_Hz must be a finite positive real scalar.", ...
        BranchName);
end

if ~isnumeric(SampleCount) || ...
        ~isscalar(SampleCount) || ...
        ~isreal(SampleCount) || ...
        ~isfinite(SampleCount) || ...
        SampleCount < 1 || ...
        SampleCount ~= floor(SampleCount)

    error( ...
        "sensorsimulation:InvalidSampleCount", ...
        "%s SampleCount must be a positive integer scalar.", ...
        BranchName);
end

if ~isnumeric(Time_s) || ...
        ~isvector(Time_s) || ...
        numel(Time_s) ~= SampleCount || ...
        any(~isfinite(Time_s))

    error( ...
        "sensorsimulation:InvalidTime", ...
        "%s Time_s must contain exactly SampleCount finite values.", ...
        BranchName);
end

Time_s = Time_s(:);

if any(diff(Time_s) <= 0)

    error( ...
        "sensorsimulation:NonMonotonicTime", ...
        "%s Time_s must be strictly increasing.", ...
        BranchName);
end

end


function ValidateVector(Value,N,FieldName)

if ~isnumeric(Value) || ...
        ~isvector(Value) || ...
        numel(Value) ~= N || ...
        any(~isfinite(Value))

    error( ...
        "sensorsimulation:InvalidSensorVector", ...
        "%s must contain exactly SampleCount finite numeric values.", ...
        FieldName);
end

end


function ValidateMatrix3(Value,N,FieldName)

if ~isnumeric(Value) || ...
        ~ismatrix(Value) || ...
        size(Value,1) ~= N || ...
        size(Value,2) ~= 3 || ...
        any(~isfinite(Value),'all')

    error( ...
        "sensorsimulation:InvalidSensorMatrix", ...
        "%s must be an N-by-3 finite numeric array.", ...
        FieldName);
end

end


function ValidateAvailability(Available,N,BranchName)

if ~islogical(Available) || ...
        ~isvector(Available) || ...
        numel(Available) ~= N

    error( ...
        "sensorsimulation:InvalidAvailability", ...
        "%s Available must be an N-by-1 or 1-by-N logical vector.", ...
        BranchName);
end

end