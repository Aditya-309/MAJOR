function OutputPaths = ...
    WriteSensorTelemetry(RealisticSensorTelemetry, OutputDirectory)
%WRITESENSORTELEMETRY Persist Block 8 realistic sensor telemetry.
%
%   OutputPaths = sensorsimulation.WriteSensorTelemetry( ...
%       RealisticSensorTelemetry, OutputDirectory)
%
%   Persists validated Block 8 realistic sensor telemetry into the
%   specified output directory.
%
%   Files written:
%
%       <OutputDirectory>/
%           GNSS.csv
%           IMU.csv
%           AirData.csv
%           Magnetometer.csv
%           RealisticSensorTelemetry.mat
%
%   This function is the persistence boundary for Block 8.
%
%   It does NOT:
%       - generate sensor noise
%       - apply sensor noise
%       - apply sensor corruption
%       - modify telemetry
%       - modify configuration
%       - alter availability
%       - resample timelines
%       - generate scenarios
%       - perform estimation
%       - perform sensor fusion
%
%   The input telemetry must already be the final realistic telemetry
%   produced by BuildSensorSimulation.
%
%   OutputPaths contains the full paths of all generated files.

arguments
    RealisticSensorTelemetry (1,1) struct
    OutputDirectory (1,1) string
end

%% ============================================================
%  Validate output directory argument
%  ============================================================

if strlength(strtrim(OutputDirectory)) == 0
    error( ...
        'sensorsimulation:InvalidOutputDirectory', ...
        'OutputDirectory must be a non-empty path.');
end

%% ============================================================
%  Validate complete Block 8 telemetry structure
%  ============================================================

Config = sensorsimulation.SensorSimulationConfig();

sensorsimulation.ValidateSensorSimulationInput( ...
    RealisticSensorTelemetry, ...
    Config);

%% ============================================================
%  Create output directory if required
%  ============================================================

if ~isfolder(OutputDirectory)
    [Success, Message, MessageID] = mkdir(OutputDirectory);

    if ~Success
        error( ...
            'sensorsimulation:OutputDirectoryCreationFailed', ...
            'Unable to create output directory "%s". %s (%s)', ...
            OutputDirectory, Message, MessageID);
    end
end

%% ============================================================
%  Construct output paths
%  ============================================================

OutputPaths = struct();

OutputPaths.GNSS = fullfile(OutputDirectory, "GNSS.csv");
OutputPaths.IMU = fullfile(OutputDirectory, "IMU.csv");
OutputPaths.AirData = fullfile(OutputDirectory, "AirData.csv");
OutputPaths.Magnetometer = ...
    fullfile(OutputDirectory, "Magnetometer.csv");

OutputPaths.RealisticSensorTelemetry = ...
    fullfile(OutputDirectory, "RealisticSensorTelemetry.mat");

%% ============================================================
%  Build sensor tables
%  ============================================================

GNSS = RealisticSensorTelemetry.GNSS;

GNSSVelocity = GNSS.Velocity_NED_mps;

GNSS_Table = table( ...
    GNSS.Time_s(:), ...
    GNSS.Latitude_rad(:), ...
    GNSS.Longitude_rad(:), ...
    GNSS.Altitude_m(:), ...
    GNSSVelocity(:,1), ...
    GNSSVelocity(:,2), ...
    GNSSVelocity(:,3), ...
    GNSS.Available(:), ...
    'VariableNames', { ...
        'Time_s', ...
        'Latitude_rad', ...
        'Longitude_rad', ...
        'Altitude_m', ...
        'VelocityNorth_mps', ...
        'VelocityEast_mps', ...
        'VelocityDown_mps', ...
        'Available'});

IMU = RealisticSensorTelemetry.IMU;

IMU_Table = table( ...
    IMU.Time_s(:), ...
    IMU.Accelerometer_mps2(:,1), ...
    IMU.Accelerometer_mps2(:,2), ...
    IMU.Accelerometer_mps2(:,3), ...
    IMU.Gyroscope_radps(:,1), ...
    IMU.Gyroscope_radps(:,2), ...
    IMU.Gyroscope_radps(:,3), ...
    IMU.Available(:), ...
    'VariableNames', { ...
        'Time_s', ...
        'AccelerometerX_mps2', ...
        'AccelerometerY_mps2', ...
        'AccelerometerZ_mps2', ...
        'GyroscopeX_radps', ...
        'GyroscopeY_radps', ...
        'GyroscopeZ_radps', ...
        'Available'});

AirData = RealisticSensorTelemetry.AirData;

AirData_Table = table( ...
    AirData.Time_s(:), ...
    AirData.TrueAirspeed_mps(:), ...
    AirData.DynamicPressure_Pa(:), ...
    AirData.Available(:), ...
    'VariableNames', { ...
        'Time_s', ...
        'TrueAirspeed_mps', ...
        'DynamicPressure_Pa', ...
        'Available'});

Magnetometer = RealisticSensorTelemetry.Magnetometer;

Magnetometer_Table = table( ...
    Magnetometer.Time_s(:), ...
    Magnetometer.MagneticFieldBody_uT(:,1), ...
    Magnetometer.MagneticFieldBody_uT(:,2), ...
    Magnetometer.MagneticFieldBody_uT(:,3), ...
    Magnetometer.Available(:), ...
    'VariableNames', { ...
        'Time_s', ...
        'MagneticFieldX_uT', ...
        'MagneticFieldY_uT', ...
        'MagneticFieldZ_uT', ...
        'Available'});

%% ============================================================
%  Write CSV telemetry
%  ============================================================

writetable(GNSS_Table, OutputPaths.GNSS);
writetable(IMU_Table, OutputPaths.IMU);
writetable(AirData_Table, OutputPaths.AirData);
writetable(Magnetometer_Table, OutputPaths.Magnetometer);

%% ============================================================
%  Write complete MATLAB telemetry structure
%  ============================================================

save( ...
    OutputPaths.RealisticSensorTelemetry, ...
    'RealisticSensorTelemetry', ...
    '-v7');

end