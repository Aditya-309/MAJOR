function FinalizedRun = FinalizeProductionRun( ...
    ProductionConfig, ...
    RunContext, ...
    RunResult, ...
    ValidationResult)
% FinalizeProductionRun
%
% Promotes a validated production working run from WorkingRuns to Runs.
%
% Inputs:
%   ProductionConfig - Frozen production configuration
%   RunContext       - Current production working-run context
%   RunResult        - Executed production result
%   ValidationResult - Passed production validation result
%
% Output:
%   FinalizedRun     - Updated production run context
%
% This function:
%   - requires an EXECUTED and PASSED run
%   - requires RunMetadata.json to exist
%   - verifies required production artifacts
%   - moves the complete working run into production/Runs
%   - verifies the finalized run
%
% This function does not:
%   - regenerate telemetry
%   - modify Block 1-8
%   - register the run
%   - modify RunRegistry.json
%   - alter scientific data

%% Validate input count

if nargin ~= 4
    error('FinalizeProductionRun:InputCount', ...
        'Exactly four inputs are required.');
end

%% Validate ProductionConfig

if ~isstruct(ProductionConfig) || ...
        ~isscalar(ProductionConfig)
    error('FinalizeProductionRun:InvalidProductionConfig', ...
        'ProductionConfig must be a scalar structure.');
end

RequiredProductionFields = { ...
    'RunsRoot', ...
    'WorkingRunsRoot', ...
    'FailedRunsRoot', ...
    'ScenarioSelector', ...
    'ScenarioID', ...
    'ScenarioName'};

for k = 1:numel(RequiredProductionFields)

    FieldName = RequiredProductionFields{k};

    if ~isfield(ProductionConfig, FieldName)
        error('FinalizeProductionRun:MissingProductionField', ...
            'ProductionConfig.%s is missing.', FieldName);
    end
end

%% Validate RunContext

if ~isstruct(RunContext) || ...
        ~isscalar(RunContext)
    error('FinalizeProductionRun:InvalidRunContext', ...
        'RunContext must be a scalar structure.');
end

RequiredRunFields = { ...
    'RunID', ...
    'Status', ...
    'WorkingRunDirectory', ...
    'FinalRunDirectory', ...
    'FailedRunDirectory', ...
    'Block7Directory', ...
    'GroundTruthDirectory', ...
    'IdealSensorDirectory', ...
    'RealisticSensorDirectory', ...
    'ScenarioSelector', ...
    'ScenarioID', ...
    'ScenarioName'};

for k = 1:numel(RequiredRunFields)

    FieldName = RequiredRunFields{k};

    if ~isfield(RunContext, FieldName)
        error('FinalizeProductionRun:MissingRunField', ...
            'RunContext.%s is missing.', FieldName);
    end
end

if ~strcmp(RunContext.Status, 'WORKING')
    error('FinalizeProductionRun:InvalidRunStatus', ...
        'RunContext.Status must be WORKING before finalization.');
end

%% Validate RunResult

if ~isstruct(RunResult) || ...
        ~isscalar(RunResult)
    error('FinalizeProductionRun:InvalidRunResult', ...
        'RunResult must be a scalar structure.');
end

RequiredResultFields = { ...
    'RunID', ...
    'Status', ...
    'Scenario', ...
    'GroundTruth', ...
    'IdealSensorTelemetry', ...
    'RealisticSensorTelemetry'};

for k = 1:numel(RequiredResultFields)

    FieldName = RequiredResultFields{k};

    if ~isfield(RunResult, FieldName)
        error('FinalizeProductionRun:MissingResultField', ...
            'RunResult.%s is missing.', FieldName);
    end
end

if ~strcmp(RunResult.Status, 'EXECUTED')
    error('FinalizeProductionRun:InvalidResultStatus', ...
        'RunResult.Status must be EXECUTED.');
end

%% Validate ValidationResult

if ~isstruct(ValidationResult) || ...
        ~isscalar(ValidationResult)
    error('FinalizeProductionRun:InvalidValidationResult', ...
        'ValidationResult must be a scalar structure.');
end

RequiredValidationFields = { ...
    'Status', ...
    'RunID', ...
    'ScenarioID', ...
    'ScenarioName', ...
    'Block7ArtifactCount'};

for k = 1:numel(RequiredValidationFields)

    FieldName = RequiredValidationFields{k};

    if ~isfield(ValidationResult, FieldName)
        error('FinalizeProductionRun:MissingValidationField', ...
            'ValidationResult.%s is missing.', FieldName);
    end
end

if ~strcmp(ValidationResult.Status, 'PASSED')
    error('FinalizeProductionRun:ValidationNotPassed', ...
        'ValidationResult.Status must be PASSED before finalization.');
end

%% Cross-check identity

if ~strcmp(RunContext.RunID, RunResult.RunID)
    error('FinalizeProductionRun:RunIDMismatch', ...
        'RunContext.RunID and RunResult.RunID do not match.');
end

if ~strcmp(RunContext.RunID, ValidationResult.RunID)
    error('FinalizeProductionRun:ValidationRunIDMismatch', ...
        'RunContext.RunID and ValidationResult.RunID do not match.');
end

if ~isequaln( ...
        RunContext.ScenarioSelector, ...
        ProductionConfig.ScenarioSelector)
    error('FinalizeProductionRun:ScenarioSelectorMismatch', ...
        'RunContext scenario selector does not match ProductionConfig.');
end

if ~isequaln( ...
        RunContext.ScenarioID, ...
        ProductionConfig.ScenarioID)
    error('FinalizeProductionRun:ScenarioIDMismatch', ...
        'RunContext scenario ID does not match ProductionConfig.');
end

if ~strcmp( ...
        RunContext.ScenarioName, ...
        ProductionConfig.ScenarioName)
    error('FinalizeProductionRun:ScenarioNameMismatch', ...
        'RunContext scenario name does not match ProductionConfig.');
end

if ~isequaln( ...
        RunResult.Scenario.ID, ...
        ProductionConfig.ScenarioID)
    error('FinalizeProductionRun:ResultScenarioMismatch', ...
        'RunResult scenario ID does not match ProductionConfig.');
end

if ~strcmp( ...
        RunResult.Scenario.Name, ...
        ProductionConfig.ScenarioName)
    error('FinalizeProductionRun:ResultScenarioNameMismatch', ...
        'RunResult scenario name does not match ProductionConfig.');
end

%% Validate working directory

if ~isfolder(RunContext.WorkingRunDirectory)
    error('FinalizeProductionRun:MissingWorkingDirectory', ...
        'Working run directory does not exist.');
end

%% Validate metadata

MetadataPath = fullfile( ...
    RunContext.WorkingRunDirectory, ...
    'RunMetadata.json');

if ~isfile(MetadataPath)
    error('FinalizeProductionRun:MissingMetadata', ...
        'RunMetadata.json must exist before finalization.');
end

MetadataInfo = dir(MetadataPath);

if isempty(MetadataInfo) || MetadataInfo.bytes <= 0
    error('FinalizeProductionRun:EmptyMetadata', ...
        'RunMetadata.json is empty.');
end

%% Required production artifact directories

RequiredDirectories = { ...
    RunContext.Block7Directory, ...
    RunContext.GroundTruthDirectory, ...
    RunContext.IdealSensorDirectory, ...
    RunContext.RealisticSensorDirectory};

for k = 1:numel(RequiredDirectories)

    if ~isfolder(RequiredDirectories{k})
        error('FinalizeProductionRun:MissingArtifactDirectory', ...
            'Required artifact directory does not exist: %s', ...
            RequiredDirectories{k});
    end
end

%% Required Block 7 artifacts

RequiredBlock7Files = { ...
    'Init.xml', ...
    'Script.xml', ...
    'Output.xml', ...
    'Telemetry.csv'};

for k = 1:numel(RequiredBlock7Files)

    FilePath = fullfile( ...
        RunContext.Block7Directory, ...
        RequiredBlock7Files{k});

    if ~isfile(FilePath)
        error('FinalizeProductionRun:MissingBlock7Artifact', ...
            'Required Block 7 artifact is missing: %s', ...
            RequiredBlock7Files{k});
    end

    FileInfo = dir(FilePath);

    if isempty(FileInfo) || FileInfo.bytes <= 0
        error('FinalizeProductionRun:EmptyBlock7Artifact', ...
            'Required Block 7 artifact is empty: %s', ...
            RequiredBlock7Files{k});
    end
end

%% Required telemetry artifacts

RequiredTelemetryFiles = { ...
    fullfile(RunContext.GroundTruthDirectory, ...
        'GroundTruthTelemetry.mat'), ...
    fullfile(RunContext.GroundTruthDirectory, ...
        'GroundTruthTelemetry.csv'), ...
    fullfile(RunContext.IdealSensorDirectory, ...
        'IdealSensorTelemetry.mat'), ...
    fullfile(RunContext.IdealSensorDirectory, ...
        'GNSS.csv'), ...
    fullfile(RunContext.IdealSensorDirectory, ...
        'IMU.csv'), ...
    fullfile(RunContext.IdealSensorDirectory, ...
        'AirData.csv'), ...
    fullfile(RunContext.IdealSensorDirectory, ...
        'Magnetometer.csv'), ...
    fullfile(RunContext.RealisticSensorDirectory, ...
        'RealisticSensorTelemetry.mat'), ...
    fullfile(RunContext.RealisticSensorDirectory, ...
        'GNSS.csv'), ...
    fullfile(RunContext.RealisticSensorDirectory, ...
        'IMU.csv'), ...
    fullfile(RunContext.RealisticSensorDirectory, ...
        'AirData.csv'), ...
    fullfile(RunContext.RealisticSensorDirectory, ...
        'Magnetometer.csv')};

for k = 1:numel(RequiredTelemetryFiles)

    FilePath = RequiredTelemetryFiles{k};

    if ~isfile(FilePath)
        error('FinalizeProductionRun:MissingTelemetryArtifact', ...
            'Required telemetry artifact is missing: %s', ...
            FilePath);
    end

    FileInfo = dir(FilePath);

    if isempty(FileInfo) || FileInfo.bytes <= 0
        error('FinalizeProductionRun:EmptyTelemetryArtifact', ...
            'Required telemetry artifact is empty: %s', ...
            FilePath);
    end
end

%% Validate final destination

if isfolder(RunContext.FinalRunDirectory)
    error('FinalizeProductionRun:FinalDirectoryExists', ...
        'Final run directory already exists: %s', ...
        RunContext.FinalRunDirectory);
end

if ~isfolder(ProductionConfig.RunsRoot)
    mkdir(ProductionConfig.RunsRoot);
end

%% Promote working run

[MoveSuccess, MoveMessage, MoveMessageID] = movefile( ...
    RunContext.WorkingRunDirectory, ...
    RunContext.FinalRunDirectory);

if ~MoveSuccess
    if isempty(MoveMessageID)
        error('FinalizeProductionRun:MoveFailure', ...
            'Failed to promote working run: %s', ...
            MoveMessage);
    else
        error('FinalizeProductionRun:MoveFailure', ...
            'Failed to promote working run [%s]: %s', ...
            MoveMessageID, ...
            MoveMessage);
    end
end

%% Verify final directory

if ~isfolder(RunContext.FinalRunDirectory)
    error('FinalizeProductionRun:FinalDirectoryMissing', ...
        'Finalized run directory does not exist after promotion.');
end

if isfolder(RunContext.WorkingRunDirectory)
    error('FinalizeProductionRun:WorkingDirectoryStillExists', ...
        'Working run directory still exists after promotion.');
end

%% Verify metadata in final location

FinalMetadataPath = fullfile( ...
    RunContext.FinalRunDirectory, ...
    'RunMetadata.json');

if ~isfile(FinalMetadataPath)
    error('FinalizeProductionRun:FinalMetadataMissing', ...
        'RunMetadata.json is missing from finalized run.');
end

%% Verify finalized artifact directories

FinalBlock7Directory = fullfile( ...
    RunContext.FinalRunDirectory, ...
    'Block7');

FinalGroundTruthDirectory = fullfile( ...
    RunContext.FinalRunDirectory, ...
    'GroundTruth');

FinalIdealSensorDirectory = fullfile( ...
    RunContext.FinalRunDirectory, ...
    'IdealSensorTelemetry');

FinalRealisticSensorDirectory = fullfile( ...
    RunContext.FinalRunDirectory, ...
    'RealisticSensorTelemetry');

FinalDirectories = { ...
    FinalBlock7Directory, ...
    FinalGroundTruthDirectory, ...
    FinalIdealSensorDirectory, ...
    FinalRealisticSensorDirectory};

for k = 1:numel(FinalDirectories)

    if ~isfolder(FinalDirectories{k})
        error('FinalizeProductionRun:FinalArtifactDirectoryMissing', ...
            'Finalized artifact directory is missing: %s', ...
            FinalDirectories{k});
    end
end

%% Verify finalized artifacts

FinalFiles = { ...
    fullfile(FinalBlock7Directory, 'Init.xml'), ...
    fullfile(FinalBlock7Directory, 'Script.xml'), ...
    fullfile(FinalBlock7Directory, 'Output.xml'), ...
    fullfile(FinalBlock7Directory, 'Telemetry.csv'), ...
    fullfile(FinalGroundTruthDirectory, 'GroundTruthTelemetry.mat'), ...
    fullfile(FinalGroundTruthDirectory, 'GroundTruthTelemetry.csv'), ...
    fullfile(FinalIdealSensorDirectory, 'IdealSensorTelemetry.mat'), ...
    fullfile(FinalIdealSensorDirectory, 'GNSS.csv'), ...
    fullfile(FinalIdealSensorDirectory, 'IMU.csv'), ...
    fullfile(FinalIdealSensorDirectory, 'AirData.csv'), ...
    fullfile(FinalIdealSensorDirectory, 'Magnetometer.csv'), ...
    fullfile(FinalRealisticSensorDirectory, 'RealisticSensorTelemetry.mat'), ...
    fullfile(FinalRealisticSensorDirectory, 'GNSS.csv'), ...
    fullfile(FinalRealisticSensorDirectory, 'IMU.csv'), ...
    fullfile(FinalRealisticSensorDirectory, 'AirData.csv'), ...
    fullfile(FinalRealisticSensorDirectory, 'Magnetometer.csv'), ...
    FinalMetadataPath};

for k = 1:numel(FinalFiles)

    if ~isfile(FinalFiles{k})
        error('FinalizeProductionRun:FinalArtifactMissing', ...
            'Finalized artifact is missing: %s', ...
            FinalFiles{k});
    end

    FileInfo = dir(FinalFiles{k});

    if isempty(FileInfo) || FileInfo.bytes <= 0
        error('FinalizeProductionRun:FinalArtifactEmpty', ...
            'Finalized artifact is empty: %s', ...
            FinalFiles{k});
    end
end

%% Return finalized context

FinalizedRun = RunContext;

FinalizedRun.Status = 'FINALIZED';
FinalizedRun.FinalizedAt = char(datetime( ...
    'now', ...
    'Format', 'yyyy-MM-dd''T''HH:mm:ss.SSS'));

end