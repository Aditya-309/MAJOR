function Flags = QualityFlags()
%QUALITYFLAGS Block 9 quality state fields and finding registry.
%
%   Flags = QUALITYFLAGS() returns the canonical quality model used by the
%   Block 9 preprocessing pipeline.
%
%   Flags.StateFields - the three independent per-row state fields:
%       Available        - sensor-reported availability (forward-held when
%                          aligned); never altered by quality checks
%       RowValid         - row participates in estimator-ready data
%                          (later duplicate rows are excluded)
%       MeasurementValid - measurement values are usable (false for
%                          non-finite or invalid measurements; suspected
%                          outliers remain valid but are flagged)
%
%   Flags.Findings - struct array with fields:
%       Name        - finding identifier used in outputs and reports
%       Severity    - 'Info', 'Warning' or 'Error'
%       Description - short explanation
%
%   Severities are fixed here as the single source of truth; configuration
%   enables or disables checks but never re-maps severities.
%
%   INTERNAL function. Not part of the public Block 9 API. The public API
%   is DiscoverRuns, InspectRun, PreprocessRun and GetPreprocessingReport.
%
%   See also: InspectSensorQuality, DetectSensorOutliers,
%   ProcessSensorTimestamps, PreprocessingConfig.

    %% State Fields

    Flags = struct();

    Flags.StateFields = [ ...
        stateField( ...
            'Available', ...
            ['Sensor-reported availability (logical). Forward-held when ', ...
             'aligned; never altered by quality checks.']); ...
        stateField( ...
            'RowValid', ...
            ['Row participates in estimator-ready data (logical). Later ', ...
             'duplicate timestamps and non-finite timestamps are ', ...
             'excluded.']); ...
        stateField( ...
            'MeasurementValid', ...
            ['Measurement values are usable (logical). False for ', ...
             'non-finite or invalid measurements. Suspected outliers ', ...
             'remain valid but are flagged.'])];

    %% Finding Registry

    Flags.Findings = [ ...
        finding( ...
            'MissingSensor', ...
            'Error', ...
            'Configured sensor stream is absent from the run.'); ...
        finding( ...
            'NonFiniteTimestamp', ...
            'Error', ...
            'Time_s value is NaN or Inf; row excluded from estimator-ready data.'); ...
        finding( ...
            'BackwardTimestamp', ...
            'Warning', ...
            'Time_s decreased; the row starts a new time segment.'); ...
        finding( ...
            'DuplicateTimestampLater', ...
            'Warning', ...
            ['Later row with a repeated timestamp; flagged and excluded ', ...
             'from estimator-ready data (first occurrence is kept).']); ...
        finding( ...
            'UnexpectedGap', ...
            'Warning', ...
            ['Sample interval exceeds the configured gap thresholds ', ...
             '(absolute OR relative criterion).']); ...
        finding( ...
            'NonFiniteMeasurement', ...
            'Error', ...
            ['NaN or Inf in a measurement channel; MeasurementValid set ', ...
             'false for the row.']); ...
        finding( ...
            'Unavailable', ...
            'Info', ...
            'Sensor reports Available = false for the row.'); ...
        finding( ...
            'PhysicalOutlier', ...
            'Warning', ...
            'Value outside the configured physical bounds (flagged only).'); ...
        finding( ...
            'StatisticalOutlier', ...
            'Warning', ...
            'Value outside the configured statistical window (flagged only).'); ...
        finding( ...
            'SuddenChange', ...
            'Warning', ...
            ['Step between consecutive valid samples exceeds the ', ...
             'configured threshold (flagged only).']); ...
        finding( ...
            'StartupTransient', ...
            'Warning', ...
            ['Configured startup window sample with suspicious values; ', ...
             'preserved and flagged, never deleted.']); ...
        finding( ...
            'StaleAlignedSample', ...
            'Warning', ...
            ['Zero-order-hold sample age exceeds the configured maximum ', ...
             'for the stream.']); ...
        finding( ...
            'AlignedNoCoverage', ...
            'Warning', ...
            ['Reference time is outside the source stream coverage; no ', ...
             'extrapolation is performed.'])];

    %% Self-Check

    StateNames = {Flags.StateFields.Name};

    if numel(unique(StateNames)) ~= 3

        error( ...
            'Preprocessing:QualityFlags:InvalidStateFields', ...
            ['The state fields Available, RowValid and MeasurementValid ', ...
             'must be defined exactly once each.']);

    end

    FindingNames = {Flags.Findings.Name};

    if numel(unique(FindingNames)) ~= numel(FindingNames)

        error( ...
            'Preprocessing:QualityFlags:DuplicateFinding', ...
            'Finding names must be unique.');

    end

    Severities = {Flags.Findings.Severity};

    if ~all(ismember(Severities, {'Info', 'Warning', 'Error'}))

        error( ...
            'Preprocessing:QualityFlags:InvalidSeverity', ...
            'Finding severities must be Info, Warning or Error.');

    end

end

% =========================================================================
%% LOCAL HELPERS
% =========================================================================

function Entry = stateField(Name, Description)
%STATEFIELD Build one state-field definition.

    Entry = struct('Name', Name, 'Description', Description);

end

function Entry = finding(Name, Severity, Description)
%FINDING Build one finding definition.

    Entry = struct( ...
        'Name', Name, ...
        'Severity', Severity, ...
        'Description', Description);

end
