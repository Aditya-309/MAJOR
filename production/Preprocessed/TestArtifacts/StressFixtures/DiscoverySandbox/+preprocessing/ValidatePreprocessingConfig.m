function ValidatePreprocessingConfig(Config)
%VALIDATEPREPROCESSINGCONFIG Validate a Block 9 preprocessing configuration.
%
%   VALIDATEPREPROCESSINGCONFIG(Config) validates the structure, types and
%   value ranges of a Block 9 preprocessing configuration as produced by
%   PreprocessingConfig. Validation is pure: no files are read or written.
%
%   Every rejection raises an error of the form
%   'Preprocessing:ValidatePreprocessingConfig:<Reason>'.
%
%   INTERNAL function. Not part of the public Block 9 API. The public API
%   is DiscoverRuns, InspectRun, PreprocessRun and GetPreprocessingReport.
%
%   See also: PreprocessingConfig, SensorDataContracts, QualityFlags.

    %% Validate Configuration Structure

    if ~isstruct(Config) || ~isscalar(Config)

        error( ...
            ['Preprocessing:ValidatePreprocessingConfig:', ...
             'InvalidConfigStructure'], ...
            'Config must be a scalar structure.');

    end

    RequiredTopFields = { ...
        'Name', ...
        'Version', ...
        'Source', ...
        'MissingSensors', ...
        'Timestamps', ...
        'Quality', ...
        'Alignment'};

    MissingFields = ...
        RequiredTopFields(~isfield(Config, RequiredTopFields));

    if ~isempty(MissingFields)

        error( ...
            ['Preprocessing:ValidatePreprocessingConfig:', ...
             'MissingConfigField'], ...
            'Config is missing required field(s): %s.', ...
            strjoin(MissingFields, ', '));

    end

    Contracts = preprocessing.SensorDataContracts();
    CanonicalStreams = Contracts.Streams;
    MeasurementFields = measurementFieldNames(Contracts);

    %% Validate Source

    if ~(isTextScalar(Config.Source) && any(strcmpi(char(Config.Source), ...
            {'RealisticSensorTelemetry', 'IdealSensorTelemetry'})))

        error( ...
            'Preprocessing:ValidatePreprocessingConfig:InvalidSource', ...
            ['Config.Source must be ''RealisticSensorTelemetry'' or ', ...
             '''IdealSensorTelemetry''.']);

    end

    %% Validate Missing-Sensor Policy

    if ~isstruct(Config.MissingSensors) || ~isscalar(Config.MissingSensors) ...
            || ~all(isfield(Config.MissingSensors, ...
                {'Policy', 'RequiredSensors'}))

        error( ...
            ['Preprocessing:ValidatePreprocessingConfig:', ...
             'InvalidMissingSensors'], ...
            ['Config.MissingSensors must be a scalar structure with ', ...
             'Policy and RequiredSensors fields.']);

    end

    if ~(isTextScalar(Config.MissingSensors.Policy) && any(strcmpi( ...
            char(Config.MissingSensors.Policy), {'Continue', 'Strict'})))

        error( ...
            'Preprocessing:ValidatePreprocessingConfig:InvalidPolicy', ...
            ['Config.MissingSensors.Policy must be ''Continue'' or ', ...
             '''Strict''.']);

    end

    RequiredSensors = Config.MissingSensors.RequiredSensors;

    if ~(iscellstr(RequiredSensors) && ~isempty(RequiredSensors)) %#ok<ISCLSTR>

        error( ...
            ['Preprocessing:ValidatePreprocessingConfig:', ...
             'InvalidRequiredSensors'], ...
            ['Config.MissingSensors.RequiredSensors must be a nonempty ', ...
             'cell array of character vectors.']);

    end

    if numel(unique(RequiredSensors)) ~= numel(RequiredSensors) || ...
            ~all(ismember(RequiredSensors, CanonicalStreams))

        error( ...
            ['Preprocessing:ValidatePreprocessingConfig:', ...
             'InvalidRequiredSensors'], ...
            ['Config.MissingSensors.RequiredSensors must contain unique ', ...
             'canonical stream names: %s.'], ...
            strjoin(CanonicalStreams, ', '));

    end

    %% Validate Timestamp Processing

    if ~isstruct(Config.Timestamps) || ~isscalar(Config.Timestamps) || ...
            ~all(isfield(Config.Timestamps, ...
                {'DuplicatePolicy', 'GapAbsolute_s', 'GapRelative', ...
                 'NominalRateSource'}))

        error( ...
            ['Preprocessing:ValidatePreprocessingConfig:', ...
             'InvalidTimestamps'], ...
            ['Config.Timestamps must be a scalar structure with ', ...
             'DuplicatePolicy, GapAbsolute_s, GapRelative and ', ...
             'NominalRateSource fields.']);

    end

    if ~(isTextScalar(Config.Timestamps.DuplicatePolicy) && strcmpi( ...
            char(Config.Timestamps.DuplicatePolicy), 'KeepFirst'))

        error( ...
            ['Preprocessing:ValidatePreprocessingConfig:', ...
             'InvalidDuplicatePolicy'], ...
            ['Config.Timestamps.DuplicatePolicy must be ''KeepFirst'' ', ...
             '(the only supported policy).']);

    end

    GapAbsolute_s = Config.Timestamps.GapAbsolute_s;

    if ~isDisabledCriterion(GapAbsolute_s) && ...
            ~isPositiveFiniteScalar(GapAbsolute_s)

        error( ...
            ['Preprocessing:ValidatePreprocessingConfig:', ...
             'InvalidGapAbsolute'], ...
            ['Config.Timestamps.GapAbsolute_s must be [] or a positive ', ...
             'finite scalar.']);

    end

    GapRelative = Config.Timestamps.GapRelative;

    if ~isDisabledCriterion(GapRelative) && ...
            ~isPositiveFiniteScalar(GapRelative)

        error( ...
            ['Preprocessing:ValidatePreprocessingConfig:', ...
             'InvalidGapRelative'], ...
            ['Config.Timestamps.GapRelative must be [] or a positive ', ...
             'finite scalar.']);

    end

    if isempty(Config.Timestamps.GapAbsolute_s) && ...
            isempty(Config.Timestamps.GapRelative)

        error( ...
            ['Preprocessing:ValidatePreprocessingConfig:', ...
             'InvalidGapConfiguration'], ...
            ['At least one gap criterion (GapAbsolute_s or GapRelative) ', ...
             'must remain configured.']);

    end

    if ~(isTextScalar(Config.Timestamps.NominalRateSource) && ...
            any(strcmpi(char(Config.Timestamps.NominalRateSource), ...
                {'Auto', 'Recorded', 'Measured', 'CodeDefault'})))

        error( ...
            ['Preprocessing:ValidatePreprocessingConfig:', ...
             'InvalidNominalRateSource'], ...
            ['Config.Timestamps.NominalRateSource must be ''Auto'', ', ...
             '''Recorded'', ''Measured'' or ''CodeDefault''.']);

    end

    %% Validate Quality Checks

    if ~isstruct(Config.Quality) || ~isscalar(Config.Quality) || ...
            ~all(isfield(Config.Quality, ...
                {'StartupTransient', 'Statistical', 'SuddenChange', ...
                 'Physical'}))

        error( ...
            ['Preprocessing:ValidatePreprocessingConfig:', ...
             'InvalidQuality'], ...
            ['Config.Quality must be a scalar structure with ', ...
             'StartupTransient, Statistical, SuddenChange and Physical ', ...
             'fields.']);

    end

    Transient = Config.Quality.StartupTransient;

    if ~isScalarStructWith(Transient, {'Enabled', 'WindowSamples'}) || ...
            ~isLogicalScalar(Transient.Enabled) || ...
            ~isNonnegIntegerScalar(Transient.WindowSamples)

        error( ...
            ['Preprocessing:ValidatePreprocessingConfig:', ...
             'InvalidStartupTransient'], ...
            ['Config.Quality.StartupTransient must have a logical ', ...
             'Enabled flag and a nonnegative integer WindowSamples.']);

    end

    Statistical = Config.Quality.Statistical;

    if ~isScalarStructWith(Statistical, ...
            {'Enabled', 'WindowSamples', 'SigmaThreshold', ...
             'DeviationFloor'}) || ...
            ~isLogicalScalar(Statistical.Enabled) || ...
            ~(isIntegerScalar(Statistical.WindowSamples) && ...
                Statistical.WindowSamples >= 3) || ...
            ~isPositiveFiniteScalar(Statistical.SigmaThreshold) || ...
            ~isNonnegFiniteScalar(Statistical.DeviationFloor)

        error( ...
            ['Preprocessing:ValidatePreprocessingConfig:', ...
             'InvalidStatistical'], ...
            ['Config.Quality.Statistical must have a logical Enabled ', ...
             'flag, an integer WindowSamples >= 3, a positive finite ', ...
             'SigmaThreshold and a nonnegative finite DeviationFloor.']);

    end

    SuddenChange = Config.Quality.SuddenChange;

    if ~isScalarStructWith(SuddenChange, {'Enabled', 'Thresholds'}) || ...
            ~isLogicalScalar(SuddenChange.Enabled) || ...
            ~isScalarStruct(SuddenChange.Thresholds)

        error( ...
            ['Preprocessing:ValidatePreprocessingConfig:', ...
             'InvalidSuddenChange'], ...
            ['Config.Quality.SuddenChange must have a logical Enabled ', ...
             'flag and a scalar structure Thresholds.']);

    end

    if ~isScalarStructWith(Config.Quality.Physical, {'Bounds'}) || ...
            ~isScalarStruct(Config.Quality.Physical.Bounds)

        error( ...
            ['Preprocessing:ValidatePreprocessingConfig:', ...
             'InvalidPhysicalBounds'], ...
            ['Config.Quality.Physical must contain a scalar structure ', ...
             'Bounds.']);

    end

    BoundNames = fieldnames(Config.Quality.Physical.Bounds);

    for Index = 1:numel(BoundNames)

        BoundName = BoundNames{Index};
        BoundValue = Config.Quality.Physical.Bounds.(BoundName);

        if ~ismember(BoundName, MeasurementFields)

            error( ...
                ['Preprocessing:ValidatePreprocessingConfig:', ...
                 'InvalidPhysicalBoundField'], ...
                ['Physical bound field "%s" is not a canonical ', ...
                 'measurement field.'], ...
                BoundName);

        end

        if ~(isnumeric(BoundValue) && isreal(BoundValue) && ...
                isequal(size(BoundValue), [1, 2]) && ...
                all(isfinite(BoundValue)) && BoundValue(1) < BoundValue(2))

            error( ...
                ['Preprocessing:ValidatePreprocessingConfig:', ...
                 'InvalidPhysicalBounds'], ...
                ['Physical bound for "%s" must be a finite [min max] ', ...
                 'pair with min < max.'], ...
                BoundName);

        end

    end

    %% Validate Alignment Settings

    if ~isScalarStructWith(Config.Alignment, ...
            {'Enabled', 'ReferenceStream', 'MaxSampleAge_s'}) || ...
            ~isLogicalScalar(Config.Alignment.Enabled)

        error( ...
            'Preprocessing:ValidatePreprocessingConfig:InvalidAlignment', ...
            ['Config.Alignment must have a logical Enabled flag, a ', ...
             'ReferenceStream and a MaxSampleAge_s structure.']);

    end

    if ~(isTextScalar(Config.Alignment.ReferenceStream) && ...
            any(strcmpi(char(Config.Alignment.ReferenceStream), ...
                CanonicalStreams)))

        error( ...
            ['Preprocessing:ValidatePreprocessingConfig:', ...
             'InvalidReferenceStream'], ...
            'Config.Alignment.ReferenceStream must be a canonical stream name.');

    end

    if ~isScalarStruct(Config.Alignment.MaxSampleAge_s)

        error( ...
            ['Preprocessing:ValidatePreprocessingConfig:', ...
             'InvalidMaxSampleAge'], ...
            'Config.Alignment.MaxSampleAge_s must be a scalar structure.');

    end

    AgeNames = fieldnames(Config.Alignment.MaxSampleAge_s);

    for Index = 1:numel(AgeNames)

        AgeName = AgeNames{Index};
        AgeValue = Config.Alignment.MaxSampleAge_s.(AgeName);

        if ~ismember(AgeName, CanonicalStreams) || ...
                ~isPositiveFiniteScalar(AgeValue)

            error( ...
                ['Preprocessing:ValidatePreprocessingConfig:', ...
                 'InvalidMaxSampleAge'], ...
                ['Config.Alignment.MaxSampleAge_s entries must map ', ...
                 'canonical stream names to positive finite scalars.']);

        end

    end

end

% =========================================================================
%% LOCAL HELPERS
% =========================================================================

function Result = isTextScalar(Value)
%ISTEXTSCALAR True for a character vector or scalar string.

    Result = ischar(Value) && isrow(Value) || ...
        (isstring(Value) && isscalar(Value));

end

function Result = isLogicalScalar(Value)
%ISLOGICALSCALAR True for a logical scalar.

    Result = islogical(Value) && isscalar(Value);

end

function Result = isIntegerScalar(Value)
%ISINTEGERSCALAR True for a finite integer-valued real scalar.

    Result = isnumeric(Value) && isreal(Value) && isscalar(Value) && ...
        isfinite(Value) && Value == floor(Value);

end

function Result = isNonnegIntegerScalar(Value)
%ISNONNEGINTEGERSCALAR True for a nonnegative integer scalar.

    Result = isIntegerScalar(Value) && Value >= 0;

end

function Result = isPositiveFiniteScalar(Value)
%ISPOSITIVEFINITESCALAR True for a positive finite real scalar.

    Result = isnumeric(Value) && isreal(Value) && isscalar(Value) && ...
        isfinite(Value) && Value > 0;

end

function Result = isNonnegFiniteScalar(Value)
%ISNONNEGINITESCALAR True for a nonnegative finite real scalar.

    Result = isnumeric(Value) && isreal(Value) && isscalar(Value) && ...
        isfinite(Value) && Value >= 0;

end

function Result = isScalarStruct(Value)
%ISSCALARSTRUCT True for a scalar structure.

    Result = isstruct(Value) && isscalar(Value);

end

function Result = isScalarStructWith(Value, RequiredFields)
%ISSCALARSTRUCTWITH True for a scalar structure with the given fields.

    Result = isScalarStruct(Value) && ...
        all(isfield(Value, RequiredFields));

end

function Result = isDisabledCriterion(Value)
%ISDISABLEDCRITERION True for [] (the disabled-criterion marker).

    Result = (isnumeric(Value) || islogical(Value)) && isempty(Value);

end

function Names = measurementFieldNames(Contracts)
%MEASUREMENTFIELDNAMES Canonical measurement field names (audit excluded).

    PerStream = cell(1, numel(Contracts.Streams));

    for Index = 1:numel(Contracts.Streams)

        Stream = Contracts.(Contracts.Streams{Index});
        PerStream{Index} = {Stream.Channels.CanonicalField};

    end

    AllNames = [PerStream{:}];
    Names = AllNames(~ismember(AllNames, {'Time_s', 'Available'}));

end
