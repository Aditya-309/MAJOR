function OutputPaths = WriteIdealSensorTelemetry(IdealSensorTelemetry, IdealSensorDirectory)
% WriteIdealSensorTelemetry
%
% Production persistence layer for frozen Block 4 IdealSensorTelemetry.
%
% Inputs:
%   IdealSensorTelemetry  - Frozen Block 4 ideal sensor telemetry
%   IdealSensorDirectory  - Production run IdealSensorTelemetry directory
%
% Outputs:
%   OutputPaths            - Paths to persisted MAT/CSV telemetry files
%
% This function does not:
%   - generate sensor data
%   - modify sensor data
%   - apply noise
%   - apply corruption
%   - alter timelines
%   - modify GroundTruth
%
% It only persists the already-generated frozen Block 4 output.

%% Validate inputs

if nargin ~= 2
    error('WriteIdealSensorTelemetry:InputCount', ...
        'Exactly two inputs are required.');
end

if ~isstruct(IdealSensorTelemetry) || ...
        ~isscalar(IdealSensorTelemetry)
    error('WriteIdealSensorTelemetry:InvalidTelemetry', ...
        'IdealSensorTelemetry must be a scalar structure.');
end

if ~(ischar(IdealSensorDirectory) || ...
        (isstring(IdealSensorDirectory) && isscalar(IdealSensorDirectory)))
    error('WriteIdealSensorTelemetry:InvalidDirectory', ...
        'IdealSensorDirectory must be a character vector or scalar string.');
end

IdealSensorDirectory = char(IdealSensorDirectory);

RequiredSensors = { ...
    'GNSS', ...
    'IMU', ...
    'AirData', ...
    'Magnetometer'};

for k = 1:numel(RequiredSensors)

    SensorName = RequiredSensors{k};

    if ~isfield(IdealSensorTelemetry, SensorName)
        error('WriteIdealSensorTelemetry:MissingSensor', ...
            'IdealSensorTelemetry.%s is missing.', SensorName);
    end

    Sensor = IdealSensorTelemetry.(SensorName);

    if ~isstruct(Sensor) || ~isscalar(Sensor)
        error('WriteIdealSensorTelemetry:InvalidSensor', ...
            'IdealSensorTelemetry.%s must be a scalar structure.', ...
            SensorName);
    end

    RequiredFields = { ...
        'Time_s', ...
        'SampleRate_Hz', ...
        'SampleCount'};

    for j = 1:numel(RequiredFields)

        FieldName = RequiredFields{j};

        if ~isfield(Sensor, FieldName)
            error('WriteIdealSensorTelemetry:MissingField', ...
                'IdealSensorTelemetry.%s.%s is missing.', ...
                SensorName, FieldName);
        end
    end

    Time = Sensor.Time_s(:);
    SampleCount = Sensor.SampleCount;

    if ~isnumeric(Time) || isempty(Time) || ...
            any(~isfinite(Time))
        error('WriteIdealSensorTelemetry:InvalidTime', ...
            'IdealSensorTelemetry.%s.Time_s must contain finite values.', ...
            SensorName);
    end

    if ~isscalar(SampleCount) || ...
            ~isnumeric(SampleCount) || ...
            ~isfinite(SampleCount) || ...
            SampleCount < 1 || ...
            SampleCount ~= floor(SampleCount)
        error('WriteIdealSensorTelemetry:InvalidSampleCount', ...
            'IdealSensorTelemetry.%s.SampleCount must be a positive integer.', ...
            SensorName);
    end

    if numel(Time) ~= SampleCount
        error('WriteIdealSensorTelemetry:SampleCountMismatch', ...
            'IdealSensorTelemetry.%s Time_s length does not match SampleCount.', ...
            SensorName);
    end

    if numel(Time) > 1 && any(diff(Time) <= 0)
        error('WriteIdealSensorTelemetry:InvalidTimeOrder', ...
            'IdealSensorTelemetry.%s.Time_s must be strictly increasing.', ...
            SensorName);
    end

    SampleRate = Sensor.SampleRate_Hz;

    if ~isscalar(SampleRate) || ...
            ~isnumeric(SampleRate) || ...
            ~isfinite(SampleRate) || ...
            SampleRate <= 0
        error('WriteIdealSensorTelemetry:InvalidSampleRate', ...
            'IdealSensorTelemetry.%s.SampleRate_Hz must be positive and finite.', ...
            SensorName);
    end
end

%% Validate sensor-specific fields

GNSSFields = { ...
    'Latitude_rad', ...
    'Longitude_rad', ...
    'Altitude_m', ...
    'Velocity_NED_mps', ...
    'Available'};

IMUFields = { ...
    'Accelerometer_mps2', ...
    'Gyroscope_radps', ...
    'Available'};

AirDataFields = { ...
    'TrueAirspeed_mps', ...
    'DynamicPressure_Pa', ...
    'Available'};

MagnetometerFields = { ...
    'MagneticFieldBody_uT', ...
    'Available'};

SensorSpecificFields = { ...
    'GNSS', GNSSFields; ...
    'IMU', IMUFields; ...
    'AirData', AirDataFields; ...
    'Magnetometer', MagnetometerFields};

for k = 1:size(SensorSpecificFields,1)

    SensorName = SensorSpecificFields{k,1};
    Fields = SensorSpecificFields{k,2};

    Sensor = IdealSensorTelemetry.(SensorName);

    for j = 1:numel(Fields)

        FieldName = Fields{j};

        if ~isfield(Sensor, FieldName)
            error('WriteIdealSensorTelemetry:MissingField', ...
                'IdealSensorTelemetry.%s.%s is missing.', ...
                SensorName, FieldName);
        end
    end
end

%% Validate dimensions of vector/matrix telemetry

N_GNSS = IdealSensorTelemetry.GNSS.SampleCount;
N_IMU = IdealSensorTelemetry.IMU.SampleCount;
N_AirData = IdealSensorTelemetry.AirData.SampleCount;
N_Magnetometer = IdealSensorTelemetry.Magnetometer.SampleCount;

if ~isequal(size(IdealSensorTelemetry.GNSS.Velocity_NED_mps), ...
            [N_GNSS, 3])
    error('WriteIdealSensorTelemetry:InvalidGNSSVelocity', ...
        'GNSS.Velocity_NED_mps must be SampleCount-by-3.');
end

if ~isequal(size(IdealSensorTelemetry.IMU.Accelerometer_mps2), ...
            [N_IMU, 3])
    error('WriteIdealSensorTelemetry:InvalidIMUAcceleration', ...
        'IMU.Accelerometer_mps2 must be SampleCount-by-3.');
end

if ~isequal(size(IdealSensorTelemetry.IMU.Gyroscope_radps), ...
            [N_IMU, 3])
    error('WriteIdealSensorTelemetry:InvalidIMUGyroscope', ...
        'IMU.Gyroscope_radps must be SampleCount-by-3.');
end

if ~isequal(size(IdealSensorTelemetry.Magnetometer.MagneticFieldBody_uT), ...
            [N_Magnetometer, 3])
    error('WriteIdealSensorTelemetry:InvalidMagnetometer', ...
        'Magnetometer.MagneticFieldBody_uT must be SampleCount-by-3.');
end

%% Create output directory

if ~isfolder(IdealSensorDirectory)
    mkdir(IdealSensorDirectory);
end

%% Define output paths

OutputPaths = struct();

OutputPaths.IdealSensorTelemetryMAT = ...
    fullfile(IdealSensorDirectory, ...
    'IdealSensorTelemetry.mat');

OutputPaths.GNSSCSV = ...
    fullfile(IdealSensorDirectory, ...
    'GNSS.csv');

OutputPaths.IMUCSV = ...
    fullfile(IdealSensorDirectory, ...
    'IMU.csv');

OutputPaths.AirDataCSV = ...
    fullfile(IdealSensorDirectory, ...
    'AirData.csv');

OutputPaths.MagnetometerCSV = ...
    fullfile(IdealSensorDirectory, ...
    'Magnetometer.csv');

%% Persist exact MATLAB structure

IdealSensorTelemetryToSave = IdealSensorTelemetry; %#ok<NASGU>

save(OutputPaths.IdealSensorTelemetryMAT, ...
    'IdealSensorTelemetryToSave', ...
    '-v7.3');

%% GNSS CSV

GNSS = IdealSensorTelemetry.GNSS;

GNSSTable = table( ...
    GNSS.Time_s(:), ...
    GNSS.Latitude_rad(:), ...
    GNSS.Longitude_rad(:), ...
    GNSS.Altitude_m(:), ...
    GNSS.Velocity_NED_mps(:,1), ...
    GNSS.Velocity_NED_mps(:,2), ...
    GNSS.Velocity_NED_mps(:,3), ...
    'VariableNames', { ...
    'Time_s', ...
    'Latitude_rad', ...
    'Longitude_rad', ...
    'Altitude_m', ...
    'Velocity_North_mps', ...
    'Velocity_East_mps', ...
    'Velocity_Down_mps'});

writetable(GNSSTable, OutputPaths.GNSSCSV);

%% IMU CSV

IMU = IdealSensorTelemetry.IMU;

IMUTable = table( ...
    IMU.Time_s(:), ...
    IMU.Accelerometer_mps2(:,1), ...
    IMU.Accelerometer_mps2(:,2), ...
    IMU.Accelerometer_mps2(:,3), ...
    IMU.Gyroscope_radps(:,1), ...
    IMU.Gyroscope_radps(:,2), ...
    IMU.Gyroscope_radps(:,3), ...
    'VariableNames', { ...
    'Time_s', ...
    'Accelerometer_X_mps2', ...
    'Accelerometer_Y_mps2', ...
    'Accelerometer_Z_mps2', ...
    'Gyroscope_X_radps', ...
    'Gyroscope_Y_radps', ...
    'Gyroscope_Z_radps'});

writetable(IMUTable, OutputPaths.IMUCSV);

%% AirData CSV

AirData = IdealSensorTelemetry.AirData;

AirDataTable = table( ...
    AirData.Time_s(:), ...
    AirData.TrueAirspeed_mps(:), ...
    AirData.DynamicPressure_Pa(:), ...
    'VariableNames', { ...
    'Time_s', ...
    'TrueAirspeed_mps', ...
    'DynamicPressure_Pa'});

writetable(AirDataTable, OutputPaths.AirDataCSV);

%% Magnetometer CSV

Magnetometer = IdealSensorTelemetry.Magnetometer;

MagnetometerTable = table( ...
    Magnetometer.Time_s(:), ...
    Magnetometer.MagneticFieldBody_uT(:,1), ...
    Magnetometer.MagneticFieldBody_uT(:,2), ...
    Magnetometer.MagneticFieldBody_uT(:,3), ...
    'VariableNames', { ...
    'Time_s', ...
    'MagneticFieldBody_X_uT', ...
    'MagneticFieldBody_Y_uT', ...
    'MagneticFieldBody_Z_uT'});

writetable(MagnetometerTable, ...
    OutputPaths.MagnetometerCSV);

%% Verify all files exist and are non-empty

OutputFileFields = fieldnames(OutputPaths);

for k = 1:numel(OutputFileFields)

    FilePath = OutputPaths.(OutputFileFields{k});

    if ~isfile(FilePath)
        error('WriteIdealSensorTelemetry:WriteFailure', ...
            'Expected output file was not created: %s', ...
            FilePath);
    end

    FileInfo = dir(FilePath);

    if isempty(FileInfo) || FileInfo.bytes <= 0
        error('WriteIdealSensorTelemetry:EmptyFile', ...
            'Output file is empty: %s', ...
            FilePath);
    end
end

end