function OutputPath = WriteRunMetadata( ...
    ProductionConfig, ...
    RunContext, ...
    RunResult, ...
    ValidationResult)
% WriteRunMetadata
%
% Production persistence layer for run-level metadata.
%
% Inputs:
%   ProductionConfig - Frozen production configuration
%   RunContext       - Production working-run context
%   RunResult        - Executed production result
%   ValidationResult - Passed production validation result
%
% Output:
%   OutputPath       - Full path to RunMetadata.json
%
% This function only persists run metadata. It does not modify:
%   - Block 1-8 source code
%   - GroundTruth
%   - IdealSensorTelemetry
%   - RealisticSensorTelemetry
%   - production run identity

%% Validate input count

if nargin ~= 4
    error('WriteRunMetadata:InputCount', ...
        'Exactly four inputs are required.');
end

%% Validate ProductionConfig

if ~isstruct(ProductionConfig) || ...
        ~isscalar(ProductionConfig)
    error('WriteRunMetadata:InvalidProductionConfig', ...
        'ProductionConfig must be a scalar structure.');
end

RequiredProductionFields = { ...
    'ProjectRoot', ...
    'ProductionRoot', ...
    'RunsRoot', ...
    'WorkingRunsRoot', ...
    'FailedRunsRoot', ...
    'RegistryFile', ...
    'ScenarioSelector', ...
    'ScenarioID', ...
    'ScenarioName', ...
    'ScenarioConfigPath'};

for k = 1:numel(RequiredProductionFields)

    FieldName = RequiredProductionFields{k};

    if ~isfield(ProductionConfig, FieldName)
        error('WriteRunMetadata:MissingProductionField', ...
            'ProductionConfig.%s is missing.', FieldName);
    end
end

%% Validate RunContext

if ~isstruct(RunContext) || ...
        ~isscalar(RunContext)
    error('WriteRunMetadata:InvalidRunContext', ...
        'RunContext must be a scalar structure.');
end

RequiredRunFields = { ...
    'RunID', ...
    'Status', ...
    'CreatedAt', ...
    'WorkingRunDirectory', ...
    'FinalRunDirectory', ...
    'FailedRunDirectory', ...
    'Block7Directory', ...
    'GroundTruthDirectory', ...
    'IdealSensorDirectory', ...
    'RealisticSensorDirectory', ...
    'ScenarioSelector', ...
    'ScenarioID', ...
    'ScenarioName'};

for k = 1:numel(RequiredRunFields)

    FieldName = RequiredRunFields{k};

    if ~isfield(RunContext, FieldName)
        error('WriteRunMetadata:MissingRunField', ...
            'RunContext.%s is missing.', FieldName);
    end
end

if ~strcmp(RunContext.Status, 'WORKING')
    error('WriteRunMetadata:InvalidRunStatus', ...
        'RunContext.Status must be WORKING.');
end

%% Validate RunResult

if ~isstruct(RunResult) || ...
        ~isscalar(RunResult)
    error('WriteRunMetadata:InvalidRunResult', ...
        'RunResult must be a scalar structure.');
end

RequiredResultFields = { ...
    'RunID', ...
    'Status', ...
    'Scenario', ...
    'Timeline', ...
    'GroundTruth', ...
    'IdealSensorTelemetry', ...
    'RealisticSensorTelemetry'};

for k = 1:numel(RequiredResultFields)

    FieldName = RequiredResultFields{k};

    if ~isfield(RunResult, FieldName)
        error('WriteRunMetadata:MissingResultField', ...
            'RunResult.%s is missing.', FieldName);
    end
end

if ~strcmp(RunResult.Status, 'EXECUTED')
    error('WriteRunMetadata:InvalidResultStatus', ...
        'RunResult.Status must be EXECUTED.');
end

%% Validate ValidationResult

if ~isstruct(ValidationResult) || ...
        ~isscalar(ValidationResult)
    error('WriteRunMetadata:InvalidValidationResult', ...
        'ValidationResult must be a scalar structure.');
end

RequiredValidationFields = { ...
    'Status', ...
    'RunID', ...
    'ScenarioID', ...
    'ScenarioName', ...
    'TimelineSampleCount', ...
    'GroundTruthSampleCount', ...
    'GNSSSampleCount', ...
    'IMUSampleCount', ...
    'AirDataSampleCount', ...
    'MagnetometerSampleCount', ...
    'Block7ArtifactCount', ...
    'ValidatedAt'};

for k = 1:numel(RequiredValidationFields)

    FieldName = RequiredValidationFields{k};

    if ~isfield(ValidationResult, FieldName)
        error('WriteRunMetadata:MissingValidationField', ...
            'ValidationResult.%s is missing.', FieldName);
    end
end

if ~strcmp(ValidationResult.Status, 'PASSED')
    error('WriteRunMetadata:ValidationNotPassed', ...
        'ValidationResult.Status must be PASSED.');
end

%% Cross-check run identity

if ~strcmp(RunContext.RunID, RunResult.RunID)
    error('WriteRunMetadata:RunIDMismatch', ...
        'RunContext.RunID and RunResult.RunID do not match.');
end

if ~strcmp(RunContext.RunID, ValidationResult.RunID)
    error('WriteRunMetadata:ValidationRunIDMismatch', ...
        'RunContext.RunID and ValidationResult.RunID do not match.');
end

if ~isequaln( ...
        RunContext.ScenarioSelector, ...
        ProductionConfig.ScenarioSelector)
    error('WriteRunMetadata:ScenarioSelectorMismatch', ...
        'RunContext scenario selector does not match ProductionConfig.');
end

if ~isequaln( ...
        RunContext.ScenarioID, ...
        ProductionConfig.ScenarioID)
    error('WriteRunMetadata:ScenarioIDMismatch', ...
        'RunContext scenario ID does not match ProductionConfig.');
end

if ~strcmp( ...
        RunContext.ScenarioName, ...
        ProductionConfig.ScenarioName)
    error('WriteRunMetadata:ScenarioNameMismatch', ...
        'RunContext scenario name does not match ProductionConfig.');
end

if ~isequaln( ...
        RunResult.Scenario.ID, ...
        ProductionConfig.ScenarioID)
    error('WriteRunMetadata:ResultScenarioMismatch', ...
        'RunResult scenario ID does not match ProductionConfig.');
end

if ~strcmp( ...
        RunResult.Scenario.Name, ...
        ProductionConfig.ScenarioName)
    error('WriteRunMetadata:ResultScenarioNameMismatch', ...
        'RunResult scenario name does not match ProductionConfig.');
end

if ~isequaln( ...
        ValidationResult.ScenarioID, ...
        ProductionConfig.ScenarioID)
    error('WriteRunMetadata:ValidationScenarioMismatch', ...
        'Validation scenario ID does not match ProductionConfig.');
end

if ~strcmp( ...
        ValidationResult.ScenarioName, ...
        ProductionConfig.ScenarioName)
    error('WriteRunMetadata:ValidationScenarioNameMismatch', ...
        'Validation scenario name does not match ProductionConfig.');
end

%% Validate working directory

if ~isfolder(RunContext.WorkingRunDirectory)
    error('WriteRunMetadata:MissingWorkingDirectory', ...
        'Working run directory does not exist.');
end

%% Build metadata

Metadata = struct();

Metadata.Run = struct();
Metadata.Run.RunID = RunContext.RunID;
Metadata.Run.Status = RunResult.Status;
Metadata.Run.CreatedAt = char(RunContext.CreatedAt);
Metadata.Run.MetadataWrittenAt = char(datetime( ...
    'now', ...
    'Format', 'yyyy-MM-dd''T''HH:mm:ss.SSS'));

Metadata.Project = struct();
Metadata.Project.ProjectRoot = ProductionConfig.ProjectRoot;
Metadata.Project.ProductionRoot = ProductionConfig.ProductionRoot;

Metadata.Scenario = struct();
Metadata.Scenario.Selector = ProductionConfig.ScenarioSelector;
Metadata.Scenario.ID = ProductionConfig.ScenarioID;
Metadata.Scenario.Name = ProductionConfig.ScenarioName;

Metadata.Configuration = struct();
Metadata.Configuration.ScenarioConfigPath = ...
    ProductionConfig.ScenarioConfigPath;

Metadata.Paths = struct();
Metadata.Paths.WorkingRunDirectory = ...
    RunContext.WorkingRunDirectory;
Metadata.Paths.Block7Directory = ...
    RunContext.Block7Directory;
Metadata.Paths.GroundTruthDirectory = ...
    RunContext.GroundTruthDirectory;
Metadata.Paths.IdealSensorDirectory = ...
    RunContext.IdealSensorDirectory;
Metadata.Paths.RealisticSensorDirectory = ...
    RunContext.RealisticSensorDirectory;

Metadata.Validation = struct();
Metadata.Validation.Status = ValidationResult.Status;
Metadata.Validation.ValidatedAt = ...
    char(ValidationResult.ValidatedAt);
Metadata.Validation.TimelineSampleCount = ...
    ValidationResult.TimelineSampleCount;
Metadata.Validation.GroundTruthSampleCount = ...
    ValidationResult.GroundTruthSampleCount;
Metadata.Validation.GNSSSampleCount = ...
    ValidationResult.GNSSSampleCount;
Metadata.Validation.IMUSampleCount = ...
    ValidationResult.IMUSampleCount;
Metadata.Validation.AirDataSampleCount = ...
    ValidationResult.AirDataSampleCount;
Metadata.Validation.MagnetometerSampleCount = ...
    ValidationResult.MagnetometerSampleCount;
Metadata.Validation.Block7ArtifactCount = ...
    ValidationResult.Block7ArtifactCount;

Metadata.Telemetry = struct();
Metadata.Telemetry.GroundTruthSampleCount = ...
    RunResult.GroundTruth.SampleCount;
Metadata.Telemetry.GNSSSampleCount = ...
    RunResult.IdealSensorTelemetry.GNSS.SampleCount;
Metadata.Telemetry.IMUSampleCount = ...
    RunResult.IdealSensorTelemetry.IMU.SampleCount;
Metadata.Telemetry.AirDataSampleCount = ...
    RunResult.IdealSensorTelemetry.AirData.SampleCount;
Metadata.Telemetry.MagnetometerSampleCount = ...
    RunResult.IdealSensorTelemetry.Magnetometer.SampleCount;

%% Output path

OutputPath = fullfile( ...
    RunContext.WorkingRunDirectory, ...
    'RunMetadata.json');

%% Encode JSON

try
    JSONText = jsonencode( ...
        Metadata, ...
        'PrettyPrint', true);
catch ME
    error('WriteRunMetadata:JSONEncodeFailure', ...
        'Failed to encode RunMetadata as JSON: %s', ...
        ME.message);
end

%% Write JSON

FileID = fopen(OutputPath, 'w');

if FileID == -1
    error('WriteRunMetadata:FileOpenFailure', ...
        'Could not open RunMetadata.json for writing.');
end

CleanupObject = onCleanup(@() fclose(FileID));

Count = fwrite(FileID, JSONText, 'char');

if Count ~= numel(JSONText)
    error('WriteRunMetadata:WriteFailure', ...
        'RunMetadata.json was not completely written.');
end

clear CleanupObject;

%% Verify output

if ~isfile(OutputPath)
    error('WriteRunMetadata:MissingOutput', ...
        'RunMetadata.json was not created.');
end

FileInfo = dir(OutputPath);

if isempty(FileInfo) || FileInfo.bytes <= 0
    error('WriteRunMetadata:EmptyOutput', ...
        'RunMetadata.json is empty.');
end

end